#!/bin/sh
#
# tests/core-boundary/intrinsics-board.sh — decision 0022 §1's word intrinsics, run on the FRDM-IMXRT1186.
#
#   LLVM_PREFIX=... ZEPHYR_BASE=... ZEPHYR_SDK_INSTALL_DIR=... [KERNEL=...] [SPINEL_TYPEDUMP=...] \
#     [RT1186_HOST=user@host RT1186_PROBE=... RT1186_TTY=... RT1186_OWNER=...] \
#     sh tests/core-boundary/intrinsics-board.sh [DIR]
#
# The 32-bit cases of fixtures/intrinsics/cases.tsv, which tests/core-boundary/
# intrinsics.sh cannot run on a 64-bit host: a 32-bit body needs a 32-bit
# target (decision 0019). Each case's entry is built by the kernel for
# thumbv8m.main with a 32-bit body and an i32 boundary, and a small Zephyr
# program (DIR/app, generated here) calls every case once and prints
# `C <id> <status> <value>` with printk, then `INTRINSICS END`. A failed case
# must leave the result word untouched, which the program checks.
#
# The program is written and read through the board lane's harness
# (tests/doom-core/harness/rt1186-host.sh): the board's lock first, the
# identifying read, the write at 0x14000000, the console from the lane's own
# reset until the end line. Without RT1186_HOST the build parts run and the
# board part is a named skip.
set -u
ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/../.." && pwd)
# DIR keeps what the run built; without one a temporary directory is used
# and removed at the end
if [ -n "${1:-}" ]; then DIR=$1; else DIR=$(mktemp -d "${TMPDIR:-/tmp}/core-intrinsics-board.XXXXXX"); OWN_DIR=1; trap 'rm -rf "$DIR"' EXIT; fi
FIX=$ROOT/tests/core-boundary/fixtures/intrinsics
KERNEL=${KERNEL:-$ROOT/tools/mlir/native/build/bin/spinel-core-kernel}
READER=${SPINEL_TYPEDUMP:-$ROOT/tools/contract/build/spinel-typedump}
. "${ROOT:-$root}/tools/test/source-stamp.sh"
source_stamp kernel "$KERNEL"
source_stamp reader "$READER"
LLVM=${LLVM_PREFIX:-/opt/llvm-23.1.1}
CC_BIN=${CLANG:-$LLVM/bin/clang}
RUBY=${RUBY:-ruby}
THUMB="--target=thumbv8m.main-none-eabi -mcpu=cortex-m33+nodsp -mfloat-abi=soft -mthumb -Os -ffreestanding"
pass=0; fail=0; skip=0
ok() { if [ "$2" = "$3" ]; then echo "  pass $1"; pass=$((pass + 1));
       else echo "  FAIL $1 (got '$2', want '$3')"; fail=$((fail + 1)); fi; }
summary() { echo "intrinsics-board: $((pass + fail)) checked, $pass pass, $fail fail, $skip skipped; $(( $(date +%s) - T0 )) s"; [ "$fail" = 0 ]; exit $?; }
T0=$(date +%s)
for v in ZEPHYR_BASE ZEPHYR_SDK_INSTALL_DIR; do eval "[ -n \"\${$v:-}\" ]" || { echo "intrinsics-board: $v is required to build the board's program"; exit 2; }; done
command -v west > /dev/null 2>&1 || { echo "intrinsics-board: west is not on PATH"; exit 2; }
[ -x "$KERNEL" ] && [ -x "$READER" ] || { echo "intrinsics-board: no kernel or reader" >&2; exit 2; }
rm -rf "$DIR/obj" "$DIR/app" "$DIR/build"; mkdir -p "$DIR/obj" "$DIR/app/src"

params_of() { "$RUBY" -e 'm = File.read(ARGV[0])[/^def #{ARGV[1]}\(([^)]*)\)/, 1] or abort; puts m.split(/,\s*/)' "$FIX/src/words.rb" "$1"; }
rows=$(grep -v '^#' "$FIX/cases.tsv" | awk -F'\t' '$2 == 32')

echo "intrinsics-board: 1. the 32-bit entries, built for thumbv8m.main"
for e in $(printf '%s\n' "$rows" | cut -f3 | sort -u); do
  { echo "core-contract 1"; echo "root src/words.rb"; echo "entry $e"; echo "result i32"
    for p in $(params_of "$e"); do echo "param $p scalar i32"; done; } > "$DIR/obj/$e.contract"
  # shellcheck disable=SC2086
  "$KERNEL" "$DIR/obj/$e.contract" --root "$FIX" --typedump "$READER" -o "$DIR/obj/$e.o" --header "$DIR/obj/$e.h" \
    --layout ptr32-i64-32long --int-width=32 --clang "$CC_BIN" -- $THUMB > "$DIR/obj/$e.out" 2>&1
  ok "$e builds" "$?" 0
done

echo "intrinsics-board: 2. the program that calls every case, built for frdm_imxrt1186"
"$RUBY" -e '
  rows = File.readlines(ARGV[0], chomp: true).reject { |l| l.start_with?("#") || l.strip.empty? }.map { |l| l.split("\t") }.select { |r| r[1] == "32" }
  entries = rows.map { |r| r[2] }.uniq
  out = +"/* generated by tests/core-boundary/intrinsics-board.sh: every 32-bit case of\n * fixtures/intrinsics/cases.tsv, called once, its status and value printed */\n"
  out << "#include <stdint.h>\n#include <zephyr/kernel.h>\n#include <zephyr/sys/printk.h>\n"
  entries.each { |e| out << "#include \"#{e}.h\"\n" }
  out << "\nstatic const int32_t sentinel = -123456789;\n\nint main(void)\n{\n\tint32_t r, st;\n\n\tk_msleep(100);\n\tprintk(\"INTRINSICS BEGIN\\n\");\n"
  rows.each do |id, _w, e, args, _s, _v|
    a = args.split(",").map { |x| "(int32_t)#{Integer(x)}" }.join(", ")
    out << "\tr = sentinel;\n\tst = spinel_core_#{e}(#{a}, &r);\n"
    out << "\tif (st != 0) printk(\"C #{id} %d %s\\n\", (int)st, r == sentinel ? \"untouched\" : \"TOUCHED\");\n"
    out << "\telse printk(\"C #{id} 0 %d\\n\", (int)r);\n"
  end
  out << "\tprintk(\"INTRINSICS END\\n\");\n\treturn 0;\n}\n"
  File.write(ARGV[1], out)' "$FIX/cases.tsv" "$DIR/app/src/main.c"
cat > "$DIR/app/CMakeLists.txt" <<EOF
cmake_minimum_required(VERSION 3.20.0)
find_package(Zephyr REQUIRED HINTS \$ENV{ZEPHYR_BASE})
project(core_intrinsics)
target_sources(app PRIVATE src/main.c)
target_include_directories(app PRIVATE $DIR/obj)
file(GLOB SPC_OBJS $DIR/obj/*.o)
target_sources(app PRIVATE \${SPC_OBJS})
EOF
printf 'CONFIG_PRINTK=y\n' > "$DIR/app/prj.conf"
( cd "$DIR" && west build -p always -b frdm_imxrt1186/mimxrt1186/cm33 "$DIR/app" -d "$DIR/build" -- \
    -DZEPHYR_SDK_INSTALL_DIR="$ZEPHYR_SDK_INSTALL_DIR" > "$DIR/build.out" 2>&1 )
ok "the program builds" "$?|$([ -f "$DIR/build/zephyr/zephyr.bin" ] && echo bin)" "0|bin"
ok "  and its first loaded byte is the flash base, the FlexSPI configuration block at 0x400" \
   "$(od -A n -c -j 1024 -N 4 "$DIR/build/zephyr/zephyr.bin" 2>/dev/null | tr -d ' ')" FCFB

echo "intrinsics-board: 3. on the board"
RT1186_RES=$DIR/board; mkdir -p "$RT1186_RES"
# shellcheck source=tests/doom-core/harness/rt1186-host.sh
. "$ROOT/tests/doom-core/harness/rt1186-host.sh"
RT1186_TIMEOUT=${RT1186_TIMEOUT_INTRINSICS:-120}
if [ -z "${RT1186_HOST:-}" ]; then
  echo "  SKIP the board part: RT1186_HOST is not set"; skip=1; summary
fi
rt_lock > "$RT1186_RES/lock.txt" 2>&1; lrc=$?
if [ "$lrc" = 1 ]; then ok "the board is free" "$(head -1 "$RT1186_RES/lock.txt")" taken; summary; fi
if [ "$lrc" = 2 ]; then echo "  SKIP the board part: $(cat "$RT1186_RES/lock.txt")"; skip=1; summary; fi
why=$(rt_ready) || { echo "  SKIP the board part: $why"; skip=1; summary; }
rt_open || exit 1
# rt_lock and rt_open set the EXIT trap to their cleanup; a temporary DIR goes too
[ -n "${OWN_DIR:-}" ] && trap 'rt_cleanup; rm -rf "$DIR"' EXIT
rt_flash intrinsics "$DIR/build/zephyr/zephyr.bin"
ok "the program is written" "$?|$(grep -ciE 'finished|success' "$RT1186_RES/flash_intrinsics.log" | awk '{ print ($1 > 0) ? "ok" : "no" }')" "0|ok"
rt_console intrinsics 0 "INTRINSICS END"
from=$(cat "$RT1186_RES/serial_intrinsics.reset")
tail -c +$((from + 1)) "$RT1186_RES/serial_intrinsics.log" | tr -d '\r' > "$RT1186_RES/console.txt"
ok "the console has the program's end line" "$(grep -c '^INTRINSICS END$' "$RT1186_RES/console.txt")" 1
printf '%s\n' "$rows" | while IFS="$(printf '\t')" read -r id width entry args status value; do
  got=$(sed -n "s/^C $id //p" "$RT1186_RES/console.txt")
  case $status in ok) want="0 $value" ;; arithmetic) want="2 untouched" ;; esac
  ok "$id: $entry($args) at 32 bits, on the board" "$got" "$want"
done > "$RT1186_RES/cases.out"
cat "$RT1186_RES/cases.out"
pass=$((pass + $(grep -c '^  pass' "$RT1186_RES/cases.out"))); fail=$((fail + $(grep -c '^  FAIL' "$RT1186_RES/cases.out")))
summary
