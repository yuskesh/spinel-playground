# tests/doom-core/one-closure.rb — every source entry in ONE kernel closure.
#
#   ruby tests/doom-core/one-closure.rb --fixtures DIR --packed FILE --output DIR [--dispatch dense]
#
# WHY. The cutover calls render through one native entry, so every ported
# render definition must at some point be admitted by the kernel in a single
# closure. Each entry the lane builds is its own closure, which says nothing
# about their union: its size, its parameter count and whether the kernel still
# admits it. This file writes that union as an entry, so build-artifacts.sh can
# hand it to the kernel every time definitions land and screens.sh can assert
# that it is still admitted -- a series from the first batch, not one point at
# the end. NOTHING CALLS THE OBJECT; it is built to be admitted and link-checked.
#
# THE ENTRY CALLS EVERY FIXTURE ENTRY IN SEQUENCE, with no dispatch. A dispatch
# on an op code is not what the real top entry does (render_player_view calls
# its callees by name), and a dense one makes clang build a jump table in
# .rodata. `--dispatch dense` writes exactly that shape. Its references are to
# the object's own sections, so the relocation check admits it by target
# (object-relocs.rb), as it admits the tables the plain closure already has.
#
# ONE BUFFER PER RESIDENT FIELD. An entry parameter fields.tsv binds to a field
# (in the first context naming the entry) shares one buffer with every other
# parameter bound to that field; one that names no field keeps its own,
# entry-qualified. The entries' scalars arrive in one i64 buffer, `args`.
#
# It writes OUTPUT/stage/src/packed.rb (the packed source with the entry
# appended), OUTPUT/stage/one.contract and OUTPUT/shape.tsv.
require "fileutils"
require "optparse"

opt = { dispatch: "none" }
OptionParser.new do |o|
  o.on("--fixtures DIR") { |v| opt[:fixtures] = v }
  o.on("--packed FILE") { |v| opt[:packed] = v }
  o.on("--output DIR") { |v| opt[:output] = v }
  o.on("--dispatch KIND") { |v| opt[:dispatch] = v }
end.parse!
def refuse(msg)
  warn "one-closure: #{msg}"
  exit 2
end
%i[fixtures packed output].each { |k| opt[k] or refuse("--#{k} is required") }
%w[none dense].include?(opt[:dispatch]) or refuse("--dispatch is none or dense, not #{opt[:dispatch]}")

contracts = Dir[File.join(opt[:fixtures], "*.contract")].sort.to_h do |path|
  lines = File.readlines(path, chomp: true)
  entry = lines.map { |l| l[/\Aentry (\S+)/, 1] }.compact.first or refuse("#{path} names no entry")
  params = lines.grep(/\Aparam /).map { |l| l.split.drop(1) }
  [File.basename(path, ".contract"), [entry, params]]
end
contracts.empty? and refuse("no contracts under #{opt[:fixtures]}")

first_ctx = {}
fields = Hash.new { |h, k| h[k] = {} }
File.foreach(File.join(opt[:fixtures], "fields.tsv")) do |l|
  next if l.start_with?("#") || l.strip.empty?
  ctx, e, param, field, = l.chomp.split("\t")
  first_ctx[e] ||= ctx
  fields[e][param] = field if first_ctx[e] == ctx
end

buffers = {} # key => [element, mode]
calls = []
nscalars = 0
contracts.each do |e, (entry, params)|
  args = []
  params.each do |name, kind, elem, mode|
    if kind == "buffer"
      field = fields[e][name]
      key = if field == "core_state" then "state"
            elsif field && !field.start_with?("none", "job:", "derived:", "arg:") then field
            else "#{e}_#{name}"
            end
      if (have = buffers[key])
        have[0] == elem or refuse("#{key}: #{e}.#{name} is #{elem}, another entry has #{have[0]}")
        have[1] = "inout" if mode == "inout"
      else
        buffers[key] = [elem, mode]
      end
      args << key << "n_#{key}"
    elsif kind == "scalar" && !name.start_with?("n_")
      args << "args[#{nscalars}]"
      nscalars += 1
    end
  end
  calls << "#{entry}(#{args.join(', ')})"
end

params = ["op", "args", "n_args"] + buffers.keys.flat_map { |k| [k, "n_#{k}"] }
body = +"# THE ONE CLOSURE, generated by tests/doom-core/one-closure.rb. Nothing calls it.\n"
body << "def dc_sp_one(#{params.join(', ')})\n"
if opt[:dispatch] == "dense"
  calls.each_with_index { |c, k| body << "  return #{c} if op == #{k}\n" }
  body << "  -1\n"
else
  body << "  acc = 0\n"
  calls.each { |c| body << "  acc += #{c}\n" }
  body << "  acc\n"
end
body << "end\n"

contract = ["core-contract 1", "root src/packed.rb", "entry dc_sp_one", "result i64",
            "param op scalar i64", "param args buffer i64 in count n_args", "param n_args scalar u64"]
buffers.each do |k, (elem, mode)|
  contract << "param #{k} buffer #{elem} #{mode} count n_#{k}" << "param n_#{k} scalar u64"
end

stage = File.join(opt[:output], "stage")
FileUtils.mkdir_p(File.join(stage, "src"))
File.write(File.join(stage, "src/packed.rb"), File.read(opt[:packed]) + body)
File.write(File.join(stage, "one.contract"), "#{contract.join("\n")}\n")
File.write(File.join(opt[:output], "shape.tsv"),
           "entries\t#{calls.length}\nbuffers\t#{buffers.length}\nscalars\t#{nscalars}\n" \
           "params\t#{contract.grep(/\Aparam /).length}\ndispatch\t#{opt[:dispatch]}\n")
