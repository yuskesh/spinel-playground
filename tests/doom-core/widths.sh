#!/bin/sh
#
# tests/doom-core/widths.sh — decision 0018's re-measurement of the width table.
#
#   LIB=... HEADERS=... WAD=... STORE_RANGES=... sh tests/doom-core/widths.sh DIR
#
# LIB and HEADERS are what tests/doom-core/verify.sh's route part builds
# (harness/artifacts.sh's dc_route_adapter and dc_adapter_link), as for
# native-scenario-diff.sh. STORE_RANGES is the directory where verify.sh's port
# runs (input-diff.rb, step-diff.rb over the demos and the scenarios,
# render-diff.rb over the demos and at scale 2) left, through
# tools/doom/core-store-ranges.rb, every value the entries stored. verify.sh runs
# this lane after them.
#
# WHAT IT CHECKS
#   * every demo played to its end through the compiled entries by
#     tools/doom/core-ranges.rb, each with its own two controls (the direct
#     read equals the route's own, and a planted value is seen)
#   * examples/doom/core/widths.tsv against those measurements, the recorded
#     stores and a fresh
#     tools/doom/core-store-widths.rb: no measured value outside its row's
#     element, every static row still bounded by its stores, one row per entry
#     buffer (tools/doom/core-widths.rb --check)
#   * THREE CONTROLS, each a copy with one planted fault the check must name:
#     an observed row narrowed one type below what was measured, a missing
#     row, and a static row whose stores no longer bound it
#
# A FAILURE IS NOT FIXED BY EDITING THE TABLE (0018). Regenerate it from the
# measurements this lane leaves in DIR:
#   ruby tools/doom/core-widths.rb --stores DIR/stores.tsv \
#     --ranges DIR/DEMO1.tsv,DIR/DEMO2.tsv,DIR/DEMO3.tsv --store-ranges STORE_RANGES \
#     --measured-at "$(git rev-parse HEAD)" --output examples/doom/core/widths.tsv
set -u
ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/../.." && pwd)
DIR=${1:?usage: widths.sh DIR}
RUBY=${RUBY:-ruby}
WADFILE=${WAD:-$ROOT/build/doom-wad/doom1.wad}
LIB=${LIB:?LIB is the shared object linking the adapters and the kernel objects}
HEADERS=${HEADERS:?HEADERS is the directory the adapter generator wrote}
STORE_RANGES=${STORE_RANGES:?STORE_RANGES is the directory of tools/doom/core-store-ranges.rb output verify.sh writes}
TABLE=$ROOT/examples/doom/core/widths.tsv
DEMOS="DEMO1 DEMO2 DEMO3"
TAB=$(printf "\t")
pass=0; fail=0
ok() { if [ "$2" = "$3" ]; then echo "  pass $1"; pass=$((pass + 1))
       else echo "  FAIL $1 (got '$2', want '$3')"; fail=$((fail + 1)); fi; }
mkdir -p "$DIR" || exit 2

echo "== the width table, re-measured (decision 0018) =="
s=$(date +%s)
for d in $DEMOS; do
  ( "$RUBY" "$ROOT/tools/doom/core-ranges.rb" "$WADFILE" "$d" "$LIB" "$HEADERS" "$DIR/work-$d" "$DIR/$d.tsv" \
      > "$DIR/$d.out" 2>&1
    echo "$?" > "$DIR/$d.rc" ) &
done
"$RUBY" "$ROOT/tools/doom/core-store-widths.rb" --output "$DIR/stores.tsv" > "$DIR/stores.out" 2>&1
echo "$?" > "$DIR/stores.rc"
wait
echo "  time the demos: $(( $(date +%s) - s )) s"
for d in $DEMOS; do
  ok "$d: played to its end, its read checked against the route's and a planted value seen" \
     "$(cat "$DIR/$d.rc")|$(grep -c '^core-ranges: control: the direct read equals Route#cells' "$DIR/$d.out")|$(grep -c '^core-ranges: control: .* planted after the last tic is seen' "$DIR/$d.out")|$(grep -c "^core-ranges: $d .* 0 release(s) refused$" "$DIR/$d.out")" \
     "0|1|1|1"
  sed -n "s/^core-ranges: $d /    $d /p" "$DIR/$d.out"
done
ok "the stores scanned" "$(cat "$DIR/stores.rc")" "0"
nrec=$(ls "$STORE_RANGES"/*.tsv 2>/dev/null | wc -l | tr -d " ")
ok "the port runs recorded their stores, each file the recorder's" \
   "$([ "$nrec" -gt 0 ] && echo some)|$(for r in "$STORE_RANGES"/*.tsv; do head -1 "$r" | grep -q "^# Generated by tools/doom/core-store-ranges.rb: " || echo "$r"; done | wc -l | tr -d " ")" "some|0"
echo "    $(ls "$STORE_RANGES"/*.tsv | wc -l | tr -d ' ') recorded run(s): $(ls "$STORE_RANGES" | sed 's/\.tsv$//' | tr '\n' ' ')"
sed 's/^/    /' "$DIR/stores.out"

RANGES=$DIR/DEMO1.tsv,$DIR/DEMO2.tsv,$DIR/DEMO3.tsv
check() { # table stores out
  "$RUBY" "$ROOT/tools/doom/core-widths.rb" --stores "$2" --ranges "$RANGES" --store-ranges "$STORE_RANGES" \
    --check "$1" > "$3" 2>&1
}
check "$TABLE" "$DIR/stores.tsv" "$DIR/check.out"; rc=$?
ok "no measured value lies outside its row's element, and every static row is still bounded" \
   "$rc|$(grep -c '^core-widths: [0-9]* checked, [0-9]* pass, 0 fail' "$DIR/check.out")" "0|1"
sed 's/^/    /' "$DIR/check.out"
echo "    rows: $(grep -v '^#' "$TABLE" | cut -f2 | sort | uniq -c | awk '{printf "%s %s, ", $2, $1}' | sed 's/, $//'); measured at $(grep -v '^#' "$TABLE" | cut -f6 | sort -u | tr '\n' ' ')"

echo "  -- the controls, each a copy with one planted fault --"
# An OBSERVED row whose element is u16, narrowed to u8 with its min and max
# clipped to u8: the row is well-formed and only the measurement contradicts it.
# Its element is the smallest the measurement fits, so u8 cannot hold it.
nf=$(awk -F"$TAB" '!/^#/ && $2 == "u16" && $5 ~ /^observed:/ { print $1; exit }' "$TABLE")
awk -F"$TAB" -v OFS="$TAB" -v f="$nf" '$1 == f { $2 = "u8"; $3 = 0; $4 = 255 } { print }' "$TABLE" > "$DIR/ctl-narrow.tsv"
check "$DIR/ctl-narrow.tsv" "$DIR/stores.tsv" "$DIR/ctl-narrow.out"; rc=$?
ok "an observed row narrowed below its measurement is named ($nf)" \
   "$rc|$([ -n "$nf" ] && echo planted)|$(grep -c "^  FAIL $nf: measured .* outside its element u8" "$DIR/ctl-narrow.out")|$(grep -c '^  FAIL ' "$DIR/ctl-narrow.out")" \
   "1|planted|1|1"
mf=$(awk -F"$TAB" '!/^#/ { print $1; exit }' "$TABLE")
awk -F"$TAB" -v f="$mf" '$1 != f' "$TABLE" > "$DIR/ctl-missing.tsv"
check "$DIR/ctl-missing.tsv" "$DIR/stores.tsv" "$DIR/ctl-missing.out"; rc=$?
ok "a missing row is named ($mf)" \
   "$rc|$(grep -c "^  FAIL $mf: an entry buffer the table has no row for" "$DIR/ctl-missing.out")" "1|1"
# A STATIC row, with the scan's verdict for that field turned to `no`: what a
# new store the scan cannot bound would do.
sf=$(awk -F"$TAB" '!/^#/ && $5 ~ /^static:/ { print $1; exit }' "$TABLE")
awk -F"$TAB" -v OFS="$TAB" -v f="$sf" '$1 == f { $9 = "no:other" } { print }' "$DIR/stores.tsv" > "$DIR/ctl-stores.tsv"
check "$TABLE" "$DIR/ctl-stores.tsv" "$DIR/ctl-static.out"; rc=$?
ok "a static row whose stores no longer bound it is named ($sf)" \
   "$rc|$([ -n "$sf" ] && echo planted)|$(grep -c "^  FAIL $sf: the row is static, and its stores no longer bound it" "$DIR/ctl-static.out")" \
   "1|planted|1"

echo "widths: $((pass + fail)) checked, $pass pass, $fail fail"
[ "$fail" -eq 0 ]
