# tests/doom-core/stepall.rb — the step port's build-only entry, generated.
#
#   ruby tests/doom-core/stepall.rb
#
# WHILE THE STEP ENTRY IS BEING WRITTEN, ITS DEFINITIONS HAVE NO CALLER, and the
# kernel compiles only what an entry reaches. This writes dc_sp_stepall, which
# calls every step definition (`dc_st_*` in examples/doom/core/src/step*.rb) once,
# in file order, so each batch is compiled -- and refused, where the kernel
# refuses it -- as it is written. It is scaffolding: when g_ticker is ported, the
# real step entry replaces it. Nothing runs it.
#
# ONE CLOSURE FOR ALL OF STEP. The step definitions share their helpers, and an
# entry's closure admits no caller from outside it, so they cannot be split into
# one entry each without a renamed copy per helper per entry.
#
# A parameter the body indexes is a buffer (one per name, i64, inout); `state`
# is core_state and `gx` the index table; every other parameter is a scalar,
# taken from one i64 `args` buffer. It rewrites
# tests/doom-core/fixtures/source/stepall.contract and the wrapper between the
# STEPALL markers in tests/doom-core/fixtures/source/src/entries.rb.
ROOT = File.expand_path("../..", __dir__)
defs = []
raw = {}
Dir[File.join(ROOT, "examples/doom/core/src/step*.rb")].sort.each do |path|
  File.read(path).scan(/^def (dc_st_\w+)\(([^)]*)\)\n(.*?)^end\n/m) do |name, params, body|
    raw[name] = [params.split(",").map(&:strip), body]
  end
end
# A parameter is a buffer when the body indexes it, or hands it on in a position
# that is a buffer in the callee: a fixed point over every definition.
buf = raw.to_h { |n, (ps, body)| [n, ps.to_h { |x| [x, %w[state gx].include?(x) || body.match?(/\b#{Regexp.escape(x)}\[/)] }] }
# Every call in a body, nested ones included, with its top-level arguments.
def calls_in(body)
  out = []
  body.scan(/\b(dc_st_\w+)\(/) do
    name = Regexp.last_match(1)
    i = Regexp.last_match.end(0)
    depth = 0
    args = []
    cur = +""
    while i < body.size
      ch = body[i]
      if ch == "(" then depth += 1
      elsif ch == ")"
        break if depth.zero?
        depth -= 1
      elsif ch == "," && depth.zero?
        args << cur
        cur = +""
        i += 1
        next
      end
      cur << ch
      i += 1
    end
    args << cur
    out << [name, args.join(",")]
  end
  out
end
loop do
  changed = false
  raw.each do |n, (ps, body)|
    calls_in(body).each do |callee, args|
      next unless raw.key?(callee)
      args.split(",").map(&:strip).each_with_index do |a, i|
        cp = raw[callee][0][i]
        next unless cp && buf[callee][cp] && ps.include?(a) && !buf[n][a]
        buf[n][a] = true
        changed = true
      end
    end
  end
  break unless changed
end
raw.each { |n, (ps, _)| defs << [n, ps.map { |x| [x, buf[n][x]] }] }
defs.empty? and abort("stepall.rb: no dc_st_ definitions")
# ONLY THE ROOTS ARE CALLED HERE: a definition another step definition calls is
# reached through it. The kernel types a buffer parameter by where the buffer
# comes from, and a callee handed an entry buffer at one site and a helper's
# parameter at another is refused (measured on the first batch).
called = defs.map(&:first).select { |n| raw.any? { |m, (_, body)| m != n && body.match?(/\b#{n}\(/) } }
defs = defs.reject { |n, _| called.include?(n) }
buffers = []
nscalars = 0
calls = defs.map do |name, params|
  args = params.map do |n, indexed|
    if %w[state gx].include?(n) || indexed
      buffers << n unless buffers.include?(n) || %w[state gx].include?(n)
      n
    else
      nscalars += 1
      "args[#{nscalars - 1}]"
    end
  end
  "  acc += #{name}(#{args.join(', ')})\n"
end
sig = %w[state gx args] + buffers
wrapper = "# STEPALL BEGIN -- generated by tests/doom-core/stepall.rb, do not edit\n" \
          "def dc_sp_stepall(#{sig.flat_map { |b| [b, "n_#{b}"] }.join(', ')})\n  acc = 0\n#{calls.join}  acc\nend\n" \
          "# STEPALL END\n"
entries = File.join(ROOT, "tests/doom-core/fixtures/source/src/entries.rb")
e = File.read(entries)
e = e =~ /# STEPALL BEGIN.*?# STEPALL END\n/m ? e.sub(/# STEPALL BEGIN.*?# STEPALL END\n/m) { wrapper } : "#{e.rstrip}\n\n#{wrapper}"
File.write(entries, e)
contract = ["core-contract 1", "root src/packed.rb", "entry dc_sp_stepall", "result i64",
            "param state buffer i64 inout count n_state", "param n_state scalar u64",
            "param gx buffer i64 in count n_gx", "param n_gx scalar u64",
            "param args buffer i64 in count n_args", "param n_args scalar u64"]
# A buffer is i64 unless its field is not: the byte-sized fields the step reads.
ELEMENT = { "reject" => "u8" }.freeze
buffers.each { |b| contract << "param #{b} buffer #{ELEMENT.fetch(b, "i64")} inout count n_#{b}" << "param n_#{b} scalar u64" }
File.write(File.join(ROOT, "tests/doom-core/fixtures/source/stepall.contract"), "#{contract.join("\n")}\n")
puts "stepall.rb: #{defs.length} definitions, #{buffers.length} buffers, #{nscalars} scalars"
