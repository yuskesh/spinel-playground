# tests/doom-core/renderall.rb — the render spine's build-only entry, generated.
#
#   ruby tests/doom-core/renderall.rb
#
# tests/doom-core/stepall.rb's twin for the render spine
# (examples/doom/core/src/rview.rb and the copies it reaches, rvcopies.rb): it
# writes dc_sp_renderall, which calls each ROOT of the spine -- a `dc_rv_*`
# definition no other one calls: the view, the GPU path's refusal, the screen
# clear and the hi-res blit -- so the spine is compiled as it is written. It is
# scaffolding for the port phase; the render entry the program calls replaces
# it. Nothing runs it.
#
# A parameter the body indexes is a buffer (one per name, inout); `state` is
# core_state and `rx` the index table; every other parameter is a scalar, taken
# from one i64 `args` buffer. A buffer is i64 unless ELEMENT says its field is
# bytes. It rewrites tests/doom-core/fixtures/source/renderall.contract and the
# wrapper between the RENDERALL markers in
# tests/doom-core/fixtures/source/src/entries.rb.
ROOT = File.expand_path("../..", __dir__)
defs = []
raw = {}
Dir[File.join(ROOT, "examples/doom/core/src/{rview,rvcopies,rvgpu}.rb")].sort.each do |path|
  File.read(path).scan(/^def (dc_rv_\w+)\(([^)]*)\)\n(.*?)^end\n/m) do |name, params, body|
    raw[name] = [params.split(",").map(&:strip), body]
  end
end
# A parameter is a buffer when the body indexes it, or hands it on in a position
# that is a buffer in the callee: a fixed point over every definition.
buf = raw.to_h { |n, (ps, body)| [n, ps.to_h { |x| [x, %w[state rx].include?(x) || body.match?(/\b#{Regexp.escape(x)}\[/)] }] }
# Every call in a body, nested ones included, with its top-level arguments.
def calls_in(body)
  out = []
  body.scan(/\b(dc_rv_\w+)\(/) do
    name = Regexp.last_match(1)
    i = Regexp.last_match.end(0)
    depth = 0
    args = []
    cur = +""
    while i < body.size
      ch = body[i]
      if ch == "(" then depth += 1
      elsif ch == ")"
        break if depth.zero?
        depth -= 1
      elsif ch == "," && depth.zero?
        args << cur
        cur = +""
        i += 1
        next
      end
      cur << ch
      i += 1
    end
    args << cur
    out << [name, args.join(",")]
  end
  out
end
loop do
  changed = false
  raw.each do |n, (ps, body)|
    calls_in(body).each do |callee, args|
      next unless raw.key?(callee)
      args.split(",").map(&:strip).each_with_index do |a, i|
        cp = raw[callee][0][i]
        next unless cp && buf[callee][cp] && ps.include?(a) && !buf[n][a]
        buf[n][a] = true
        changed = true
      end
    end
  end
  break unless changed
end
raw.each { |n, (ps, _)| defs << [n, ps.map { |x| [x, buf[n][x]] }] }
defs.empty? and abort("renderall.rb: no dc_rv_ definitions")
# ONLY THE ROOTS ARE CALLED HERE: a definition another spine definition calls is
# reached through it. The kernel types a buffer parameter by where the buffer
# comes from, and a callee handed an entry buffer at one site and a helper's
# parameter at another is refused (measured on the first batch).
called = defs.map(&:first).select { |n| raw.any? { |m, (_, body)| m != n && body.match?(/\b#{n}\(/) } }
defs = defs.reject { |n, _| called.include?(n) }
buffers = []
nscalars = 0
calls = defs.map do |name, params|
  args = params.map do |n, indexed|
    if %w[state rx].include?(n) || indexed
      buffers << n unless buffers.include?(n) || %w[state rx].include?(n)
      n
    else
      nscalars += 1
      "args[#{nscalars - 1}]"
    end
  end
  "  acc += #{name}(#{args.join(', ')})\n"
end
sig = %w[state rx args] + buffers
wrapper = "# RENDERALL BEGIN -- generated by tests/doom-core/renderall.rb, do not edit\n" \
          "def dc_sp_renderall(#{sig.flat_map { |b| [b, "n_#{b}"] }.join(', ')})\n  acc = 0\n#{calls.join}  acc\nend\n" \
          "# RENDERALL END\n"
entries = File.join(ROOT, "tests/doom-core/fixtures/source/src/entries.rb")
e = File.read(entries)
e = e =~ /# RENDERALL BEGIN.*?# RENDERALL END\n/m ? e.sub(/# RENDERALL BEGIN.*?# RENDERALL END\n/m) { wrapper } : "#{e.rstrip}\n\n#{wrapper}"
File.write(entries, e)
contract = ["core-contract 1", "root src/packed.rb", "entry dc_sp_renderall", "result i64",
            "param state buffer i64 inout count n_state", "param n_state scalar u64",
            "param rx buffer i64 in count n_rx", "param n_rx scalar u64",
            "param args buffer i64 in count n_args", "param n_args scalar u64"]
# A buffer is i64 unless its field is not: the screens, the colormap, the
# texture and flat atlases, the WAD, the zone windows.
ELEMENT = %w[scr dst src cmap atlas flat wad zonebuf zonewin].to_h { |b| [b, "u8"] }.freeze
buffers.each { |b| contract << "param #{b} buffer #{ELEMENT.fetch(b, "i64")} inout count n_#{b}" << "param n_#{b} scalar u64" }
File.write(File.join(ROOT, "tests/doom-core/fixtures/source/renderall.contract"), "#{contract.join("\n")}\n")
puts "renderall.rb: #{defs.length} definitions, #{buffers.length} buffers, #{nscalars} scalars"
