// Package bindgen は正典 schema から cilium/ebpf 向けの型付き bindings を生成する
// (E152 / P013 Task 5)。
//
// **schema の offset が正典**である。Go の struct 詰め規則に任せず padding を
// 明示し、decoder も offset で読む — E432 が実測した「手で写した Go reader は
// C の内部 padding を落として 29/64 field を静かにずらす」を構造的に塞ぐため。
package bindgen

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"sort"
	"strings"
)

type Input struct {
	Package    string
	SchemaJSON []byte
	ObjectPath string // 生成 Go が go:embed する ELF の相対パス
}

// --- schema の読み取り (core 層だけ。telemetry と extensions は見ない) ---------

type schema struct {
	Version int `json:"version"`
	Core    struct {
		Records  []record  `json:"records"`
		Maps     []mapDecl `json:"maps"`
		Programs []program `json:"programs"`
	} `json:"core"`
}

type intType struct {
	Kind      string `json:"kind"`
	Bits      uint32 `json:"bits"`
	Signed    bool   `json:"signed"`
	Endianness string `json:"endianness"`
	Alignment uint32 `json:"alignment"`
	Count     uint64 `json:"count"`
	Element   *intType `json:"element"`
	Symbol    string `json:"symbol"`
}

type field struct {
	Name   string  `json:"name"`
	Offset uint64  `json:"offset"`
	Expose string  `json:"expose"`
	Note   string  `json:"note"`
	Type   intType `json:"type"`
}

type record struct {
	Symbol    string  `json:"symbol"`
	ID        uint32  `json:"id"`
	Size      uint64  `json:"size"`
	MinSize   uint64  `json:"min_size"`
	Alignment uint32  `json:"alignment"`
	Fields    []field `json:"fields"`
	Note      string  `json:"note"`
}

type mapDecl struct {
	Symbol string `json:"symbol"`
	Kind   string `json:"kind"`
	Record string `json:"record"`
}

type program struct {
	Name string `json:"name"`
	Kind string `json:"kind"`
}

// --- 型の写像 -----------------------------------------------------------------

func goScalar(t intType) (string, error) {
	if t.Kind != "int" {
		return "", fmt.Errorf("not a scalar type: %s", t.Kind)
	}
	prefix := "uint"
	if t.Signed {
		prefix = "int"
	}
	switch t.Bits {
	case 8, 16, 32, 64:
		return fmt.Sprintf("%s%d", prefix, t.Bits), nil
	}
	return "", fmt.Errorf("unsupported width: %d", t.Bits)
}

// Go 側の綴りと、その field が占めるバイト数。
func goType(t intType, sizes map[string]uint64) (string, uint64, error) {
	switch t.Kind {
	case "int":
		s, err := goScalar(t)
		return s, uint64(t.Bits / 8), err
	case "array":
		elem, esz, err := goType(*t.Element, sizes)
		if err != nil {
			return "", 0, err
		}
		return fmt.Sprintf("[%d]%s", t.Count, elem), t.Count * esz, nil
	case "record_ref":
		sz, ok := sizes[t.Symbol]
		if !ok {
			return "", 0, fmt.Errorf("size of record %q is unknown", t.Symbol)
		}
		return exported(t.Symbol), sz, nil
	}
	return "", 0, fmt.Errorf("unknown type kind: %s", t.Kind)
}

// exported は schema の symbol を **正しい Go の公開識別子**にする。
//
// 実物の schema には `<unit>_dns_events` のような綴りが入っている (E434)。
// 素朴に単語結合すると `<unit>DnsEvents` という parse できない綴りが出る
// (実測で踏んだ)。ここで識別子として使えない文字を落とす。
func exported(s string) string {
	parts := strings.FieldsFunc(s, func(r rune) bool {
		return !(r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9')
	})
	var b strings.Builder
	for _, p := range parts {
		if p == "" {
			continue
		}
		b.WriteString(strings.ToUpper(p[:1]))
		b.WriteString(p[1:])
	}
	out := b.String()
	if out == "" {
		return "X"
	}
	if out[0] >= '0' && out[0] <= '9' {
		return "X" + out // 数字始まりは識別子にできない
	}
	return out
}

// --- 生成 ---------------------------------------------------------------------

func Generate(in Input) ([]byte, error) {
	var s schema
	if err := json.Unmarshal(in.SchemaJSON, &s); err != nil {
		return nil, fmt.Errorf("cannot read the schema: %w", err)
	}
	if s.Version != 1 {
		return nil, fmt.Errorf("schema version must be 1 (got %d)", s.Version)
	}

	sizes := map[string]uint64{}
	for _, r := range s.Core.Records {
		sizes[r.Symbol] = r.Size
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, `// Code generated by spbpf-bindgen. DO NOT EDIT.
//
// 正典は schema であり、この file はその派生である。**手で直さない。**
// offset と padding は schema の宣言そのままで、Go の struct 詰め規則には
// 頼っていない (E432: 手で写した reader は C の内部 padding を落として静かにずれる)。
//
// cgo も C ソースも MLIR も要らない。load 以降は cilium/ebpf に委ねる。
package %s

import (
	"bytes"
	_ "embed"
	"encoding/binary"
	"fmt"

	"github.com/cilium/ebpf"
)

//go:embed %s
var objectELF []byte

// ObjectELF は埋め込んだ BTF 付き BPF ELF。
func ObjectELF() []byte { return objectELF }
`, in.Package, in.ObjectPath)

	// --- record structs + decoders ---
	recs := append([]record(nil), s.Core.Records...)
	sort.Slice(recs, func(i, j int) bool { return recs[i].Symbol < recs[j].Symbol })
	for _, r := range recs {
		name := exported(r.Symbol)
		fmt.Fprintf(&b, "\n// %s は schema の record %q (size=%d", name, r.Symbol, r.Size)
		if r.MinSize != r.Size {
			fmt.Fprintf(&b, ", min=%d の可変長", r.MinSize)
		}
		b.WriteString(")。\n")
		if r.Note != "" {
			fmt.Fprintf(&b, "// %s\n", r.Note)
		}
		fmt.Fprintf(&b, "type %s struct {\n", name)

		fields := append([]field(nil), r.Fields...)
		sort.Slice(fields, func(i, j int) bool { return fields[i].Offset < fields[j].Offset })
		var at uint64
		pad := 0
		for _, f := range fields {
			if f.Offset > at {
				fmt.Fprintf(&b, "\t_pad%d [%d]byte // schema が宣言する穴 (Go に詰めさせない)\n",
					pad, f.Offset-at)
				pad++
				at = f.Offset
			}
			gt, sz, err := goType(f.Type, sizes)
			if err != nil {
				return nil, fmt.Errorf("record %q field %q: %w", r.Symbol, f.Name, err)
			}
			fmt.Fprintf(&b, "\t%s %s", exported(f.Name), gt)
			if f.Note != "" {
				fmt.Fprintf(&b, " // %s", strings.ReplaceAll(f.Note, "\n", " "))
			}
			b.WriteString("\n")
			at = f.Offset + sz
		}
		if r.Size > at {
			fmt.Fprintf(&b, "\t_pad%d [%d]byte // 末尾の穴\n", pad, r.Size-at)
		}
		b.WriteString("}\n")

		fmt.Fprintf(&b, "\n// Size%s は schema が宣言する record の大きさ。\nconst Size%s = %d\n",
			name, name, r.Size)

		// schema の expose が "str" なら、NUL 終端として読む便利メソッドを生やす。
		// (expose は E149 が core に載せた情報。読み手が毎回書く定型をここで消す)
		for _, f := range fields {
			if f.Expose != "str" || f.Type.Kind != "array" || f.Type.Element == nil ||
				f.Type.Element.Bits != 8 {
				continue
			}
			fn := exported(f.Name)
			fmt.Fprintf(&b, `
// %sString は %s を NUL 終端の文字列として読む (schema の expose = "str")。
func (v *%s) %sString() string {
	buf := make([]byte, 0, %d)
	for _, c := range v.%s {
		if c == 0 {
			break
		}
		buf = append(buf, byte(c))
	}
	return string(buf)
}
`, fn, f.Name, name, fn, f.Type.Count, fn)
		}

		// decoder: offset で読む。struct の詰め方に依存しない。
		fmt.Fprintf(&b, `
// Decode は ring buffer から来た生バイト列を読む。**offset は schema の宣言そのまま**で、
// Go の struct レイアウトには依存しない。
func (v *%s) Decode(b []byte) error {
	if len(b) < %d {
		return fmt.Errorf("%s: %%d バイトしかない (最低 %d 要る)", len(b))
	}
`, name, r.MinSize, r.Symbol, r.MinSize)
		for _, f := range fields {
			if err := emitDecode(&b, f, sizes, r); err != nil {
				return nil, err
			}
		}
		b.WriteString("\treturn nil\n}\n")
	}

	// --- Objects ---
	b.WriteString("\n// Objects は load した program と map。tag は ELF の symbol 名。\ntype Objects struct {\n")
	progs := append([]program(nil), s.Core.Programs...)
	sort.Slice(progs, func(i, j int) bool { return progs[i].Name < progs[j].Name })
	for _, p := range progs {
		fmt.Fprintf(&b, "\t%s *ebpf.Program `ebpf:%q`\n", exported(p.Name), p.Name)
	}
	maps := append([]mapDecl(nil), s.Core.Maps...)
	sort.Slice(maps, func(i, j int) bool { return maps[i].Symbol < maps[j].Symbol })
	for _, m := range maps {
		fmt.Fprintf(&b, "\t%s *ebpf.Map `ebpf:%q`\n", exported(m.Symbol), m.Symbol)
	}
	b.WriteString("}\n")

	b.WriteString(`
// LoadCollectionSpec は埋め込み ELF を parse する。**root 権限は要らない** —
// kernel に触らずに ELF と BTF を読むだけ。
func LoadCollectionSpec() (*ebpf.CollectionSpec, error) {
	return ebpf.LoadCollectionSpecFromReader(bytes.NewReader(objectELF))
}

// LoadObjects は埋め込み ELF から program と map を作って o に割り当てる。
func LoadObjects(o *Objects, opts *ebpf.CollectionOptions) error {
	spec, err := LoadCollectionSpec()
	if err != nil {
		return fmt.Errorf("埋め込み ELF を parse できない: %w", err)
	}
	return spec.LoadAndAssign(o, opts)
}

// Close は割り当てた kernel resource を閉じる。
func (o *Objects) Close() error {
	var first error
	closeOne := func(c interface{ Close() error }) {
		if c == nil {
			return
		}
		if err := c.Close(); err != nil && first == nil {
			first = err
		}
	}
`)
	for _, p := range progs {
		fmt.Fprintf(&b, "\tcloseOne(o.%s)\n", exported(p.Name))
	}
	for _, m := range maps {
		fmt.Fprintf(&b, "\tcloseOne(o.%s)\n", exported(m.Symbol))
	}
	b.WriteString("\treturn first\n}\n")

	// binary を使わない生成になった場合に import が余らないよう、必ず 1 度は使う。
	b.WriteString("\nvar _ = binary.LittleEndian\n")

	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("cannot format the generated Go: %w\n%s", err, b.String())
	}
	return out, nil
}

func emitDecode(b *bytes.Buffer, f field, sizes map[string]uint64, r record) error {
	name := exported(f.Name)
	switch f.Type.Kind {
	case "int":
		gt, _ := goScalar(f.Type)
		switch f.Type.Bits {
		case 8:
			fmt.Fprintf(b, "\tv.%s = %s(b[%d])\n", name, gt, f.Offset)
		case 16:
			fmt.Fprintf(b, "\tv.%s = %s(binary.LittleEndian.Uint16(b[%d:]))\n", name, gt, f.Offset)
		case 32:
			fmt.Fprintf(b, "\tv.%s = %s(binary.LittleEndian.Uint32(b[%d:]))\n", name, gt, f.Offset)
		case 64:
			fmt.Fprintf(b, "\tv.%s = %s(binary.LittleEndian.Uint64(b[%d:]))\n", name, gt, f.Offset)
		}
	case "array":
		elem := *f.Type.Element
		if elem.Kind != "int" || elem.Bits != 8 {
			return fmt.Errorf("record %q field %q: arrays of elements other than 8 bits cannot be read yet", r.Symbol, f.Name)
		}
		if elem.Signed {
			// char[] は Go では int8[] になるので copy が使えない。
			fmt.Fprintf(b, "\tfor i := 0; i < %d; i++ {\n\t\tv.%s[i] = int8(b[%d+i])\n\t}\n",
				f.Type.Count, name, f.Offset)
		} else {
			fmt.Fprintf(b, "\tcopy(v.%s[:], b[%d:%d])\n", name, f.Offset, f.Offset+f.Type.Count)
		}
	case "record_ref":
		sz := sizes[f.Type.Symbol]
		fmt.Fprintf(b, "\tif err := v.%s.Decode(b[%d : %d]); err != nil {\n\t\treturn err\n\t}\n",
			name, f.Offset, f.Offset+sz)
	}
	return nil
}
