# frozen_string_literal: true
# tools/npu/stm32mp2/lane.rb -- the STM32MP257F-DK half of tools/npu/spinel-npu
# (decision 0034): a Linux executable that runs the model through TFLite and the
# VX delegate from an IREE dispatch.
#
# Environment
#   IREE_COMPILE, IREE_SRC  iree-compile and the IREE source tree
#   IREE_STM32MP2_BUILD     the output of tools/npu/stm32mp2/build-iree.sh
#   STM32MP2_CROSS          the cross tools' prefix, ending in the target name and "-"
#   STM32MP2_SYSROOT        a sysroot with glibc, libstdc++ and TFLite 2.18 headers and library

IREE_A35 = %w[
  --iree-stream-partitioning-favor=min-peak-memory
  --iree-hal-target-device=local
  --iree-hal-local-target-device-backends=llvm-cpu
  --iree-llvmcpu-target-triple=aarch64-unknown-linux-gnu
  --iree-llvmcpu-target-cpu=cortex-a35
  --iree-llvmcpu-debug-symbols=false
  --iree-llvmcpu-link-embedded=false
  --iree-llvmcpu-link-static
].freeze

A35 = %w[-mcpu=cortex-a35 -O2 -ffunction-sections -fdata-sections -w -D_GNU_SOURCE].freeze

def stm32_check_model(decl, model, path)
  die("#{path}: partial: true has no meaning here: the delegate takes the whole model or the program stops") if decl.partial
  die("#{path}: the model has #{model.inputs.size} inputs and #{model.outputs.size} outputs; this lane takes one of each") unless model.inputs.size == 1 && model.outputs.size == 1
  { "input" => [decl.input, model.tensors[model.inputs[0]]],
    "output" => [decl.output, model.tensors[model.outputs[0]]] }.each do |side, (d, t)|
    die("#{path}: the model's #{side} is type #{t.type}, not int8") unless t.type == TFLite::INT8
    die("#{path}: the declaration says #{side}: #{d.inspect}, the model has #{shape_s(t)}") unless d[1..] == t.shape
  end
end

def stm32_write_glue(out, decl, vmfb, tag)
  bytes = ->(s) { s[1..].inject(:*) }
  File.write(File.join(out, "npu_glue.c"), <<~C)
    /* Generated by tools/npu/spinel-npu -- do not edit. */
    #include <stdint.h>
    #include <string.h>
    #include "iree/hal/drivers/local_sync/sync_device.h"
    #include "iree/hal/local/loaders/static_library_loader.h"
    #include "iree/runtime/api.h"
    #include "npu_k.h"

    extern const uint8_t npu_tflite[];
    extern const size_t npu_tflite_size;
    int sp_t_register_module(const char *, const void *, int64_t);
    void sp_npu_tflite_run(const char *, const void *, size_t, const void *, size_t, void *, size_t);

    void sp_npu_run(const int8_t *in, size_t in_off, int8_t *out, size_t out_off)
    {
    \tsp_npu_tflite_run("#{tag}", npu_tflite, npu_tflite_size, in + in_off, #{bytes[decl.input]}, out + out_off, #{bytes[decl.output]});
    }

    #{device_glue(vmfb)}
  C
end

def stm32_build(out, rb, stripped, app)
  src = env!("IREE_SRC")
  iree = env!("IREE_STM32MP2_BUILD")
  cross = env!("STM32MP2_CROSS")
  sysroot = env!("STM32MP2_SYSROOT")
  gcc = "#{cross}gcc"
  gxx = "#{cross}g++"
  sr = ["--sysroot=#{sysroot}"]
  path = { "PATH" => "#{File.dirname(cross)}:#{ENV["PATH"]}" }
  die("#{gcc} is not executable", 2) unless File.executable?(gcc)
  die("#{sysroot} has no TFLite headers", 2) unless File.exist?(File.join(sysroot, "usr/include/tensorflow/lite/interpreter.h"))

  Dir[File.join(File.dirname(app), "*.rb")].each { |f| FileUtils.cp(f, rb) }
  File.write(File.join(rb, File.basename(app)), stripped)
  FileUtils.cp_r(File.join(ROOT, "tools/tensor/spinel"), rb)

  mk = File.read(File.join(VENDOR, "Makefile"))
  members = mk[/^RT_MEMBERS\s*=\s*(.+)$/, 1].to_s.split
  regexp = mk[/^RE_SRC\s*=\s*(.+)$/, 1].to_s.split
  die("no RT_MEMBERS or RE_SRC in the vendor Makefile") if members.empty? || regexp.empty?
  rt = File.join(out, "rt")
  FileUtils.mkdir_p(rt)
  inc = ["-I#{VENDOR}/lib", "-I#{VENDOR}/lib/regexp", "-I#{VENDOR}/lib/regexp/shim"]
  (members.map { |m| "lib/#{m}.c" } + regexp).each do |s|
    obj = File.join(rt, "#{File.basename(s, ".c")}.o")
    next if File.exist?(obj)
    run!(gcc, *sr, *A35, "-std=gnu2x", *inc, "-c", File.join(VENDOR, s), "-o", obj, env: path)
  end

  spinel = File.join(VENDOR, "bin/spinel")
  die("no #{spinel}: build vendor/spinel first", 2) unless File.executable?(spinel)
  run!(spinel, File.basename(app), "-c", "-o", File.join(out, "app.c"), chdir: rb, log: File.join(out, "spinel.log"))
  iree_inc = ["-I#{src}/runtime/src", "-I#{src}", "-I#{iree}/runtime/src", "-I#{out}"]
  c = [gcc, *sr, *A35, "-std=gnu2x", *inc, *iree_inc, "-DSP_T_STATIC_DEVICE", "-DIREE_ALLOCATOR_SYSTEM_CTL=iree_allocator_libc_ctl"]
  run!(*c, "-c", File.join(out, "app.c"), "-o", File.join(out, "app.o"), env: path)
  run!(*c, "-c", File.join(ROOT, "tools/tensor/sp_tensor_shim.c"), "-o", File.join(out, "shim.o"), env: path)
  run!(*c, "-c", File.join(out, "npu_glue.c"), "-o", File.join(out, "npu_glue.o"), env: path)
  run!(*c, "-c", File.join(out, "npu_model.c"), "-o", File.join(out, "npu_model.o"), env: path)
  run!(gxx, *sr, *A35, "-std=c++17", "-c", File.join(ROOT, "tools/npu/stm32mp2/npu_tflite.cc"),
       "-o", File.join(out, "npu_tflite.o"), env: path)

  libs = Dir[File.join(iree, "runtime/src/iree/**/*.a")] + Dir[File.join(iree, "build_tools/third_party/*/*.a")]
  die("#{iree} has no IREE libraries: run tools/npu/stm32mp2/build-iree.sh", 2) if libs.empty?
  objs = %w[app shim npu_k npu_glue npu_model npu_tflite].map { |n| File.join(out, "#{n}.o") } + Dir[File.join(rt, "*.o")]
  # The target's TFLite library has dependencies this sysroot need not hold.
  run!(gxx, *sr, "-Wl,--gc-sections", "-Wl,--allow-shlib-undefined", *objs, "-Wl,--start-group", *libs, "-Wl,--end-group",
       "-ltensorflow-lite", "-ldl", "-lm", "-lpthread", "-o", File.join(out, "app"), env: path)
end

def stm32_lane(decl, path, out, stripped, app, check_only)
  bytes = File.binread(path)
  model = begin
    TFLite::Model.new(bytes)
  rescue ArgumentError, NoMethodError => e
    die("#{path}: cannot read it as TFLite (#{e.message})")
  end
  stm32_check_model(decl, model, path)
  puts "spinel-npu: #{decl.name}: stm32mp257f-dk, input #{decl.input[1..].inspect}, output #{decl.output[1..].inspect}"
  return if check_only

  rb = File.join(out, "rb")
  FileUtils.mkdir_p(rb)
  File.write(File.join(out, "npu_model.c"), "#include <stddef.h>\n#include <stdint.h>\n" +
    c_array("npu_tflite", bytes) + "const size_t npu_tflite_size = #{bytes.bytesize};\n")
  File.write(File.join(out, "npu.mlir"), mlir(decl))
  run!(env!("IREE_COMPILE"), File.join(out, "npu.mlir"), *IREE_A35,
       "--iree-llvmcpu-static-library-output-path=#{File.join(out, "npu_k.h")}", "-o", File.join(out, "npu.vmfb"))
  sig = write_table(out, decl)
  write_gen(rb, decl, sig)
  vmfb = File.binread(File.join(out, "npu.vmfb"))
  tag = Digest::SHA256.hexdigest(vmfb + stripped + File.binread(File.join(out, "npu_model.c")) + File.binread(File.join(ROOT, "tools/npu/stm32mp2/npu_tflite.cc")))
  File.write(File.join(out, "build.tag"), "#{tag}\n")
  stm32_write_glue(out, decl, vmfb, tag)
  stm32_build(out, rb, stripped, app)
  puts "spinel-npu: #{File.join(out, "app")}"
end
