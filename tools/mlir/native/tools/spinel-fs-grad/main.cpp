// Freestanding gradient generator matches frozen spinel-gradfs inputs/object properties without
// launching Python. The initial stage read declarations, applied verbatim g01..g12, wrote
// rejects.tsv and stopped with matching failure status; accepted declarations then failed visibly
// as not-implemented until shim/Enzyme/cleanup/object generation landed. Enzyme runs in process;
// kernel IR comes from the emission library. Only typedump/codegen are subprocesses, and symbol
// tables are read in process.
