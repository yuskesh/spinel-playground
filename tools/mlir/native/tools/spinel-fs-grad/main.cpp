#else
constexpr const char *kEnzymePlugin = "LLVMEnzyme-23.so";
#endif

// Frozen ctype spelling: pointers end in * with no extra space; other types take one.
std::string ctypeOf(const fs_::FsParam &p) {
  if (p.kind == fs_::FsParam::Kind::Len)
    return "int32_t ";
  static const std::pair<const char *, const char *> kMap[] = {
      {"i8", "int8_t"},   {"i16", "int16_t"}, {"i32", "int32_t"},
      {"i64", "int64_t"}, {"u8", "uint8_t"},  {"u16", "uint16_t"},
      {"u32", "uint32_t"}, {"f32", "float"},  {"f64", "double"}};
  std::string c = "void";
  for (auto &kv : kMap)
    if (p.type == kv.first)
      c = kv.second;
  if (p.kind == fs_::FsParam::Kind::Scalar)
    return c + " ";
  return (p.direction == "in" ? "const " + c + " *" : c + " *");
}

// Frozen emit_header verbatim except the first-line generator name.
std::string gradHeader(ArrayRef<fs_::GradTarget> targets, StringRef tag) {
  std::string out;
  raw_string_ostream os(out);
  os << "/* generated by tools/mlir/native spinel-fs-grad (profile " << tag
     << ") */\n#ifndef SPINEL_GRAD_H\n#define SPINEL_GRAD_H\n"
        "#include <stdint.h>\n\n";
  for (const fs_::GradTarget &t : targets) {
    const fs_::FsGradDecl &g = *t.grad;
    std::string wrt;
    for (size_t i = 0; i < g.wrt.size(); ++i) {
      if (i)
        wrt += ",";
      wrt += g.wrt[i];
    }
    char tolBuf[64];
    std::snprintf(tolBuf, sizeof(tolBuf), "%g", g.tol);
    os << "/* freestanding_grad_def :" << g.name << " (line " << g.line
       << ")  wrt: " << wrt << "  tol: " << tolBuf << " */\n";
    os << "/*   d(" << g.name << ")/d(" << wrt
       << "); the shadow is ASSIGNED (zeroed first) */\n";
    std::string sig;
    for (size_t i = 0; i < t.fs->params.size(); ++i) {
      if (!sig.empty())
        sig += ", ";
      sig += ctypeOf(t.fs->params[i]) + t.pnames[i];
      if (llvm::is_contained(g.wrt, t.pnames[i]))
        sig += ", double *d_" + t.pnames[i];
    }
    os << "double " << g.sym() << "(" << sig << ");\n";
    if (g.hvp) {
      const std::string &w = g.wrt.front();
      std::string hsig;
      for (size_t i = 0; i < t.fs->params.size(); ++i) {
        if (!hsig.empty())
          hsig += ", ";
        hsig += ctypeOf(t.fs->params[i]) + t.pnames[i];
        if (t.pnames[i] == w)
          hsig += ", const double *dir_" + w + ", double *g_" + w +
                  ", double *hv_" + w;
      }
      os << "/*   forward-over-reverse: g_" << w << " := grad, hv_" << w
         << " := H.dir, returns grad.dir */\n";
      os << "double " << g.hvpSym() << "(" << hsig << ");\n";
    }
    os << "\n";
  }
  os << "#endif\n";
  return out;
}

int die(const Twine &msg) {
  errs() << "spinel-fs-grad: " << msg << "\n";
  return 1;
}

