int usage(const char *argv0) {
  errs() << "usage: " << argv0
         << " <kern.rb> --profile <p.yaml> -o <dir> [--tag T] [--grads-only]\n"
            "       [--emit-header H] [--fast-math] [--allow-rejects] "
            "[--enzyme PATH]\n"
            "       [--typedump PATH] [--codegen PATH] [--menus PATH] [--int64-allow PATH] [-v]\n"
            "\n"
            "  native calls no Python subprocess, so it does not take the frozen "
            "spinel-gradfs's\n"
            "  --spinel / --mlirgen / --undef-check (E167 design "
            "section 2).\n";
  return 2;
}

// Search executable ancestors as fs-emit does.
std::string ancestorPath(const char *argv0, ArrayRef<StringRef> parts) {
  std::string exe =
      sys::fs::getMainExecutable(argv0, reinterpret_cast<void *>(&usage));
  if (exe.empty())
    return {};
  SmallString<128> dir(sys::path::parent_path(exe));
  while (!dir.empty()) {
    SmallString<128> c(dir);
    for (StringRef p : parts)
      sys::path::append(c, p);
    if (sys::fs::exists(c))
      return std::string(c);
    StringRef parent = sys::path::parent_path(dir);
    if (parent == dir)
      break;
    dir = parent;
  }
  return {};
}

class ScopedTempDir {
public:
  ~ScopedTempDir() {
    if (!path_.empty())
      sys::fs::remove_directories(path_);
  }
  std::error_code create() {
    SmallString<128> model;
    sys::path::system_temp_directory(true, model);
    sys::path::append(model, "spinel-fs-grad");
    return sys::fs::createUniqueDirectory(model, path_);
  }
  std::string file(StringRef name) const {
    SmallString<128> p(path_);
    sys::path::append(p, name);
    return std::string(p);
  }

private:
  SmallString<128> path_;
};

