int main(int argc, char **argv) {
  std::string source, profilePath, outDir, tag, headerPath, enzymePath;
  std::string typedumpPath, codegenPath, menusPath, int64AllowPath;
  bool gradsOnly = false, fastMath = false, allowRejects = false,
       verbose = false;

  if (argc < 2 || argv[1][0] == '-')
    return usage(argv[0]);
  source = argv[1];
  for (int i = 2; i < argc; ++i) {
    StringRef a = argv[i];
    auto take = [&](std::string &dst) {
      if (i + 1 >= argc || !dst.empty())
        return false;
      dst = argv[++i];
      return true;
    };
    if (a == "--profile") { if (!take(profilePath)) return usage(argv[0]); }
    else if (a == "-o" || a == "--out") { if (!take(outDir)) return usage(argv[0]); }
    else if (a == "--tag") { if (!take(tag)) return usage(argv[0]); }
    else if (a == "--emit-header") { if (!take(headerPath)) return usage(argv[0]); }
    else if (a == "--enzyme") { if (!take(enzymePath)) return usage(argv[0]); }
    else if (a == "--typedump") { if (!take(typedumpPath)) return usage(argv[0]); }
    else if (a == "--codegen") { if (!take(codegenPath)) return usage(argv[0]); }
    else if (a == "--menus") { if (!take(menusPath)) return usage(argv[0]); }
    else if (a == "--int64-allow") { if (!take(int64AllowPath)) return usage(argv[0]); }
    else if (a == "--grads-only") { if (gradsOnly) return usage(argv[0]); gradsOnly = true; }
    else if (a == "--fast-math") { if (fastMath) return usage(argv[0]); fastMath = true; }
    else if (a == "--allow-rejects") { if (allowRejects) return usage(argv[0]); allowRejects = true; }
    else if (a == "-v" || a == "--verbose") { verbose = true; }
    else return usage(argv[0]);
  }
  if (profilePath.empty() || outDir.empty())
    return usage(argv[0]);
  (void)fastMath;
  (void)gradsOnly;
  (void)headerPath;
  (void)enzymePath;
  (void)verbose;

  if (tag.empty()) {
    StringRef base = sys::path::filename(profilePath);
    tag = sys::path::stem(base).str();
  }
  if (typedumpPath.empty())
    typedumpPath = ancestorPath(argv[0], {"tools", "contract", "build",
                                          "spinel-typedump"});
  if (typedumpPath.empty())
    return die("typedump-missing: cannot find tools/contract/build/"
               "spinel-typedump (pass --typedump PATH)");
  // spinel-fs-codegen writes the object, as for fs-emit: the one beside this
  // executable unless --codegen names another.
  if (codegenPath.empty())
    codegenPath = ancestorPath(argv[0], {"spinel-fs-codegen"});
  if (codegenPath.empty())
    return die("codegen-missing: cannot find spinel-fs-codegen (pass --codegen "
               "PATH)");
  // ---- profile ------------------------------------------------------------
  auto yaml = MemoryBuffer::getFile(profilePath);
  if (!yaml)
    return die("unreadable: " + profilePath + ": " + yaml.getError().message());
  bool profileRejected = false;
  auto diag = [&](const fs_::Rejection &r) {
    if (profileRejected)
      return;
    profileRejected = true;
    errs() << fs_::formatRejection(r) << "\n";
  };
  std::string ledgerInfra;
  if (menusPath.empty())
    menusPath = ancestorPath(argv[0], {"tools", "platform", "menus.yaml"});
  auto profile = fs_::resolveFreestandingProfile(
      profilePath, (*yaml)->getBuffer(), menusPath, diag, &ledgerInfra);
  if (!ledgerInfra.empty())
    return die("ledger: " + ledgerInfra);
  if (!profile)
    return 1;

  auto widthSource = MemoryBuffer::getFile(source);
  if (!widthSource) return die("unreadable source: " + source);
  const unsigned targetBits = spinel_mlir::targetIntegerPointerBits(profile->triple());
  const unsigned profileBits = spinel_mlir::profileIntegerBits(profile->intWidth());
  const bool int64 = spinel_mlir::declaresInt64((*widthSource)->getBuffer());
  // Decision 0019, revised 2026-10-21: a 32-bit target has no 64-bit body
  // unless tools/core/int64-allow.tsv lists the source.
  if (targetBits == 32 && int64) {
    const spinel_mlir::Int64Allow allow =
        spinel_mlir::int64Allowed((*widthSource)->getBuffer(), int64AllowPath);
    if (!allow.error.empty())
      return die("int64-allow-table: " + allow.error);
    if (!allow.listed)
      return die("int-width-int64-refused: " + source + ":1: `# spinel: int64` declares a "
                 "64-bit body, the target's pointers are 32 bits, and " + allow.table +
                 " does not list this source; remove the declaration and compute at "
                 "32 bits, or build for a 64-bit target");
  }
  if (!targetBits || !profileBits || (targetBits != profileBits && !int64))
    return die("int-width-mismatch: profile and target width disagree");
  const std::string widthArg = "--int-width=" + std::to_string(int64 ? 64 : profileBits);

  // Four contract faces.
  ScopedTempDir tmp;
  if (std::error_code ec = tmp.create())
    return die("temp-dir-failed: " + ec.message());
  static const StringRef kFaces[4] = {"ast", "nodes", "locals", "methods"};
  std::unique_ptr<MemoryBuffer> faces[4];
  for (int f = 0; f < 4; ++f) {
    std::string o = tmp.file((kFaces[f] + ".txt").str());
    std::string e = tmp.file((kFaces[f] + ".err").str());
    StringRef args[] = {typedumpPath, source, widthArg, kFaces[f]};
    std::optional<StringRef> redirects[] = {StringRef(""), StringRef(o),
                                            StringRef(e)};
    std::string execError;
    int rc = sys::ExecuteAndWait(typedumpPath, args, std::nullopt, redirects, 0,
                                 0, &execError);
    if (!execError.empty())
      return die("subprocess-failed: cannot run " + typedumpPath + ": " +
                 execError);
    if (rc != 0) {
      errs() << "spinel-fs-grad: typedump-failed: " << kFaces[f] << "\n";
      if (auto eb = MemoryBuffer::getFile(e))
        errs() << (*eb)->getBuffer();
      return 1;
    }
    auto b = MemoryBuffer::getFile(o);
    if (!b)
      return die("unreadable: " + o + ": " + b.getError().message());
    faces[f] = std::move(*b);
  }
  contract::ContractInputs in{faces[0]->getBuffer(), faces[1]->getBuffer(),
                              faces[2]->getBuffer(), faces[3]->getBuffer()};
  bool contractBad = false;
  auto creject = [&](StringRef line) {
    if (contractBad)
      return;
    contractBad = true;
    errs() << "spinel-fs-grad: contract-rejected: " << line << "\n";
  };
  auto module = contract::readContract(in, creject);
  if (!module)
    return 1;

  // Gate 1 uses lightweight boundary reading before D1/D2, matching frozen order. Full matching
  // belongs to kernel IR construction; checking missing def early would report D2 instead of g10.
  std::string readError;
  auto fsDecls = fs_::readGradBoundaryDeclarations(*module, readError);
  if (!fsDecls)
    return die(readError);
  std::map<std::string, const fs_::FsDecl *> byName;
  for (const fs_::FsDecl &d : *fsDecls)
    byName[d.name] = &d;

  std::vector<fs_::GradReject> rejects;
  auto gradDecls =
      fs_::readFreestandingGradDeclarations(*module, rejects, readError);
  if (!gradDecls) {
    // Read-time g08 Reject does not create a REFUSE row or rejects.tsv: frozen catches it and dies
    // immediately. Preserve spelling/order.
    if (!rejects.empty())
      return die(rejects.front().code + ": " + rejects.front().message);
    return die(readError);
  }

  // ---- gate G1-fs ---------------------------------------------------------
  if (gradDecls->empty())
    return die("no `freestanding_grad_def` in " + source);
  std::vector<const fs_::FsGradDecl *> accepted;
  for (const fs_::FsGradDecl &g : *gradDecls) {
    auto it = byName.find(g.name);
    const fs_::FsDecl *fs = it == byName.end() ? nullptr : it->second;
    auto pnames = fs_::readDefParameterNames(*module, g.name);
    fs_::GradReject r;
    if (fs_::checkGradGate1(g, fs, pnames ? &*pnames : nullptr, r))
      accepted.push_back(&g);
    else
      rejects.push_back(r);
  }

  // ---- rejects.tsv --------------------------------------------------------
  if (std::error_code ec = sys::fs::create_directories(outDir))
    return die("out-dir-failed: " + outDir + ": " + ec.message());
  {
    SmallString<128> p(outDir);
    sys::path::append(p, "rejects.tsv");
    std::error_code ec;
    raw_fd_ostream os(p, ec);
    if (ec)
      return die("rejects-write-failed: " + ec.message());
    os << "target\tline\tcode\tmessage\n";
    for (const fs_::GradReject &r : rejects) {
      std::string m = r.message;
      for (char &ch : m)
        if (ch == '\t')
          ch = ' ';
      os << r.target << "\t" << r.line << "\t" << r.code << "\t" << m << "\n";
    }
  }
  if (!rejects.empty() && !allowRejects) {
    for (const fs_::GradReject &r : rejects)
      errs() << "spinel-fs-grad: REFUSE " << r.target << " [" << r.code << "] "
             << r.message << "\n";
    return 1;
  }
  if (accepted.empty())
    return die("every declaration was refused");

  // ---- Generation ---------------------------------------------------------------
  auto outFile = [&](const Twine &name) {
    SmallString<128> p(outDir);
    sys::path::append(p, name);
    return std::string(p);
  };
  auto writeModule = [&](Module &m, const std::string &path) -> bool {
    std::error_code ec;
    raw_fd_ostream os(path, ec);
    if (ec) {
      errs() << "spinel-fs-grad: write-failed: " << path << ": " << ec.message()
             << "\n";
      return false;
    }
    m.print(os, nullptr);
    return true;
  };

  std::vector<fs_::GradTarget> targets;
  for (const fs_::FsGradDecl *g : accepted) {
    fs_::GradTarget t;
    t.grad = g;
    t.fs = byName.at(g->name);
    auto pn = fs_::readDefParameterNames(*module, g->name);
    t.pnames = *pn;
    targets.push_back(std::move(t));
  }

  // Kernel IR through the library, not a spinel-mlirgen subprocess.
  ScopedTempDir work;
  if (std::error_code ec = work.create())
    return die("temp-dir-failed: " + ec.message());
  auto runTool = [](StringRef tool, ArrayRef<StringRef> args, StringRef out,
                    StringRef err) {
    std::optional<StringRef> redirects[] = {StringRef(""), out, err};
    std::string execError;
    int rc = sys::ExecuteAndWait(tool, args, std::nullopt, redirects, 0, 0,
                                 &execError);
    if (!execError.empty()) {
      errs() << "spinel-fs-grad: subprocess-failed: cannot run " << tool << ": "
             << execError << "\n";
      return -1;
    }
    return rc;
  };
  auto tempPath = [&](StringRef name) { return work.file(name); };

  LLVMContext llvmContext;
  fs_::EmitRequest kreq;
  kreq.sourcePath = source;
  kreq.profilePath = profilePath;
  kreq.typedumpPath = typedumpPath;
  kreq.menusPath = menusPath;
  kreq.int64AllowPath = int64AllowPath;
  kreq.codegenPath = codegenPath;
  fs_::EmitStatus kstatus = fs_::EmitStatus::Infrastructure;
  auto kern = fs_::emitFreestandingModule(kreq, llvmContext, runTool, tempPath,
                                          diag, errs(), kstatus);
  if (!kern)
    return die("spinel-mlirgen --freestanding failed (in-process)");
  std::string kll = outFile("kern." + tag + ".ll");
  if (!writeModule(*kern, kll))
    return 1;

  // Shim reuses the kernel triple/data layout.
  auto shim = std::make_unique<Module>("spinel-fs-grad.shim", llvmContext);
  shim->setTargetTriple(kern->getTargetTriple());
  shim->setDataLayout(kern->getDataLayout());
  std::string shimError;
  auto shimAttrs = fs_::shimAttrsFromCflags(profile->cflags());
  if (!fs_::buildEnzymeShim(*shim, targets, shimAttrs, shimError))
    return die(shimError);
  std::string sll = outFile("shim." + tag + ".ll");
  if (!writeModule(*shim, sll))
    return 1;
  // Retain frozen pre-link layout validation even though shared-profile construction should prevent
  // mismatch: unnoticed mismatch would change every pointer meaning.
  if (kern->getDataLayoutStr() != shim->getDataLayoutStr())
    return die("data layout mismatch for profile " + profilePath + ":\n  kernel " +
               kern->getDataLayoutStr() + "\n  shim   " + shim->getDataLayoutStr());

  if (Linker::linkModules(*kern, std::move(shim)))
    return die("llvm-link failed (in-process)");
  std::string lll = outFile("linked." + tag + ".ll");
  if (!writeModule(*kern, lll))
    return 1;

  // Enzyme in process; missing plugin is a visible rc 1.
  if (enzymePath.empty())
    enzymePath = ancestorPath(argv[0], {"third_party", "enzyme", "build",
                                        "Enzyme", kEnzymePlugin});
  if (enzymePath.empty())
    return die("the Enzyme plugin is missing (build third_party/enzyme, see "
               "docs/tools/enzyme.md, or pass --enzyme PATH)");
  std::string pipeError;
  if (!fs_::runEnzyme(*kern, enzymePath, fastMath, pipeError))
    return die(pipeError);
  std::string rawll = outFile("enzyme." + tag + ".ll");
  if (!writeModule(*kern, rawll))
    return 1;
  // Collect adjoint names immediately after Enzyme, before cleanup inlines them.
  std::vector<std::string> adjoints = fs_::adjointNames(*kern);
  std::vector<std::string> fwdAdjoints = fs_::forwardAdjointNames(*kern);
  for (const fs_::FsGradDecl *g : accepted)
    if (g->hvp && fwdAdjoints.empty())
      return die("hvp: requested for " + g->name +
                 " but Enzyme produced no forward derivative of the reverse "
                 "wrapper (fwddiffe*) -- the forward-over-reverse chain broke "
                 "inside opt, and an absent product would otherwise be as "
                 "silent as R013 O2");
  // Gate G5.
  unsigned fmSites = fs_::fastMathSites(*kern);
  if (fmSites && !fastMath)
    return die("G5: the adjoint still carries fast-math flags (" +
               Twine(fmSites) +
               " site(s)). `fast` licences reassociation and FMA contraction, "
               "and the targets do not fuse alike -- the gradient would not be "
               "bit-identical.");

  if (!fs_::runGradCleanup(*kern, pipeError))
    return die(pipeError);
  std::string dll = outFile("grad." + tag + ".ll");
  if (!writeModule(*kern, dll))
    return 1;
  if (adjoints.empty())
    return die("Enzyme produced no adjoint (R013 O2: an empty adjoint is "
               "SILENT -- if this ever fires, the target is not the f64 "
               "function it claims)");
  unsigned nalloca = fs_::allocaCount(*kern);

  // 5. Minimize.
  std::vector<std::string> keep;
  for (const fs_::FsGradDecl *g : accepted) {
    keep.push_back(g->sym());
    if (g->hvp)
      keep.push_back(g->hvpSym());
  }
  if (!gradsOnly) {
    for (const fs_::FsGradDecl *g : accepted)
      keep.push_back(byName.at(g->name)->exportSymbol.empty()
                         ? ("spinel_" + g->name)
                         : byName.at(g->name)->exportSymbol);
    for (const fs_::FsDecl &d : *fsDecls)
      keep.push_back(d.exportSymbol.empty() ? ("spinel_" + d.name)
                                            : d.exportSymbol);
  }
  llvm::sort(keep);
  keep.erase(std::unique(keep.begin(), keep.end()), keep.end());
  if (!fs_::runGradInternalize(*kern, keep, pipeError))
    return die(pipeError);
  std::string mll = outFile("grad." + tag + ".min.ll");
  if (!writeModule(*kern, mll))
    return 1;

  std::string obj = outFile("grad." + tag + ".o");
  {
    // spinel-fs-codegen with the profile's cflags alone, which is what clang
    // was given here: not the emitter's -O2 -ffreestanding -fno-builtin.
    std::vector<StringRef> cc = {codegenPath, "--profile", profilePath};
    if (!menusPath.empty()) {
      cc.push_back("--menus");
      cc.push_back(menusPath);
    }
    for (StringRef a : {StringRef("--profile-cflags-only"), StringRef(mll),
                        StringRef("-o"), StringRef(obj)})
      cc.push_back(a);
    std::string ccErr = work.file("codegen.err");
    if (runTool(codegenPath, cc, "", ccErr) != 0) {
      errs() << "spinel-fs-grad: spinel-fs-codegen (object) failed\n";
      if (auto eb = MemoryBuffer::getFile(ccErr))
        errs() << (*eb)->getBuffer();
      return 1;
    }
  }

  // G2-fs checks that adjoints remain freestanding through the in-process gate.
  std::vector<fs_::UndefRow> undefRows;
  std::string gateInfra;
  bool clean = fs_::runUndefGate(obj, *profile, undefRows, &gateInfra);
  std::string undefTsv = outFile("undef." + tag + ".tsv");
  {
    std::error_code ec;
    raw_fd_ostream os(undefTsv, ec);
    if (ec)
      return die("undef-tsv-write-failed: " + ec.message());
    os << fs_::formatUndefTsv(undefRows);
  }
  if (!gateInfra.empty())
    return die("undef-gate: " + gateInfra);
  if (!clean) {
    for (const fs_::UndefRow &r : undefRows)
      if (r.verdict == "DENY")
        errs() << "spinel-fs-grad: G2-fs DENY " << r.verdict << "\t"
               << r.object << "\t" << r.symbol << "\t" << r.reason << "\n";
    return die("the adjoint object needs symbols the profile does not allow "
               "(D-3 stage 2 applied to the DERIVATIVE)");
  }

  // Result tables preserve frozen columns/spelling.
  {
    std::error_code ec;
    raw_fd_ostream os(outFile("targets." + tag + ".tsv"), ec);
    if (ec)
      return die("targets-write-failed: " + ec.message());
    os << "target\tprimal_sym\tgrad_sym\twrt\ttol\tparams\treturns\n";
    for (const fs_::GradTarget &t : targets) {
      std::string ps;
      for (size_t i = 0; i < t.fs->params.size(); ++i) {
        if (i)
          ps += ",";
        const fs_::FsParam &p = t.fs->params[i];
        if (p.kind == fs_::FsParam::Kind::Buffer)
          ps += "[" + p.type + "_buf," + p.direction + "]";
        else if (p.kind == fs_::FsParam::Kind::Len)
          ps += ":len";
        else
          ps += ":" + p.type;
      }
      std::string wrt;
      for (size_t i = 0; i < t.grad->wrt.size(); ++i) {
        if (i)
          wrt += "+";
        wrt += t.grad->wrt[i];
      }
      char tolBuf[64];
      std::snprintf(tolBuf, sizeof(tolBuf), "%g", t.grad->tol);
      os << t.grad->name << "\t"
         << (t.fs->exportSymbol.empty() ? ("spinel_" + t.fs->name)
                                        : t.fs->exportSymbol)
         << "\t" << t.grad->sym() << "\t" << wrt << "\t" << tolBuf << "\t" << ps
         << "\t" << t.fs->returns << "\n";
    }
  }
  std::vector<std::string> defined;
  {
    // The object's defined external symbols, as `llvm-nm --defined-only
    // --extern-only` printed them.
    auto buf = MemoryBuffer::getFile(obj);
    if (!buf)
      return die("cannot read " + obj + ": " + buf.getError().message());
    auto file = object::ObjectFile::createObjectFile((*buf)->getMemBufferRef());
    if (!file)
      return die("cannot read " + obj + ": " + toString(file.takeError()));
    for (const object::SymbolRef &sym : (*file)->symbols()) {
      auto flags = sym.getFlags();
      if (!flags)
        return die("cannot read " + obj + ": " + toString(flags.takeError()));
      if ((*flags & object::SymbolRef::SF_Undefined) ||
          !(*flags & object::SymbolRef::SF_Global) ||
          (*flags & object::SymbolRef::SF_FormatSpecific))
        continue;
      auto name = sym.getName();
      if (!name)
        return die("cannot read " + obj + ": " + toString(name.takeError()));
      defined.push_back(name->str());
    }
  }
  llvm::sort(defined);
  {
    std::error_code ec;
    raw_fd_ostream os(outFile("build." + tag + ".tsv"), ec);
    if (ec)
      return die("build-write-failed: " + ec.message());
    auto join = [](ArrayRef<std::string> v) {
      std::string out;
      for (size_t i = 0; i < v.size(); ++i) {
        if (i)
          out += ",";
        out += v[i];
      }
      return out;
    };
    os << "key\tvalue\n";
    os << "profile\t" << sys::path::filename(profilePath) << "\n";
    os << "triple\t" << profile->triple() << "\n";
    os << "adjoints\t" << join(adjoints) << "\n";
    bool anyHvp = false;
    for (const fs_::FsGradDecl *g : accepted)
      anyHvp |= g->hvp;
    if (anyHvp)
      os << "fwd_adjoints\t" << join(fwdAdjoints) << "\n";
    os << "alloca_in_module\t" << nalloca << "\n";
    os << "fastmath_sites\t" << fmSites << "\n";
    std::vector<std::string> allowed;
    for (const fs_::UndefRow &r : undefRows)
      if (r.verdict == "ALLOW")
        allowed.push_back(r.symbol);
    llvm::sort(allowed);
    os << "undefined\t" << join(allowed) << "\n";
    os << "exports\t" << join(defined) << "\n";
    uint64_t size = 0;
    sys::fs::file_size(obj, size);
    os << "object_bytes\t" << size << "\n";
  }
  if (!headerPath.empty()) {
    std::error_code ec;
    raw_fd_ostream os(headerPath, ec);
    if (ec)
      return die("header-write-failed: " + ec.message());
    os << gradHeader(targets, tag);
  }

  errs() << "spinel-fs-grad: " << tag << " -- " << accepted.size()
         << " gradient(s), adjoint(s) ";
  for (size_t i = 0; i < adjoints.size(); ++i)
    errs() << (i ? "," : "") << adjoints[i];
  uint64_t objBytes = 0;
  sys::fs::file_size(obj, objBytes);
  errs() << ", " << nalloca << " alloca, " << objBytes << " B\n";
  for (size_t i = 0; i < accepted.size(); ++i)
    outs() << (i ? "," : "") << accepted[i]->sym();
  outs() << "\n";
  (void)verbose;
  return 0;
}
