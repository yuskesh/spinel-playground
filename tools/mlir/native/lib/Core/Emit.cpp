void emitCoreFailHeader(llvm::raw_ostream &os) {
  using scalar::CoreFailKind;
  using scalar::CoreFailOp;
  auto n = [](auto v) { return static_cast<int32_t>(v); };
  os << "/* Generated by spinel-core-emit. Decision 0015: the failure hook of a\n"
        "   native scalar core object. The core object calls it and does not\n"
        "   continue; the hosted program defines it. */\n"
        "#ifndef SPINEL_CORE_FAIL_H\n"
        "#define SPINEL_CORE_FAIL_H\n"
        "#include <stdint.h>\n\n"
        "/* kind */\n"
        "#define SPC_CORE_FAIL_OVERFLOW " << n(CoreFailKind::Overflow) << "\n"
     << "#define SPC_CORE_FAIL_ZERO_DIVISION " << n(CoreFailKind::ZeroDivision) << "\n"
     << "#define SPC_CORE_FAIL_NEGATIVE_EXPONENT " << n(CoreFailKind::NegativeExponent) << "\n"
     << "#define SPC_CORE_FAIL_INTRINSIC " << n(CoreFailKind::Intrinsic) << "\n"
     << "\n"
     << "/* op */\n"
     << "#define SPC_CORE_OP_NONE " << n(CoreFailOp::None) << "\n"
     << "#define SPC_CORE_OP_ADD " << n(CoreFailOp::Add) << "\n"
     << "#define SPC_CORE_OP_SUB " << n(CoreFailOp::Sub) << "\n"
     << "#define SPC_CORE_OP_MUL " << n(CoreFailOp::Mul) << "\n"
     << "#define SPC_CORE_OP_DIV " << n(CoreFailOp::Div) << "\n"
     << "#define SPC_CORE_OP_MOD " << n(CoreFailOp::Mod) << "\n"
     << "#define SPC_CORE_OP_NEG " << n(CoreFailOp::Neg) << "\n"
     << "#define SPC_CORE_OP_SHL " << n(CoreFailOp::Shl) << "\n"
     << "#define SPC_CORE_OP_ABS " << n(CoreFailOp::Abs) << "\n"
     << "#define SPC_CORE_OP_POW " << n(CoreFailOp::Pow) << "\n\n"
     << "__attribute__((noreturn)) void " << scalar::kCoreFailHook
     << "(int32_t kind, int32_t op);\n\n"
        "#endif\n";
}

void emitCoreFailShim(llvm::raw_ostream &os) {
  using scalar::CoreFailKind;
  using scalar::CoreFailOp;
  auto n = [](auto v) { return static_cast<int32_t>(v); };
  os << "/* Generated by spinel-core-emit. Decision 0015: the hosted definition of\n"
        "   the native scalar core object's failure hook. Its own translation unit:\n"
        "   it includes no runtime header and calls one runtime entry, which runs\n"
        "   the at_exit hooks, prints what an uncaught raise prints and exits with\n"
        "   the uncaught status, consulting no rescue frame. */\n"
        "#include <stdint.h>\n\n"
        "__attribute__((noreturn)) void sp_abort_uncaught(const char *cls, const char *msg);\n\n"
        "__attribute__((noreturn)) void " << scalar::kCoreFailHook
     << "(int32_t kind, int32_t op) {\n"
        "  if (kind == " << n(CoreFailKind::ZeroDivision) << ")\n"
        "    sp_abort_uncaught(\"ZeroDivisionError\", \"divided by 0\");\n"
        "  if (kind == " << n(CoreFailKind::NegativeExponent) << ")\n"
        "    sp_abort_uncaught(\"RangeError\", \"negative exponent\");\n";
  // Decision 0042 stage 4: an intrinsic's failure, by the op the core object
  // passes (failOp), with the text the hosted prelude raises.
  os << "  if (kind == " << n(CoreFailKind::Intrinsic) << ") {\n"
        "    switch (op) {\n";
  for (const core::CoreIntrinsic &in : core::kCoreIntrinsics) {
    if (core::checksI32Operands(in))
      os << "    case " << core::failOp(in, core::IntrinsicFailure::Operand)
         << ": sp_abort_uncaught(\"RangeError\", \""
         << core::failText(in, core::IntrinsicFailure::Operand) << "\");\n";
    if (in.countMax)
      os << "    case " << core::failOp(in, core::IntrinsicFailure::Count)
         << ": sp_abort_uncaught(\"RangeError\", \""
         << core::failText(in, core::IntrinsicFailure::Count) << "\");\n";
  }
  os << "    }\n"
        "  }\n"
        "  if (kind == " << n(CoreFailKind::Overflow) << ") {\n"
        "    switch (op) {\n";
  const std::pair<CoreFailOp, const char *> ops[] = {
      {CoreFailOp::Add, "+"}, {CoreFailOp::Sub, "-"}, {CoreFailOp::Mul, "*"},
      {CoreFailOp::Div, "/"}, {CoreFailOp::Mod, "%"}, {CoreFailOp::Neg, "-@"},
      {CoreFailOp::Shl, "<<"}, {CoreFailOp::Abs, "abs"}, {CoreFailOp::Pow, "**"}};
  for (const auto &o : ops)
    os << "    case " << n(o.first) << ": sp_abort_uncaught(\"RangeError\", "
       << "\"integer overflow in " << o.second << "\");\n";
  os << "    }\n"
        "  }\n"
        "  /* A kind or operator this shim was not generated for: the core object\n"
        "     and the shim disagree, and there is no exception to name. */\n"
        "  __builtin_trap();\n"
        "}\n";
}

CoreEmitStatus emitCoreObject(const contract::ContractModule &module,
                              const CoreEmitRequest &request, RunToolFn runTool,
                              TempPathFn tempPath, CoreDiagnosticFn diag) {
  if (request.roots.empty())
    return diag(line("bad-request", "no root was selected")), CoreEmitStatus::BadRequest;
  if (request.outputPath.empty())
    return diag(line("bad-request", "no output path")), CoreEmitStatus::BadRequest;
  for (const CoreRootRequest &r : request.roots) {
    if (r.identity.empty())
      return diag(line("bad-request", "a root has an empty identity")), CoreEmitStatus::BadRequest;
    // The symbol is the caller's to supply. Deriving one here would create the
    // second derivation the mapping exists to prevent, so an absent symbol is a
    // refusal rather than something to fill in.
    if (r.symbol.empty())
      return diag(line("bad-request", "root '" + r.identity + "' has no symbol; it must come "
                                      "from the hosted compiler's mapping")),
             CoreEmitStatus::BadRequest;
    // The boundary this side can define. Everything it lowers is machine-width
    // integer, so a hosted prototype in any other type is a disagreement about
    // the call -- and one the linker cannot see, because a symbol name carries
    // no types. Checked against the mapping's own signature text, which is the
    // hosted compiler's declared contract for that symbol.
    if (!r.signature.empty()) {
      llvm::StringRef sig(r.signature);
      const bool intReturn = sig.starts_with("sp_int ");
      bool intParams = true;
      const size_t open = sig.find('(');
      if (open == llvm::StringRef::npos) intParams = false;
      else {
        llvm::StringRef args = sig.substr(open + 1);
        args.consume_back(")");
        if (!args.empty() && args != "void")
          for (auto part : llvm::split(args, ","))
            if (!part.ltrim().starts_with("sp_int ")) intParams = false;
      }
      if (!intReturn || !intParams) {
        diag(line("boundary-mismatch",
                  "the hosted prototype for '" + r.identity + "' is \"" + r.signature +
                      "\"; this path lowers machine-width integers only, so the two would "
                      "disagree about the call and the link would not notice"));
        return CoreEmitStatus::InputRejected;
      }
    }
  }

  // 1. Admission. The same checker the source side runs, on the same module --
  //    not a second opinion about what is admissible.
  std::vector<std::string> entries;
  // Decision 0026 step 4: the calls each root's check resolved, for the
  // selector and the lowering to read.
  scalar::ScalarImportOptions selection;
  selection.callEdges.emplace();
  // Decision 0026 step 5: this route compiles for the host it runs on
  // (hostTargetLayout() reads the same width).
  selection.pointerBits = sizeof(void *) * 8;
  // Decision 0042: the bitwise operators and the shifts, admitted by the
  // checker above and lowered by `Abort`, the shifts with the hook.
  selection.bitOperators = true;
  for (const CoreRootRequest &r : request.roots) {
    EligibilityReport report = checkEligibility(module, r.identity);
    if (!report.checked()) {
      for (const Diagnostic &d : report.diagnostics)
        diag(llvm::Twine("spinel-core-emit: not-eligible: " + d.reason + ": " +
                         d.detail + " (" + d.location + ")").str());
      if (report.diagnostics.empty())
        diag(line("not-eligible", "'" + r.identity + "' names no method here"));
      return CoreEmitStatus::InputRejected;
    }
    // The checker's own closure is what gets lowered. Selecting a different set
    // here would mean the thing checked and the thing emitted are two things.
    for (const std::string &m : report.methods)
      if (std::find(entries.begin(), entries.end(), m) == entries.end())
        entries.push_back(m);
    for (const CallEdge &e : report.callEdges) (*selection.callEdges)[e.nodeId] = e.callee;
  }

  // 2. Selection, through the importer the freestanding lane already uses. No
  //    declaration is read and no option but the checker's call edges is set:
  //    `freestandingTypes` stays false, so no declaration-shaped boundary and
  //    no trap policy can enter through this path.
  bool selectionFailed = false;
  auto scalarDiag = [&](llvm::StringRef m) {
    selectionFailed = true;
    diag(("spinel-core-emit: not-lowerable: " + m).str());
  };
  auto program = scalar::selectScalarProgram(module, entries, scalarDiag, selection);
  if (!program || selectionFailed)
    return CoreEmitStatus::InputRejected;

  // 3. Import. Decision 0015: `Abort` checks every admitted arithmetic
  //    operation and sends a failure to the one hook, which does not return.
  //    `None` would have defined wrapping, and it was safe only while
  //    eligibility refused arithmetic outright.
  mlir::MLIRContext context;
  context.loadDialect<mlir::func::FuncDialect, mlir::arith::ArithDialect,
                      mlir::cf::ControlFlowDialect, mlir::LLVM::LLVMDialect,
                      mlir::spinel::SpinelDialect>();
  auto imported = scalar::importScalarProgram(
      module, *program, context, scalar::OverflowMode::Abort, scalarDiag,
      /*emitCheckedArithmetic=*/false, /*trapHook=*/"");
  if (!imported || selectionFailed)
    return CoreEmitStatus::InputRejected;

  mlir::ModuleOp mod = *imported;

  // 4. Naming. The root takes the symbol the mapping gave it; every other
  //    function in the closure becomes private, so the object exports the
  //    selected roots and nothing else. The rename goes through SymbolTable so
  //    call sites inside the module are updated with it.
  mlir::SymbolTable symbols(mod);
  for (const CoreRootRequest &r : request.roots) {
    // The importer names a method `sp_<name>` (MlirGen). That is ITS internal
    // convention, not the mapping's, and this is the one place that depends on
    // it -- so if it ever changes, the failure below names every function the
    // module does have instead of leaving the caller to guess.
    const std::string internal = "sp_" + r.identity;
    auto fn = symbols.lookup<mlir::func::FuncOp>(internal);
    if (!fn) {
      std::string have;
      mod.walk([&](mlir::func::FuncOp f) {
        if (!have.empty()) have += ", ";
        have += f.getSymName().str();
      });
      diag(line("bad-request",
                "the lowered closure has no function '" + internal + "' for root '" +
                    r.identity + "'; it defines: " + (have.empty() ? "nothing" : have)));
      return CoreEmitStatus::BadRequest;
    }
    if (symbols.lookup(r.symbol)) {
      diag(line("bad-request", "the mapped symbol '" + r.symbol +
                                   "' already exists in the lowered closure"));
      return CoreEmitStatus::BadRequest;
    }
    if (failed(symbols.rename(fn, r.symbol))) {
      diag(line("bad-request", "cannot rename '" + r.identity + "' to '" + r.symbol + "'"));
      return CoreEmitStatus::BadRequest;
    }
  }
  std::set<std::string> exported;
  for (const CoreRootRequest &r : request.roots) exported.insert(r.symbol);
  mod.walk([&](mlir::func::FuncOp fn) {
    if (exported.count(fn.getSymName().str())) return;
    fn.setPrivate();
    // `private` visibility alone did not stop the helper being exported from
    // the object -- measured: the module printed `func.func private @sp_lower`
    // and nm still listed it as a global. The conversion to LLVM keeps external
    // linkage for a defined function unless it is told otherwise, so say so.
    fn->setAttr("llvm.linkage", mlir::LLVM::LinkageAttr::get(
                                    &context, mlir::LLVM::Linkage::Internal));
  });

  if (mlir::failed(mlir::verify(mod))) {
    diag(line("internal", "the lowered closure does not verify"));
    return CoreEmitStatus::Infrastructure;
  }

  // 5. Emission, through the shared pipeline. Hosted target with an empty hook:
  //    the freestanding hook would be a trap policy, and this slice has none.
  if (!request.emitMlirPath.empty()) {
    scalar::HostEmitRequest mreq;
    mreq.kind = scalar::HostEmitRequest::Kind::Mlir;
    mreq.outputPath = request.emitMlirPath;
    if (!scalar::emitHostModule(mod, mreq, runTool, tempPath, diag))
      return CoreEmitStatus::Infrastructure;
  }
  if (!request.shimPath.empty()) {
    std::error_code ec;
    llvm::raw_fd_ostream os(request.shimPath, ec, llvm::sys::fs::OF_Text);
    if (ec) {
      diag(line("io", "cannot write " + request.shimPath + ": " + ec.message()));
      return CoreEmitStatus::Infrastructure;
    }
    emitCoreFailShim(os);
    os.close();
    if (os.has_error()) {
      diag(line("io", "writing " + request.shimPath + " failed"));
      return CoreEmitStatus::Infrastructure;
    }
  }
  if (!request.headerPath.empty()) {
    std::error_code ec;
    llvm::raw_fd_ostream os(request.headerPath, ec, llvm::sys::fs::OF_Text);
    if (ec) {
      diag(line("io", "cannot write " + request.headerPath + ": " + ec.message()));
      return CoreEmitStatus::Infrastructure;
    }
    emitCoreFailHeader(os);
    os.close();
    if (os.has_error()) {
      diag(line("io", "writing " + request.headerPath + " failed"));
      return CoreEmitStatus::Infrastructure;
    }
  }
  scalar::HostEmitRequest req;
  req.kind = scalar::HostEmitRequest::Kind::Obj;
  req.outputPath = request.outputPath;
  req.clangPath = request.clangPath;
  req.clangArgs = request.clangArgs;
  if (!scalar::emitHostModule(mod, req, runTool, tempPath, diag))
    return CoreEmitStatus::Infrastructure;
  return CoreEmitStatus::Ok;
}

