std::optional<ExternArtifacts>
repairExternModule(llvm::StringRef foreignModule, llvm::StringRef where,
                   ExternDiagnosticFn diag) {
  RepairSites sites = scanRepairSites(foreignModule);
  if (sites.malformedConv) {
    diag(kCheckFailed, (where + "a stablehlo.convolution window is not in the"
                                " repairable shape; this tool does not guess it")
                           .str());
    return std::nullopt;
  }
  ExternArtifacts art;
  if (sites.convWindow || sites.dynamicReshape) {
    if (!repairForeignModule(foreignModule, sites, art, diag, where))
      return std::nullopt;
    return art;
  }
  // If no repairs apply, return identical text: repairing a repaired module is byte-idempotent.
  art.repairedModule = foreignModule.str();
  return art;
}

std::optional<ExternArtifacts>
checkExtern(const TensorExtern &decl, llvm::StringRef foreignModule,
            llvm::StringRef modulePath, ExternDiagnosticFn diag) {
  const std::string where = decl.where() + ": ";
  auto fail = [&](llvm::StringRef category, const llvm::Twine &detail)
      -> std::optional<ExternArtifacts> {
    diag(category, detail.str());
    return std::nullopt;
  };

  // ---- module / entry ----------------------------------------------------
  llvm::SmallVector<llvm::StringRef, 0> lines;
  foreignModule.split(lines, '\n');
  const std::string moduleNeedle = "module @" + decl.vmModule;
  const std::string entryNeedle = "func.func public @" + decl.entry;
  unsigned moduleHits = 0, entryHits = 0;
  llvm::StringRef entryLine;
  for (llvm::StringRef line : lines) {
    llvm::StringRef t = line.ltrim();
    if (t.starts_with(moduleNeedle)) ++moduleHits;
    if (t.starts_with(entryNeedle)) { ++entryHits; entryLine = t; }
  }
  if (moduleHits != 1)
    return fail(kCheckFailed, where + "module @" + decl.vmModule + " appears " +
                                  llvm::Twine(moduleHits) + " times in " +
                                  modulePath);
  if (entryHits != 1)
    return fail(kCheckFailed, where + "func.func public @" + decl.entry +
                                  " appears " + llvm::Twine(entryHits) +
                                  " times in " + modulePath);

  // Read signature tensor types at general rank.
  struct Ty { llvm::SmallVector<int64_t, 4> dims; std::string elt; std::string text; };
  llvm::SmallVector<Ty, 8> tys;
  {
    llvm::StringRef rest = entryLine;
    while (true) {
      size_t at = rest.find("tensor<");
      if (at == llvm::StringRef::npos) break;
      rest = rest.substr(at);
      size_t end = rest.find('>');
      if (end == llvm::StringRef::npos) break;
      llvm::StringRef whole = rest.take_front(end + 1);
      llvm::StringRef inner = whole.drop_front(strlen("tensor<")).drop_back(1);
      Ty t; t.text = whole.str();
      llvm::SmallVector<llvm::StringRef, 6> parts;
      inner.split(parts, 'x');
      for (size_t i = 0; i + 1 < parts.size(); ++i) {
        int64_t v = 0;
        t.dims.push_back(parts[i] == "?" ? -1
                         : (!parts[i].getAsInteger(10, v) ? v : -2));
      }
      t.elt = parts.empty() ? "" : parts.back().str();
      tys.push_back(std::move(t));
      rest = rest.substr(end + 1);
    }
  }
  const size_t want = decl.params.size() + 1;
  if (tys.size() != want)
    return fail(kCheckFailed,
                where + "entry takes " + llvm::Twine(decl.params.size()) +
                    " ranked tensor(s) and returns 1 in the declaration, but " +
                    modulePath + " has " + llvm::Twine(tys.size()) +
                    " tensor type(s) at the boundary");

  // Admit only shim-supported element types.
  static const char *kElts[] = {"f32", "ui8", "f16", "i8", "i32"};
  for (const Ty &t : tys)
    if (!llvm::is_contained(kElts, t.elt))
      return fail(kCheckFailed,
                  where + modulePath + " uses element type " + t.elt +
                      ", which sp_tensor_shim.c cannot allocate or transfer");

  // Match against declarations.
  std::vector<std::vector<TensorExtern::Dim>> shapes = decl.shapes;
  shapes.push_back(decl.returnsShape);
  // Show every shape together in Python list repr, e.g. [[None,784],[None,11]], so mismatched pairs
  // are visible rather than reporting one at a time.
  auto pyList = [](const std::vector<std::vector<std::string>> &rows) {
    std::string out = "[";
    for (size_t i = 0; i < rows.size(); ++i) {
      if (i) out += ", ";
      out += "[";
      for (size_t d = 0; d < rows[i].size(); ++d) {
        if (d) out += ", ";
        out += rows[i][d];
      }
      out += "]";
    }
    return out + "]";
  };
  std::vector<std::vector<std::string>> wantShape, gotShape;
  for (const auto &sh : shapes) {
    std::vector<std::string> row;
    for (const TensorExtern::Dim &v : sh)
      row.push_back(v.fixed ? std::to_string(v.value) : "None");
    wantShape.push_back(std::move(row));
  }
  for (const Ty &t : tys) {
    std::vector<std::string> row;
    for (int64_t d : t.dims) row.push_back(d < 0 ? "None" : std::to_string(d));
    gotShape.push_back(std::move(row));
  }
  if (wantShape != gotShape)
    return fail(kCheckFailed,
                where + "shapes: transcribes " + pyList(wantShape) + " but " +
                    modulePath + " says " + pyList(gotShape) +
                    " (a '?' in the module is a dimension variable in the"
                    " declaration and vice versa)");
  // Element types must match; declaration u8 is module ui8.
  {
    std::vector<std::string> wantDt;
    for (size_t i = 0; i < decl.params.size(); ++i)
      wantDt.push_back(i < decl.dtypes.size() ? decl.dtypes[i] : decl.dtype);
    wantDt.push_back(decl.returnsDtype.empty() ? decl.dtype : decl.returnsDtype);
    std::vector<std::string> wantElt, gotElt;
    for (const std::string &d : wantDt)
      wantElt.push_back(d == "u8" ? "ui8" : d);
    for (const Ty &t : tys) gotElt.push_back(t.elt);
    if (wantElt != gotElt) {
      auto pyStrs = [](const std::vector<std::string> &v) {
        std::string out = "[";
        for (size_t i = 0; i < v.size(); ++i) {
          if (i) out += ", ";
          out += "'" + v[i] + "'";
        }
        return out + "]";
      };
      return fail(kCheckFailed,
                  where + "the declaration says element types " +
                      pyStrs(wantElt) + " but " + modulePath + " says " +
                      pyStrs(gotElt) +
                      " (dtype:/dtypes:/returns_dtype: name what the Tensors are;"
                      " the shim allocates ui8 and i8 as DIFFERENT types)");
    }
  }

  // Frozen success line uses Python shape lists, mapping ? to None.
  std::string summary;
  {
    std::string sig;
    for (size_t i = 0; i < tys.size(); ++i) {
      if (i) sig += " -> ";
      std::string dims = "[";
      for (size_t d = 0; d < tys[i].dims.size(); ++d) {
        if (d) dims += ", ";
        dims += tys[i].dims[d] < 0 ? "None" : std::to_string(tys[i].dims[d]);
      }
      sig += dims + "]:" + tys[i].elt;
    }
    summary = decl.vmModule + " @" + decl.entry + " (" + sig + ") matches " +
              decl.where();
  }

  // Repairable defects remaining here mean --extern-repair was not requested, since callers perform
  // repairs before matching, as frozen order requires.
  RepairSites sites = scanRepairSites(foreignModule);
  if (sites.malformedConv)
    return fail(kCheckFailed,
                where + "a stablehlo.convolution window is not in the"
                        " repairable shape; this tool does not guess it");
  if (sites.convWindow || sites.dynamicReshape) {
    // Use frozen format_extern_defects wording/order: all dynamic_reshape sites in module order,
    // then convolution.
    const unsigned n = sites.dynamicReshape + sites.convWindow;
    std::string msg = where + modulePath.str() +
                      " cannot be reached through sp_tensor_shim.c as it stands (" +
                      std::to_string(n) + " finding(s)):";
    for (const auto &t : sites.reshapeTypes)
      msg += "\n  * [iree] stablehlo.dynamic_reshape " + t.first + " -> " +
             t.second +
             " -- iree-compile 3.11.0 marks this op illegal on BOTH backends and "
             "has no conversion for it (probe d01); it is the single op that made "
             "E037 bake one .vmfb per batch size.  It is a pure row-major reshape, "
             "so it can be rewritten to `tensor.reshape`, which IREE does compile "
             "(probe d02)";
    for (unsigned i = 0; i < sites.convWindow; ++i)
      msg += "\n  * [iree] stablehlo.convolution with no "
             "stride/lhs_dilate/rhs_dilate in its `window`"
             " -- stablehlo's printer omits a window attribute that equals its "
             "default, so a stride-1 dilation-1 convolution prints "
             "`window = {pad = ...}` or even `window = {}`.  IREE's "
             "stablehlo->linalg conversion then builds a linalg.conv_2d_nhwc_hwcf "
             "with no `strides`/`dilations` attribute and its OWN verifier rejects "
             "it (probe c01/c02/c05).  Writing the omitted defaults back changes no "
             "semantics";
    std::string kinds;
    if (sites.convWindow) kinds = "conv-window";
    if (sites.dynamicReshape) {
      if (!kinds.empty()) kinds += ", ";
      kinds += "dynamic-reshape";
    }
    msg += "\n  " + std::to_string(n) +
           " of these are REPAIRABLE by writing back what stablehlo's printer left "
           "out (" + kinds + ").  Pass --extern-repair " + decl.name +
           "=<out.mlir> to have this tool do it and check the result, instead of a "
           "hand-run script next to the build (E037's patch_conv_window.py).";
    return fail(kRepairRequired, msg);
  }
  ExternArtifacts art;
  art.summary = summary;
  return art;
}

