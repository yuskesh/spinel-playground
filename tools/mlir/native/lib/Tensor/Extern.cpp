// One shape dimension: a fixed integer or one symbolic name.
struct ExternDim {
  bool fixed = false;
  int64_t value = 0;   ///< For fixed dimensions.
  std::string symbol;  ///< For symbolic dimensions.
};

// Single declaration model renders both C table and Ruby dispatch.
struct ExternCheckDecl {
  std::string rubyName;
  std::string vmModule;
  std::string entry;
  std::array<ExternDim, 2> inputShape;
  std::array<ExternDim, 2> resultShape;
  std::string constraints;
  uint64_t signatureHash = 0;
  std::string fq() const { return vmModule + "." + entry; }
};

// 64-bit FNV-1a with sign bit cleared, using the same input string as Entry.sig.
uint64_t fnv1a64(llvm::StringRef s) {
  uint64_t h = 0xcbf29ce484222325ULL; // offset basis
  for (unsigned char c : s) {
    h ^= c;
    h *= 0x100000001b3ULL; // prime
  }
  return h;
}

struct Builder {
  const contract::ContractModule &module;
  ExternDiagnosticFn diag;
  bool failed = false;
  ExternCheckDecl decl;

  // Explicit constructor avoids missing-field-initializer warnings for defaulted members.
  Builder(const contract::ContractModule &m, ExternDiagnosticFn d)
      : module(m), diag(d) {}

  const contract::Node *node(int64_t id) const {
    for (const contract::Node &n : module.nodes())
      if (n.id == id)
        return &n;
    return nullptr;
  }

  // Report the first failure only.
  bool reject(llvm::StringRef category, const llvm::Twine &detail) {
    if (!failed) {
      failed = true;
      diag(category, detail.str());
    }
    return false;
  }

  std::string symbolValue(int64_t id) const {
    const contract::Node *n = node(id);
    std::string v;
    if (!n || n->kind != "SymbolNode" || !getString(*n, "value", v))
      return {};
    return v;
  }

  // Diagnostic prefixed by tensor_extern :name. Detail may differ from Python; native case tables
  // pin it literally.
  std::string where() const {
    return "tensor_extern :" + decl.rubyName + ": ";
  }

  bool run();
  bool readKeywords(const contract::Node &call);
  bool readShape(int64_t arrayId, std::array<ExternDim, 2> &out,
                 llvm::StringRef what);
  void finishModel();
};

// Rank-2 shape with positive integer or symbolic dimensions only.
bool Builder::readShape(int64_t arrayId, std::array<ExternDim, 2> &out,
                        llvm::StringRef what) {
  const contract::Node *arr = node(arrayId);
  std::vector<int64_t> elems;
  if (!arr || arr->kind != "ArrayNode" || !getArray(*arr, "elements", elems))
    return reject(kMalformed, where() + what + " is not an array");
  if (elems.size() != 2)
    return reject(kCheckFailed,
                  where() + what + " must be rank 2, found rank " +
                      llvm::Twine(elems.size()));
  for (auto [i, id] : llvm::enumerate(elems)) {
    const contract::Node *e = node(id);
    if (!e)
      return reject(kMalformed, where() + what + " has an unreadable dimension");
    if (e->kind == "IntegerNode") {
      int64_t v = 0;
      if (!getInteger(*e, "value", v) || v <= 0)
        return reject(kCheckFailed,
                      where() + what + " has a non-positive dimension");
      out[i] = ExternDim{true, v, {}};
      continue;
    }
    std::string sym = symbolValue(id);
    if (sym.empty())
      return reject(kMalformed, where() + what +
                                    " dimensions must be a positive integer or"
                                    " a symbol");
    out[i] = ExternDim{false, 0, sym};
  }
  return true;
}

bool Builder::readKeywords(const contract::Node &call) {
  int64_t argsId = -1;
  std::vector<int64_t> args;
  if (!getReference(call, "arguments", argsId) || argsId < 0)
    return reject(kMalformed, "tensor_extern has no arguments");
  const contract::Node *argsNode = node(argsId);
  if (!argsNode || !getArray(*argsNode, "arguments", args) || args.size() != 2)
    return reject(kMalformed,
                  "tensor_extern takes a kernel symbol and a keyword hash");
  decl.rubyName = symbolValue(args[0]);
  if (decl.rubyName.empty())
    return reject(kMalformed, "tensor_extern does not name a kernel symbol");

  const contract::Node *hash = node(args[1]);
  std::vector<int64_t> elements;
  if (!hash || hash->kind != "KeywordHashNode" ||
      !getArray(*hash, "elements", elements))
    return reject(kMalformed, where() + "tensor_extern has no keyword hash");

  // Pass 1 fixes the keyword set before checking values. Otherwise a malformed value could precede
  // a missing-key diagnostic and conceal that defect.
  int64_t vDtype = -1, vModule = -1, vEntry = -1, vParams = -1, vShapes = -1,
          vReturns = -1, vReturnsShape = -1;
  for (int64_t id : elements) {
    const contract::Node *assoc = node(id);
    int64_t keyId = -1, valId = -1;
    if (!assoc || assoc->kind != "AssocNode" ||
        !getReference(*assoc, "key", keyId) ||
        !getReference(*assoc, "value", valId))
      return reject(kMalformed, where() + "a keyword is not an assoc");
    std::string key = symbolValue(keyId);
    int64_t *slot = key == "dtype"          ? &vDtype
                    : key == "vm_module"    ? &vModule
                    : key == "entry"        ? &vEntry
                    : key == "params"       ? &vParams
                    : key == "shapes"       ? &vShapes
                    : key == "returns"      ? &vReturns
                    : key == "returns_shape" ? &vReturnsShape
                                             : nullptr;
    if (!slot)
      return reject(kMalformed, where() + "unknown keyword `" + key + "`");
    if (*slot >= 0)
      return reject(kMalformed, where() + "repeats the keyword `" + key + "`");
    *slot = valId;
  }
  // Name missing keywords with table-defined spelling.
  if (vReturnsShape < 0)
    return reject(kMalformed, where() + "returns_shape: is required");
  if (vDtype < 0 || vModule < 0 || vEntry < 0 || vParams < 0 || vShapes < 0 ||
      vReturns < 0)
    return reject(kMalformed,
                  where() + "needs dtype:, vm_module:, entry:, params:,"
                            " shapes:, returns: and returns_shape:");

  // Pass 2 checks values against closed sets.
  std::string dtype = symbolValue(vDtype);
  if (dtype != "f32")
    return reject(kCheckFailed,
                  where() + "dtype :" + dtype +
                      " is outside the CP2 subset (:f32 only)");
  decl.vmModule = symbolValue(vModule);
  decl.entry = symbolValue(vEntry);
  if (decl.vmModule.empty() || decl.entry.empty())
    return reject(kMalformed, where() + "vm_module: and entry: must be symbols");

  const contract::Node *params = node(vParams);
  std::vector<int64_t> paramKinds;
  if (!params || params->kind != "ArrayNode" ||
      !getArray(*params, "elements", paramKinds))
    return reject(kMalformed, where() + "params: is not an array of symbols");
  if (paramKinds.size() != 1 || symbolValue(paramKinds[0]) != "mat")
    return reject(kCheckFailed,
                  where() + "params: must be exactly [:mat] in the CP2 subset");
  if (symbolValue(vReturns) != "mat")
    return reject(kCheckFailed,
                  where() + "returns: must be :mat in the CP2 subset");

  const contract::Node *shapes = node(vShapes);
  std::vector<int64_t> shapeList;
  if (!shapes || shapes->kind != "ArrayNode" ||
      !getArray(*shapes, "elements", shapeList))
    return reject(kMalformed, where() + "shapes: is not an array");
  if (shapeList.size() != 1)
    return reject(kCheckFailed,
                  where() + "shapes: must hold exactly 1 input shape");
  if (!readShape(shapeList[0], decl.inputShape, "shapes:[0]"))
    return false;
  return readShape(vReturnsShape, decl.resultShape, "returns_shape:");
}

// Build constraints/signature hash from exactly the Entry.sig input spelling; define it once here.
void Builder::finishModel() {
  // Fixed dimensions use #K; a repeated symbolic dimension equals its first position, matching
  // frozen constraints.
  llvm::SmallVector<std::string, 4> parts;
  llvm::SmallVector<std::pair<std::string, std::string>, 4> seen;
  auto emit = [&](unsigned tensor, const std::array<ExternDim, 2> &shape) {
    for (unsigned d = 0; d < 2; ++d) {
      std::string here = (llvm::Twine(tensor) + ":" + llvm::Twine(d)).str();
      if (shape[d].fixed) {
        parts.push_back(here + "=#" + std::to_string(shape[d].value));
        continue;
      }
      bool bound = false;
      for (auto &s : seen)
        if (s.first == shape[d].symbol) {
          parts.push_back(here + "=" + s.second);
          bound = true;
          break;
        }
      if (!bound)
        seen.push_back({shape[d].symbol, here});
    }
  };
  emit(0, decl.inputShape);
  emit(1, decl.resultShape);
  decl.constraints = llvm::join(parts, ";");

  std::string sig = decl.rubyName + "|mat,mat|dest=1|ret=0|shape=" +
                    decl.constraints + "|fq=" + decl.fq() + "|nin=1";
  decl.signatureHash = fnv1a64(sig) & 0x7fffffffffffffffULL;
}

bool Builder::run() {
  const contract::Node *program = node(module.root());
  if (!program || program->kind != "ProgramNode")
    return reject(kMalformed, "the sealed AST has no ProgramNode root");
  int64_t stmtsId = -1;
  if (!getReference(*program, "statements", stmtsId))
    return reject(kMalformed, "ProgramNode has no statements");
  const contract::Node *stmts = node(stmtsId);
  std::vector<int64_t> body;
  if (!stmts || stmts->kind != "StatementsNode" ||
      !getArray(*stmts, "body", body))
    return reject(kMalformed, "the program root has no top-level statements");

  // Filter statement kinds/names, not raw count: the tensor shim defs share these statements.
  llvm::SmallVector<const contract::Node *, 2> externs;
  unsigned defs = 0;
  for (int64_t id : body) {
    const contract::Node *n = node(id);
    if (!n || n->kind != "CallNode")
      continue;
    int64_t recv = -1;
    if (getReference(*n, "receiver", recv) && recv >= 0)
      continue;
    std::string name;
    if (!getString(*n, "name", name))
      continue;
    if (name == "tensor_extern")
      externs.push_back(n);
    else if (name == "tensor_def")
      ++defs;
  }
  if (externs.size() != 1)
    return reject(kMalformed,
                  "expected exactly 1 top-level `tensor_extern`, found " +
                      llvm::Twine(externs.size()));
  if (defs != 0)
    return reject(kMalformed,
                  "CP2 does not accept `tensor_def` and `tensor_extern` in the"
                  " same file (found " + llvm::Twine(defs) + " tensor_def)");
  if (!readKeywords(*externs.front()))
    return false;
  finishModel();
  return true;
}

// External module matching reads five specified facts, not general MLIR/StableHLO body validation.

// Read tensor<AxBxf32> as two dimensions; ? is dynamic.
struct ForeignShape {
  bool ok = false;
  std::array<int64_t, 2> dims{}; ///< -1 = dynamic
  std::string spelling;          ///< Spelling used verbatim in diagnostics.
};

ForeignShape parseTensor2xf32(llvm::StringRef s) {
  ForeignShape r;
  llvm::StringRef body = s;
  if (!body.consume_front("tensor<") || !body.consume_back(">"))
    return r;
  if (!body.consume_back("xf32"))
    return r;
  llvm::SmallVector<llvm::StringRef, 4> parts;
  body.split(parts, 'x');
  if (parts.size() != 2)
    return r;
  for (auto [i, p] : llvm::enumerate(parts)) {
    if (p == "?") {
      r.dims[i] = -1;
      continue;
    }
    int64_t v = 0;
    if (p.getAsInteger(10, v) || v <= 0)
      return r;
    r.dims[i] = v;
  }
  r.ok = true;
  r.spelling = s.str();
  return r;
}

// Render declared shape [a,b] for diagnostics.
std::string spellDecl(const std::array<ExternDim, 2> &s) {
  std::string out = "[";
  for (unsigned i = 0; i < 2; ++i) {
    if (i)
      out += ", ";
    out += s[i].fixed ? std::to_string(s[i].value) : s[i].symbol;
  }
  return out + "]";
}

// Count repairable module sites.
struct RepairSites {
  unsigned convWindow = 0;
  unsigned dynamicReshape = 0;
  bool malformedConv = false; ///< Unsupported partial attributes, e.g. only some of the three.
  // Preserve source-to-destination types in module order for diagnostics: a count cannot identify
  // which reshape is affected.
  std::vector<std::pair<std::string, std::string>> reshapeTypes;
};

RepairSites scanRepairSites(llvm::StringRef text) {
  RepairSites r;
  llvm::SmallVector<llvm::StringRef, 0> lines;
  text.split(lines, '\n');
  for (llvm::StringRef line : lines) {
    if (line.contains("stablehlo.convolution")) {
      bool hasWindow = line.contains("window = {");
      bool hasStride = line.contains("stride = [");
      bool hasLhs = line.contains("lhs_dilate = [");
      bool hasRhs = line.contains("rhs_dilate = [");
      if (!hasWindow)
        continue;
      if (!hasStride && !hasLhs && !hasRhs) {
        // Read spatial rank from module dim_numbers; do not invent stride values externally.
        size_t at = line.find("dim_numbers = [");
        if (at == llvm::StringRef::npos) {
          r.malformedConv = true;
          continue;
        }
        llvm::StringRef layout =
            line.substr(at + strlen("dim_numbers = ["));
        layout = layout.take_front(layout.find(']'));
        unsigned spatial = 0;
        llvm::SmallVector<llvm::StringRef, 6> toks;
        layout.split(toks, ", ");
        for (llvm::StringRef t : toks) {
          int64_t v = 0;
          if (!t.trim().getAsInteger(10, v))
            ++spatial;
        }
        if (spatial != 2) {
          r.malformedConv = true; // Do not infer defaults outside rank 2.
          continue;
        }
        ++r.convWindow;
      } else if (!(hasStride && hasLhs && hasRhs)) {
        r.malformedConv = true; // Do not fill partially present attributes.
      }
      continue;
    }
    if (line.contains("stablehlo.dynamic_reshape")) {
      // Extract source/destination from : (tensor<A>,tensor<B>) -> tensor<C>.
      size_t colon = line.find(" : (");
      size_t arrow = line.find(") -> ", colon == llvm::StringRef::npos ? 0 : colon);
      if (colon != llvm::StringRef::npos && arrow != llvm::StringRef::npos) {
        llvm::StringRef ins = line.substr(colon + 4, arrow - colon - 4);
        llvm::StringRef dst = line.drop_front(arrow + 5);
        size_t sp = dst.find(' ');
        if (sp != llvm::StringRef::npos) dst = dst.take_front(sp);
        llvm::StringRef src = ins.take_front(ins.find(','));
        r.reshapeTypes.push_back({src.trim().str(), dst.trim().str()});
      }
    }
    if (line.contains("stablehlo.dynamic_reshape"))
      ++r.dynamicReshape;
  }
  return r;
}

// Apply only the two line-local repairs, not arbitrary StableHLO rewriting. Leave unmatched
// patterns alone and invent no values. Preserve line count/final newline to match recorded
// repaired-artifact bytes.
bool repairForeignModule(llvm::StringRef text, const RepairSites &sites,
                         ExternArtifacts &art, ExternDiagnosticFn diag,
                         llvm::StringRef where) {
  // Rewrite stablehlo.dynamic_reshape %src,%shape to tensor.reshape %src(%shape) within one line;
  // retain operands/types/trailing loc bytes.
  auto repairReshape = [&](llvm::StringRef line, std::string &out) -> bool {
    size_t at = line.find("stablehlo.dynamic_reshape ");
    if (at == llvm::StringRef::npos)
      return false;
    llvm::StringRef head = line.take_front(at);
    llvm::StringRef rest =
        line.drop_front(at + strlen("stablehlo.dynamic_reshape "));
    // Split through %src, %shape : .
    size_t comma = rest.find(", ");
    size_t colon = rest.find(" : ");
    if (comma == llvm::StringRef::npos || colon == llvm::StringRef::npos ||
        comma > colon)
      return false;
    llvm::StringRef src = rest.take_front(comma);
    llvm::StringRef shape = rest.substr(comma + 2, colon - comma - 2);
    llvm::StringRef tail = rest.drop_front(colon); // " : (…) -> … loc(…)"
    if (!src.starts_with("%") || !shape.starts_with("%"))
      return false;
    out = (head + "tensor.reshape " + src + "(" + shape + ")" + tail).str();
    return true;
  };

  // If window = { lacks stride/lhs_dilate/rhs_dilate together, add ones for spatial dimensions
  // derived from module dim_numbers.
  auto repairConv = [&](llvm::StringRef line, std::string &out) -> bool {
    if (!line.contains("stablehlo.convolution") || !line.contains("window = {"))
      return false;
    if (line.contains("stride = [") || line.contains("lhs_dilate = [") ||
        line.contains("rhs_dilate = ["))
      return false;
    size_t at = line.find("window = {");
    llvm::StringRef head = line.take_front(at + strlen("window = {"));
    llvm::StringRef rest = line.drop_front(at + strlen("window = {"));
    if (!rest.starts_with("pad = "))
      return false;
    out = (head + "stride = [1, 1], lhs_dilate = [1, 1], rhs_dilate = [1, 1], " +
           rest).str();
    return true;
  };

  llvm::SmallVector<llvm::StringRef, 0> lines;
  text.split(lines, '\n');
  std::string out;
  out.reserve(text.size() + 256);
  unsigned conv = 0, reshape = 0;
  for (auto [i, line] : llvm::enumerate(lines)) {
    if (i)
      out += '\n';
    std::string fixed;
    if (repairConv(line, fixed)) {
      ++conv;
      out += fixed;
      continue;
    }
    if (repairReshape(line, fixed)) {
      ++reshape;
      out += fixed;
      continue;
    }
    out += line.str();
  }

  // Counts must equal declared expectations; never silently accept drift.
  if (conv != sites.convWindow || reshape != sites.dynamicReshape) {
    diag(kCheckFailed,
         (where + "repair applied conv-window=" + llvm::Twine(conv) +
          " dynamic-reshape=" + llvm::Twine(reshape) + " but the scan found " +
          llvm::Twine(sites.convWindow) + " and " +
          llvm::Twine(sites.dynamicReshape))
             .str());
    return false;
  }
  // Rescan with the same scanner after repair and require zero remaining sites.
  RepairSites after = scanRepairSites(out);
  if (after.convWindow || after.dynamicReshape || after.malformedConv) {
    diag(kCheckFailed,
         (where + "the module still has repairable sites after repair"
                  " (conv-window=" +
          llvm::Twine(after.convWindow) + " dynamic-reshape=" +
          llvm::Twine(after.dynamicReshape) + ")")
             .str());
    return false;
  }
  art.repairedModule = std::move(out);
  art.convWindowRepairs = conv;
  art.dynamicReshapeRepairs = reshape;
  return true;
}

