// File-local AST accessors; do not include Scalar/Freestanding private headers. Share only
// ContractModule.
const contract::AstField *findField(const contract::Node &n,
                                    llvm::StringRef key) {
  for (const contract::AstField &f : n.fields)
    if (f.key == key)
      return &f;
  return nullptr;
}

bool getReference(const contract::Node &n, llvm::StringRef key, int64_t &out) {
  const contract::AstField *f = findField(n, key);
  if (!f || f->kind != contract::AstField::Kind::Reference)
    return false;
  out = std::get<int64_t>(f->value);
  return true;
}

bool getString(const contract::Node &n, llvm::StringRef key, std::string &out) {
  const contract::AstField *f = findField(n, key);
  if (!f || f->kind != contract::AstField::Kind::String)
    return false;
  out = std::get<std::string>(f->value);
  return true;
}

bool getInteger(const contract::Node &n, llvm::StringRef key, int64_t &out) {
  const contract::AstField *f = findField(n, key);
  if (!f || f->kind != contract::AstField::Kind::Integer)
    return false;
  out = std::get<int64_t>(f->value);
  return true;
}

bool getArray(const contract::Node &n, llvm::StringRef key,
              std::vector<int64_t> &out) {
  const contract::AstField *f = findField(n, key);
  if (!f || f->kind != contract::AstField::Kind::Array)
    return false;
  out = std::get<std::vector<int64_t>>(f->value);
  return true;
}

