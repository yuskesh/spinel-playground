# frozen_string_literal: true
#
# tools/app/lib/core_app/xwrap.rb -- the recording wrappers of the
# application's own externs in a verification build (decision 0014 §10,
# Task 11). The link's --wrap=<symbol> replaces each provider symbol with
# `__wrap_<symbol>`, which records XCALL with the arguments as the host
# records them (a buffer argument as its bytes, a scalar as an i64), calls
# `__real_<symbol>` and records XRET. The externs are numbered after the
# board's members and the channels' (`xi_base`), as the trace numbers them.
require_relative "glue"

module CoreApp
  module Xwrap
    module_function

    def c(app, xi_base:)
      out = +"/* generated by spinel-core-app build (0014 §10): the recording wrappers of the\n"
      out << " * application's core_extern providers; linked with --wrap=<symbol>. */\n"
      out << "#include <stdint.h>\n#include \"recorder.h\"\n\n"
      app.externs.each_with_index do |e, k|
        xi = xi_base + k
        params = []
        args = []
        e.params.each do |pa|
          if pa.buffer?
            qual = e.writes.include?(pa.name) ? "" : "const "
            params << "#{qual}#{Glue::CTYPE.fetch(pa.type)} *#{pa.name}" << "uint32_t #{pa.name}_len"
            args << "{ 1u, 0, (const uint8_t *)#{pa.name}, #{pa.name}_len * #{Glue::WIDTH.fetch(pa.type)}u }"
          else
            params << "#{Glue::CTYPE.fetch(pa.type)} #{pa.name}"
            args << "{ 0u, (int64_t)#{pa.name}, 0, 0u }"
          end
        end
        ret = e.returns ? Glue::CTYPE.fetch(e.returns) : "void"
        plist = params.empty? ? "void" : params.join(", ")
        names = e.params.flat_map { |pa| pa.buffer? ? [pa.name, "#{pa.name}_len"] : [pa.name] }.join(", ")
        out << "#{ret} __real_#{e.symbol}(#{plist});\n"
        out << "#{ret} __wrap_#{e.symbol}(#{plist})\n{\n"
        out << "\tstruct spc_rec_arg a[#{[args.size, 1].max}] = { #{args.empty? ? '{ 0u, 0, 0, 0u }' : args.join(', ')} };\n"
        out << "\t#{ret} r;\n" if e.returns
        out << "\n\tspc_tr_XCALL(spc_rec_ctx, spc_rec_entry, #{xi}u, #{args.size}u, a);\n"
        if e.returns
          out << "\tr = __real_#{e.symbol}(#{names});\n"
          out << "\tspc_tr_XRET(spc_rec_ctx, spc_rec_entry, #{xi}u, (int64_t)r);\n\treturn r;\n}\n\n"
        else
          out << "\t__real_#{e.symbol}(#{names});\n"
          out << "\tspc_tr_XRET(spc_rec_ctx, spc_rec_entry, #{xi}u, 0);\n}\n\n"
        end
      end
      out
    end
  end
end
