  def self.sem_row(name)
    SEMCOLS.map { |c| SEM.fetch(name).fetch(c) }.join("\t")
  end

  # The kernel declaration — the string that binds the .vmfb. **If this one line changes, the name changes.**
  def self.kernel_decl(row, w, h, k, centery, ntex, ncmap)
    format("%s|form=%s|nfield=%s|fields=%s|ftypes=%s|k=%d|layout=planar_soa" \
           "|W=%d|H=%d|centery=%d|ntex=%d|ncmap=%d|semsig=%016x",
           row["name"], row["form"], row["nfield"], row["fields"], row["ftypes"],
           k, w, h, centery, ntex, ncmap, row["semsig"])
  end

  # The head of a kernel's entry name. `wall_columns` -> `wall`.
  def self.entry_prefix(name) = name.split("_")[0]

  def self.entry_name(row, ksig)
    format("%s_%s_%016x", entry_prefix(row["name"]), row["form"], ksig)
  end

  def self.annotate(rows)
    rows.each do |r|
      r["sig"] = fnv1a64(r["decl"])
      r["sem"] = sem_row(r["name"])
      r["semsig"] = fnv1a64(r["decl"] + "\t" + r["sem"])
    end
    rows
  end

  # `die` belongs to the caller (the CLI) — because each tool has its own prog name.
  def self.read_table(path, die)
    rows = []
    File.read(path, mode: "rb").force_encoding("UTF-8").each_line do |line|
      line = line.chomp("\n")
      next if line.empty? || line.start_with?("#")
      parts = line.split("\t", -1)
      if parts.size != COLS.size + 1
        die.call("#{path}: a table row has #{parts.size} columns, expected " \
                 "#{COLS.size + 1} (#{COLS.join(',')},sig)")
      end
      d = {}
      COLS.each_with_index { |c, i| d[c] = parts[i] }
      d["sig_ruby"] = parts[-1]
      d["decl"] = parts[0...-1].join("\t")
      rows << d
    end
    die.call("#{path}: no rows") if rows.empty?
    rows
  end
