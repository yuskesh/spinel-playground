  # The same computation as `Doom::Bytes.fnv1a64_hex` (FNV-1a 64 over a byte string).
  def self.fnv1a64(s)
    h = FNV_OFF
    s.to_s.dup.force_encoding(Encoding::BINARY).each_byte do |b|
      h ^= b
      h = (h * FNV_PRIME) & 0xFFFFFFFFFFFFFFFF
    end
    h
  end

