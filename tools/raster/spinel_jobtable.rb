# tools/raster/spinel_jobtable.rb -- the vocabulary the raster lane's 3 tools share.
# [the raster plan, phase 2 / E170: Ruby]
#
# **A copy of the frozen `frozen/spinel-jobtable`.** Not one message or expression changes —
# E170's only claim is "for the same argv, the same stdout / stderr / rc and the same outputs",
# and the moment it is rounded it is no longer a claim.
#
# The point is that the 3 tools (jobtable / jobcheck / rastergen) **share one vocabulary**.
# The frozen Python read jobtable as a module with `SourceFileLoader`.
# Ruby does the same with `require_relative` — the meaning table (SEM) and the signatures (fnv1a64 /
# kernel_decl) are never copied into 2 places.
#
# **The meaning table's strings were copied mechanically from the frozen Python** (copying long prose by hand
# drops a byte somewhere). The suite checks the match by bytes every time.
