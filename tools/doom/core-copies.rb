# frozen_string_literal: true
#
# tools/doom/core-copies.rb — an entry's closure, copied under the entry's prefix.
#
#   ruby tools/doom/core-copies.rb --prefix dc_rv_ --from src/rview.rb --out src/rvcopies.rb
#
# THE KERNEL REFUSES AN ENTRY WHOSE CLOSURE MEMBER IS CALLED FROM OUTSIDE THE
# CLOSURE (Eligibility.cpp, enumerateIngress), and no definition is exempt. An
# entry that reaches definitions other entries also reach therefore reaches
# COPIES of them. This writes those copies for one entry: every `<prefix>NAME`
# the entry's own file calls and does not define is the copy of `dc_NAME` (or
# of `NAME`, for fixed.rb's), and every definition a copied one calls is copied
# too, its calls renamed. A copy is its original's text with the names changed
# and nothing else.
#
# tests/doom-core/fixtures/source/dups.tsv records each pair, with the copies a
# copy calls, and tests/doom-core/dup-check.rb holds every copy identical to its
# original modulo those names. This tool replaces the rows for its own prefix
# and leaves every other row as it is.
#
# Paths are relative to examples/doom/core. Definitions are read line by line,
# `def` at column 0 to `end` at column 0, as dup-check.rb reads them.
require "optparse"

ROOT = File.expand_path("../..", __dir__)
CORE = File.join(ROOT, "examples/doom/core")
DUPS = File.join(ROOT, "tests/doom-core/fixtures/source/dups.tsv")
opt = {}
OptionParser.new do |o|
  o.on("--prefix P") { |v| opt[:prefix] = v }
  o.on("--from FILE") { |v| opt[:from] = File.join(CORE, v) }
  o.on("--out FILE") { |v| opt[:out] = File.join(CORE, v) }
end.parse!
%i[prefix from out].each { |k| opt[k] or abort "core-copies: --#{k} is required" }
prefix = opt[:prefix]

def definitions(path)
  out = {}
  lines = File.readlines(path)
  i = 0
  while i < lines.size
    if lines[i] =~ /\Adef ([a-z_0-9]+)\(/
      name = Regexp.last_match(1)
      j = i
      j += 1 until lines[j].nil? || lines[j] =~ /\Aend\b/
      out[name] = lines[i..j].join
      i = j
    end
    i += 1
  end
  out
end

defs = {}
Dir[File.join(CORE, "src/*.rb")].sort.each do |f|
  next if [opt[:from], opt[:out]].include?(f)
  definitions(f).each { |n, t| defs[n] = t }
end
own = definitions(opt[:from])
copy_of = ->(orig) { prefix + orig.delete_prefix("dc_") }
callees = ->(text) { text.scan(/\b([a-z_][a-z0-9_]*)\(/).flatten.uniq.select { |n| defs.key?(n) } }

wanted = File.read(opt[:from]).scan(/\b(#{Regexp.escape(prefix)}[a-z0-9_]+)\(/).flatten.uniq - own.keys
queue = wanted.map do |c|
  base = c.delete_prefix(prefix)
  orig = defs.key?("dc_#{base}") ? "dc_#{base}" : base
  defs.key?(orig) or abort "core-copies: #{c} names no definition (dc_#{base} or #{base})"
  copy_of.call(orig) == c or abort "core-copies: #{c} would be the copy of #{orig} under another name"
  orig
end
done = {}
until queue.empty?
  orig = queue.shift
  next if done[orig]
  own.key?(copy_of.call(orig)) and abort "core-copies: #{copy_of.call(orig)} is defined by the entry itself"
  done[orig] = callees.call(defs[orig].sub(/\Adef [a-z_0-9]+/, "")) - [orig]
  queue.concat(done[orig])
end

rows = []
body = +""
done.keys.sort.each do |orig|
  copy = copy_of.call(orig)
  text = defs[orig].sub(/\Adef #{Regexp.escape(orig)}\(/, "def #{copy}(")
  renames = done[orig].sort
  renames.each { |c| text = text.gsub(/\b#{Regexp.escape(c)}\b/, copy_of.call(c)) }
  body << text << "\n"
  rows << [orig, copy, renames.map { |c| "#{c}=#{copy_of.call(c)}" }.join(",")]
end

rel = opt[:out].delete_prefix("#{CORE}/")
from = opt[:from].delete_prefix("#{CORE}/")
header = <<~HEAD
  # examples/doom/core/#{rel} — GENERATED by tools/doom/core-copies.rb; do not edit.
  #
  # GPL-derived, as the definitions it copies. See ../NOTICE.md and ../sources.tsv.
  #
  # The copies #{from} reaches, under #{prefix}: the kernel admits no call into
  # an entry's closure from outside it, and each original here is also reached
  # by another entry. tests/doom-core/dup-check.rb holds every copy identical to
  # its original (tests/doom-core/fixtures/source/dups.tsv). #{rows.size} copies.

HEAD
File.write(opt[:out], header + body.chomp + "\n")

kept = File.readlines(DUPS).reject { |l| !l.start_with?("#") && l.split("\t")[1].to_s.start_with?(prefix) }
File.write(DUPS, kept.join + rows.map { |r| r.join("\t").sub(/\t\z/, "") + "\n" }.join)
puts "core-copies: #{rows.size} copies for #{prefix} (#{wanted.size} called by #{from}), " \
     "#{body.lines.size} lines -> #{rel}"
