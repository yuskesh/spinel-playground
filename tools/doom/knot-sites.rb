# frozen_string_literal: true
#
# tools/doom/knot-sites.rb — the lowered set's call sites, from the audit.
#
#   ruby tools/doom/knot-sites.rb --audit DIR [--check]
#
# tools/doom/knot-cps.rb refuses to write unless the direct-style source has,
# pair by pair, the call sites the ORIGINAL has; tools/doom/knot-sites.tsv is
# that count. This writes the table from the audit's output (tools/doom/
# audit-core.rb --output DIR): the members are the recursive component anchored
# at Game#dispatch_action (DIR/cycles.tsv) and the definitions lowered with it
# (ABOVE, below), and a pair's count is the number of call edges in
# DIR/closure.tsv from one member that resolve to another.
#
# The table is committed and the audit's output is not: --check compares
# instead of writing, and exits nonzero on any difference.
ROOT = File.expand_path("../..", __dir__)
TABLE = File.join(ROOT, "tools/doom/knot-sites.tsv")
ANCHOR = "Game#dispatch_action"
# Not recursive: they reach the knot, and are lowered with it so that the
# knot's buffers meet at one dispatcher (examples/doom/core/knot/play.rb).
ABOVE = %w[
  block_things_iterator_changesector change_sector death_think g_ticker mobj_thinker move_plane
  move_player move_psprites p_ticker pit_change_sector player_in_special_sector player_think
  run_thinkers slide_move stairstep t_move_floor t_plat_raise t_vertical_door thing_height_clip
  use_lines xy_movement z_movement
].map { |n| "Game##{n}" }.freeze

dir = ARGV[ARGV.index("--audit") + 1] if ARGV.include?("--audit")
dir or abort "usage: knot-sites.rb --audit DIR [--check]"
rows = ->(f) { File.readlines(File.join(dir, f)).reject { |l| l.start_with?("#") }.drop(1).map { |l| l.chomp.split("\t") } }
knot = rows.call("cycles.tsv").select { |r| r[2] == ANCHOR }.map { |r| r[4] }.uniq
knot.empty? and abort "knot-sites: no component anchored at #{ANCHOR} in #{dir}/cycles.tsv"
(knot & ABOVE).empty? or abort "knot-sites: #{(knot & ABOVE).join(' ')} listed above the knot and in it"
members = (knot + ABOVE).to_h { |m| [m, true] }
counts = Hash.new(0)
rows.call("closure.tsv").each do |r|
  next unless r[1] == "call" && members[r[0]] && members[r[8]]
  counts[[r[0], r[8]]] += 1
end
missing = ABOVE.reject { |m| counts.keys.flatten.include?(m) }
missing.empty? or abort "knot-sites: no call edge touches #{missing.join(' ')}"

header = <<~HEAD
  # tools/doom/knot-sites.tsv — the lowered set's re-entry sites, from the audit.
  #
  # GENERATED by tools/doom/knot-sites.rb from the audit's cycles.tsv and
  # closure.tsv. One row per (caller, callee) pair inside the set
  # tools/doom/knot-cps.rb lowers -- the #{knot.size}-member recursive component
  # anchored at #{ANCHOR} and the #{ABOVE.size} definitions lowered with it --
  # with the number of call sites the audit found. knot-cps.rb requires the
  # direct-style source to have exactly these sites, pair by pair: every one
  # becomes a resumption point, and a missed one would be a silent wrong
  # continuation, so the count is checked, not remembered.
  #
  #caller\tcallee\tsites
HEAD
body = counts.keys.sort.map { |a, b| "#{a}\t#{b}\t#{counts[[a, b]]}\n" }.join
out = header + body
if ARGV.include?("--check")
  old = File.read(TABLE)
  pairs = ->(t) { t.lines.reject { |l| l.start_with?("#") || l.strip.empty? }.map(&:chomp).sort }
  gone = pairs.call(old) - pairs.call(out)
  added = pairs.call(out) - pairs.call(old)
  gone.each { |l| warn "knot-sites: table has, audit does not: #{l}" }
  added.each { |l| warn "knot-sites: audit has, table does not: #{l}" }
  puts "knot-sites: #{knot.size} + #{ABOVE.size} members, #{counts.size} pairs, #{counts.values.sum} sites; " \
       "#{gone.size} row(s) only in the table, #{added.size} only in the audit"
  exit(gone.empty? && added.empty? ? 0 : 1)
end
File.write(TABLE, out)
puts "knot-sites: #{knot.size} + #{ABOVE.size} members, #{counts.size} pairs, #{counts.values.sum} sites -> #{TABLE}"
