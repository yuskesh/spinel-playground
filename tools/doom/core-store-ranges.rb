# frozen_string_literal: true
#
# tools/doom/core-store-ranges.rb — decision 0018's other observed evidence:
# every value the three CORE entries store into a buffer.
#
#   ruby tools/doom/core-store-ranges.rb --output FILE --label LABEL RUNNER [ARGS...]
#
# RUNNER is one of the lanes that run the port in CRuby -- tests/doom-core/
# input-diff.rb, step-diff.rb or render-diff.rb -- with its own ARGS; it is
# loaded as it would run, and its output and exit status are its own. The only
# change is to doom_core_input, doom_core_step and doom_core_render as the port
# defines them: during each call, each buffer the entry's contract takes
# `inout`, and that examples/doom/core/entries/fields.tsv binds to a resident
# field, keeps the minimum and maximum of every integer stored into it -- by
# `[]=` and by every mutating Array method the port could use -- whichever
# definition below the entry makes the store. Nothing is compared.
#
# WHY. The ranges tools/doom/core-ranges.rb reads are the state between calls,
# and a value an entry stores and then overwrites within one call is not there:
# dc_rv_clear_clip_segs stores the sentinel -1 into renderer_ss_last, which is
# never -1 after a tic, and the first frame of a narrowed render failed with
# ARITHMETIC at that store (decision 0018). These ranges are every store.
#
# OUTPUT, written when the runner exits: field, entry, stores, min, max.
# core_state's slots and the derived index tables are not rows: 0018 keeps them
# i64.

ROOT = File.expand_path("../..", __dir__)
ENTRIES = %w[doom_core_input doom_core_step doom_core_render].freeze

out = nil
label = nil
while ARGV.first&.start_with?("--")
  case ARGV.shift
  when "--output" then out = ARGV.shift
  when "--label" then label = ARGV.shift
  else abort("usage: core-store-ranges.rb --output FILE --label LABEL RUNNER [ARGS...]")
  end
end
runner = ARGV.shift
out && label && runner or abort("usage: core-store-ranges.rb --output FILE --label LABEL RUNNER [ARGS...]")
runner = File.expand_path(runner)

field_of = {}
File.foreach(File.join(ROOT, "examples/doom/core/entries/fields.tsv")) do |l|
  next if l.start_with?("#") || l.strip.empty?
  e, p, f, = l.chomp.split("\t")
  field_of[[e, p]] = f unless f == "core_state" || f.start_with?("derived:")
end
# Each entry's parameters in order, with the field an `inout` buffer is, or nil.
RECORDED = ENTRIES.to_h do |e|
  params = File.readlines(File.join(ROOT, "examples/doom/core/entries/#{e}.contract"))
               .filter_map { |l| l =~ /\Aparam (\S+) (buffer \S+ (\S+)|scalar)/ && [$1, $3] }
  [e, params.map { |p, mode| mode == "inout" ? field_of[[e, p]] : nil }]
end

$core_store_ranges = {}
$core_store_active = false

# The port's stores into a recorded buffer. Mixed into the buffer's singleton
# class for the duration of the run; it records only while an entry is running.
module CoreStoreRecord
  def __core_note(v)
    return unless $core_store_active && v.is_a?(Integer)
    r = ($core_store_ranges[@core_store_key] ||= [0, v, v])
    r[0] += 1
    r[1] = v if v < r[1]
    r[2] = v if v > r[2]
  end

  def __core_note_all(vs) = vs.each { |v| __core_note(v) }
  def []=(*a)
    v = a.last
    v.is_a?(Array) ? __core_note_all(v) : __core_note(v)
    super
  end
  def fill(*a, &b) = super.tap { __core_note_all(self) }
  def replace(o) = super.tap { __core_note_all(o) }
  def push(*v) = (__core_note_all(v); super)
  def <<(v) = (__core_note(v); super)
  def append(*v) = (__core_note_all(v); super)
  def concat(*a) = (a.each { |x| __core_note_all(x) }; super)
  def insert(i, *v) = (__core_note_all(v); super)
  def unshift(*v) = (__core_note_all(v); super)
  def prepend(*v) = (__core_note_all(v); super)
end

class Object
  def self.method_added(m)
    super
    name = m.to_s
    return unless ENTRIES.include?(name)
    @core_store_wrapped ||= {}
    return if @core_store_wrapped[name]
    @core_store_wrapped[name] = true
    orig = instance_method(m)
    fields = RECORDED.fetch(name)
    define_method(m) do |*args|
      args.each_with_index do |a, i|
        f = fields[i] or next
        next unless a.is_a?(Array)
        a.extend(CoreStoreRecord) unless a.is_a?(CoreStoreRecord)
        a.instance_variable_set(:@core_store_key, [f, name])
      end
      $core_store_active = true
      begin
        orig.bind(self).call(*args)
      ensure
        $core_store_active = false
      end
    end
  end
end

at_exit do
  File.open(out, "w") do |io|
    io.puts "# Generated by tools/doom/core-store-ranges.rb: #{label} (#{File.basename(runner)} #{ARGV.join(' ')})"
    io.puts "#field\tentry\tstores\tmin\tmax"
    $core_store_ranges.sort.each { |(f, e), (n, mn, mx)| io.puts [f, e, n, mn, mx].join("\t") }
    # Here and not on stderr: the lanes read the runner's own last line.
    io.puts "# #{$core_store_ranges.size} (field, entry) pair(s), #{$core_store_ranges.values.sum(&:first)} store(s)"
  end
end

$0 = runner
load runner
