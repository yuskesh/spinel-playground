# `Jobs#check`: every job's coordinates, alignment and colormap row, then the
# per-column tables; `strict` (0 or 1) also fails on a crowded column or an
# overlap. The high-water marks follow.
# C's unsigned `0xffffffff / s`, for a positive s, as the i32 pattern of
# the quotient (decision 0022: no i32 holds 0xffffffff). 2**32 - 1 is
# 2 * (2**31 - 1) + 1, so with q, r the quotient and remainder of 2**31 - 1
# by s, the quotient is 2q, plus one when 2r + 1 >= s (2r >= s - 1, written
# without the product), wrapped to 32 bits.
def dc_rv_umax_div(s)
  q = 2147483647 / s
  r = 2147483647 % s
  core_w32_add(core_w32_mul(q, 2), r >= s - 1 - r ? 1 : 0)
end

def dc_rv_jobs_check(width, height, exec_atlas_size, exec_flat_size, state, rx, wall, span, masked, xcount, xyl,
                     xyh, ycount, yx1, yx2, mcount, mlo, mhi, mseq, mfz, strict)
  w = width[0]
  h = height[0]
  atlas_size = exec_atlas_size[0]
  flat_size = exec_flat_size[0]
  i = 0
  n = state[rx[R_NWALL]]
  while i < n
    b = i * RV_WC_NF
    x = wall[b]
    yl = wall[b + 1]
    yh = wall[b + 2]
    o = wall[b + RV_WC_SRCOFS]
    cm = wall[b + RV_WC_CMAP]
    if x < 0 || x >= w || yl < -1 || yh >= h
      core_fail(:capacity)
    end
    if (o & 127) != 0 || o < 0 || o + 127 >= atlas_size
      core_fail(:capacity)
    end
    if cm < 0 || cm >= RV_CMAP_ROWS
      core_fail(:capacity)
    end
    i += 1
  end

  i = 0
  n = state[rx[R_NSPAN]]
  while i < n
    b = i * RV_SP_NF
    y = span[b]
    x1 = span[b + 1]
    x2 = span[b + 2]
    o = span[b + RV_SP_SRCOFS]
    cm = span[b + RV_SP_CMAP]
    if y < 0 || y >= h || x1 < 0 || x2 >= w || x1 > x2
      core_fail(:capacity)
    end
    if (o & 4095) != 0 || o < 0 || o + 4095 >= flat_size
      core_fail(:capacity)
    end
    if cm < 0 || cm >= RV_CMAP_ROWS
      core_fail(:capacity)
    end
    i += 1
  end

  i = 0
  n = state[rx[R_NMASKED]]
  while i < n
    b = i * RV_MC_NF
    x = masked[b]
    cm = masked[b + RV_MC_CMAP]
    fz = masked[b + RV_MC_FUZZ]
    if x < 0 || x >= w
      core_fail(:capacity)
    end
    if fz < 0 && (cm < 0 || cm >= RV_CMAP_ROWS)
      core_fail(:capacity)
    end
    if fz >= 50
      core_fail(:capacity)
    end
    i += 1
  end

  dc_rv_check_disjoint(state, wall, xcount, xyl, xyh, width, 0, rx[R_WALL_PHASE0_N], rx[R_MAX_K], rx[R_OVERLAPS])
  if strict != 0 && (state[rx[R_MAX_K]] > RV_K_MAX || state[rx[R_OVERLAPS]] > 0)
    core_fail(:capacity)
  end
  dc_rv_check_span_disjoint(state, span, ycount, yx1, yx2, height, rx[R_NSPAN], rx[R_SPAN_MAX_KX],
                            rx[R_SPAN_OVERLAPS])
  if strict != 0 && (state[rx[R_SPAN_MAX_KX]] > RV_SPAN_K_MAX || state[rx[R_SPAN_OVERLAPS]] > 0)
    core_fail(:capacity)
  end
  dc_rv_check_masked_k(state, masked, mcount, mlo, mhi, mseq, mfz, width, rx[R_NMASKED], rx[R_FUZZ_N],
                       rx[R_MASKED_MAX_KX], rx[R_FUZZ_MAX_KX])
  if strict != 0 && (state[rx[R_MASKED_MAX_KX]] > RV_MASKED_K_MAX || state[rx[R_FUZZ_MAX_KX]] > RV_FUZZ_SPLIT_MAX)
    core_fail(:capacity)
  end
  dc_rv_check_wall_all(state, wall, xcount, xyl, xyh, width, rx[R_NWALL], rx[R_WALL_ALL_MAX_K],
                       rx[R_WALL_ALL_OVERLAPS])
  if strict != 0 && (state[rx[R_WALL_ALL_MAX_K]] > RV_K_MAX || state[rx[R_WALL_ALL_OVERLAPS]] > 0)
    core_fail(:capacity)
  end

  state[rx[R_HI_WALL]] = state[rx[R_NWALL]] if state[rx[R_NWALL]] > state[rx[R_HI_WALL]]
  state[rx[R_HI_SPAN]] = state[rx[R_NSPAN]] if state[rx[R_NSPAN]] > state[rx[R_HI_SPAN]]
  state[rx[R_HI_MASKED]] = state[rx[R_NMASKED]] if state[rx[R_NMASKED]] > state[rx[R_HI_MASKED]]
  state[rx[R_HI_SCHED]] = state[rx[R_NSCHED]] if state[rx[R_NSCHED]] > state[rx[R_HI_SCHED]]
  state[rx[R_HI_ZONE]] = state[rx[R_NZONE]] if state[rx[R_NZONE]] > state[rx[R_HI_ZONE]]
  0
end

# `JobExecutor#run`: the checks, the counter, the schedule
def dc_rv_run_jobs(width, height, exec_atlas_size, exec_flat_size, state, rx, wall, span, masked, xcount, xyl, xyh,
                   ycount, yx1, yx2, mcount, mlo, mhi, mseq, mfz, scr, cmap, atlas, flat, wad, zonebuf, fuzzoffset,
                   sc_kind, sc_idx, exec_width, exec_centery, exec_vwx, exec_vwy, strict)
  dc_rv_jobs_check(width, height, exec_atlas_size, exec_flat_size, state, rx, wall, span, masked, xcount, xyl, xyh,
                   ycount, yx1, yx2, mcount, mlo, mhi, mseq, mfz, strict)
  state[rx[R_CHECKED]] += 1
  dc_rv_exec_run(scr, cmap, atlas, flat, wad, zonebuf, fuzzoffset, wall, span, masked, sc_kind, sc_idx,
                 state[rx[R_NSCHED]], exec_width[0], exec_centery[0], exec_vwx[0], exec_vwy[0])
  0
end

# `Renderer#clear_screen`
def dc_rv_clear_screen(sw, sh, scr)
  n = sw[0] * sh[0]
  i = 0
  while i < n
    scr[i] = 0
    i += 1
  end
  0
end

# `Doom::Hires.blit_scale`: the shadow buffer's rectangle, s times larger
def dc_rv_blit_scale(dst, src, dstw, srcw, sx, sy, w, h, s)
  if s < 1
    core_fail(:capacity)
  end
  row = 0
  while row < h
    srow = (sy + row) * srcw + sx
    ry = 0
    while ry < s
      drow = ((sy + row) * s + ry) * dstw + sx * s
      col = 0
      while col < w
        v = src[srow + col]
        k = 0
        d = drow + col * s
        while k < s
          dst[d + k] = v
          k += 1
        end
        col += 1
      end
      ry += 1
    end
    row += 1
  end
  0
end

# `Renderer#draw_fuzz_column`, the direct path
def dc_rv_draw_fuzz_column(state, rx, viewheight, sw, viewwindowy, viewwindowx, scr, cmap, fuzzoffset)
  yl = state[rx[R_DC_YL]]
  yh = state[rx[R_DC_YH]]
  yl = 1 if yl == 0
  yh = viewheight[0] - 2 if yh == viewheight[0] - 1
  count = yh - yl
  return 0 if count < 0
  s = sw[0]
  o = (yl + viewwindowy[0]) * s + state[rx[R_DC_X]] + viewwindowx[0]
  i = 0
  while i <= count
    scr[o] = cmap[6 * 256 + scr[o + fuzzoffset[state[rx[R_FUZZPOS]]] * s]]
    state[rx[R_FUZZPOS]] += 1
    state[rx[R_FUZZPOS]] = 0 if state[rx[R_FUZZPOS]] == 50
    o += s
    i += 1
  end
  0
end

# `Renderer#emit_column`: a wall job in phases 0 and 1, a masked or fuzz job after
def dc_rv_emit_column(state, rx, wall, sc_kind, sc_idx, cap_wall, cap_sched, viewheight, masked, cap_masked)
  if state[rx[R_PHASE]] < 2
    dc_rv_push_wall(state, wall, sc_kind, sc_idx, cap_wall, cap_sched, rx[R_NWALL], rx[R_NSCHED], state[rx[R_DC_X]],
                    state[rx[R_DC_YL]], state[rx[R_DC_YH]], state[rx[R_DC_ISCALE]], state[rx[R_DC_TEXTUREMID]],
                    state[rx[R_DC_SRCBASE]], state[rx[R_DC_COLORMAP]])
  elsif state[rx[R_DC_FUZZ]] != 0
    yl = state[rx[R_DC_YL]]
    yh = state[rx[R_DC_YH]]
    yl = 1 if yl == 0
    yh = viewheight[0] - 2 if yh == viewheight[0] - 1
    fp = state[rx[R_FUZZPOS]]
    count = yh - yl
    if count >= 0
      n = fp + count + 1
      while n >= 50
        n -= 50
      end
      state[rx[R_FUZZPOS]] = n
    end
    dc_rv_push_masked(state, masked, sc_kind, sc_idx, cap_masked, cap_sched, rx[R_NMASKED], rx[R_NSCHED],
                      state[rx[R_DC_X]], yl, yh, 0, 0, RV_RES_WAD, 0, 0, fp)
  else
    dc_rv_push_masked(state, masked, sc_kind, sc_idx, cap_masked, cap_sched, rx[R_NMASKED], rx[R_NSCHED],
                      state[rx[R_DC_X]], state[rx[R_DC_YL]], state[rx[R_DC_YH]], state[rx[R_DC_ISCALE]],
                      state[rx[R_DC_TEXTUREMID]], state[rx[R_DC_SRCRES]], state[rx[R_DC_SRCBASE]],
                      state[rx[R_DC_COLORMAP]], -1)
  end
  0
end

# `Renderer#draw_column`: the job path, the fuzz path, or the pixels
def dc_rv_column(jobmode, state, rx, wall, sc_kind, sc_idx, cap_wall, cap_sched, viewheight, masked, cap_masked, sw,
                 viewwindowy, viewwindowx, scr, cmap, fuzzoffset, atlas, wad, zonewin, centery)
  if jobmode[0] != 0
    dc_rv_emit_column(state, rx, wall, sc_kind, sc_idx, cap_wall, cap_sched, viewheight, masked, cap_masked)
    return 0
  end
  if state[rx[R_DC_FUZZ]] != 0
    dc_rv_draw_fuzz_column(state, rx, viewheight, sw, viewwindowy, viewwindowx, scr, cmap, fuzzoffset)
    return 0
  end
  dc_rv_draw_column(scr, 0, cmap, 0, atlas, 0, wad, 0, zonewin, 0, state, rx[R_DC_SRCRES], rx[R_DC_SRCBASE],
                    state[rx[R_DC_X]], state[rx[R_DC_YL]], state[rx[R_DC_YH]], state[rx[R_DC_ISCALE]],
                    state[rx[R_DC_TEXTUREMID]], state[rx[R_DC_COLORMAP]], centery[0], sw[0], viewwindowx[0],
                    viewwindowy[0])
  0
end

# `Renderer#draw_masked_column`: one patch column's posts, clipped
def dc_rv_draw_masked_column(state, rx, clipbot, cliptop, openings, viewheight, rv_caps, wad, jobmode, zone_slots,
                             lump_pos, lump_size, next_lump, zonebuf, zonewin, wall, sc_kind, sc_idx, cap_wall,
                             cap_sched, masked, cap_masked, sw, viewwindowy, viewwindowx, scr, cmap, fuzzoffset,
                             atlas, centery, lnum, lpos, lend, p, use_clip, x)
  basetexturemid = state[rx[R_DC_TEXTUREMID]]
  if use_clip != 0
    if state[rx[R_MCLIP_MODE]] == RV_MCLIP_SPRITE
      floorlim = clipbot[x]
      ceillim = cliptop[x]
    else
      # `mfloorclip = ds->sprbottomclip; mceilingclip = ds->sprtopclip`
      floorlim = dc_rv_clip_value(openings, viewheight, state[rx[R_MCLIP_BOTKIND]], state[rx[R_MCLIP_BOTBASE]], x)
      ceillim = dc_rv_clip_value(openings, viewheight, state[rx[R_MCLIP_TOPKIND]], state[rx[R_MCLIP_TOPBASE]], x)
    end
  else
    floorlim = viewheight[0]
    ceillim = -1
  end
  limit = rv_caps[RV_CAP_WAD]
  while true
    if p + 2 > limit
      core_fail(:capacity)
    end
    td = wad[p]
    break if td == 0xff
    len = wad[p + 1]
    # `spryscale * topdelta` is a 32-bit product
    spry = state[rx[R_SPRYSCALE]]
    m = core_w32_mul(spry, td)
    topscreen = core_w32_add(state[rx[R_SPRTOPSCREEN]], m)
    m = core_w32_mul(spry, len)
    bottomscreen = core_w32_add(topscreen, m)
    yl = core_w32_sub(core_w32_add(topscreen, RV_FRACUNIT), 1)
    yl >>= 16
    yh = core_w32_sub(bottomscreen, 1)
    yh >>= 16
    yh = floorlim - 1 if yh >= floorlim
    yl = ceillim + 1 if yl <= ceillim
    if yl <= yh
      state[rx[R_DC_YL]] = yl
      state[rx[R_DC_YH]] = yh
      # `R_DrawColumn` reads 128 bytes past the post's start: a post near the
      # lump's end reads the zone past it, rebuilt by the zone window
      if p + 3 + 128 <= lend
        state[rx[R_DC_SRCOFS]] = p + 3
        state[rx[R_DC_SRCRES]] = RV_RES_WAD
        state[rx[R_DC_SRCBASE]] = p + 3
      elsif jobmode[0] != 0
        # the job runs later: its window lives in the ring until the frame ends
        zb = dc_rv_alloc_zone_window(state, rx[R_NZONE], zone_slots)
        # the ring is the executor's `zonebuf`: buffer-roles.tsv binds it to `out`
        dc_rv_zone_window_into(wad, lump_pos, lump_size, next_lump, zonebuf, lnum, p + 3 - lpos, zb)
        state[rx[R_DC_SRCRES]] = RV_RES_ZONE
        state[rx[R_DC_SRCBASE]] = zb
      else
        # the single window: buffer-roles.tsv binds `zonewin` to `out`
        dc_rv_zone_window_into(wad, lump_pos, lump_size, next_lump, zonewin, lnum, p + 3 - lpos, 0)
        state[rx[R_DC_SRCOFS]] = 0
        state[rx[R_DC_SRCRES]] = RV_RES_ZONE
        state[rx[R_DC_SRCBASE]] = 0
      end
      state[rx[R_DC_TEXTUREMID]] = core_w32_sub(basetexturemid, core_w32_mul(td, 65536))
      dc_rv_column(jobmode, state, rx, wall, sc_kind, sc_idx, cap_wall, cap_sched, viewheight, masked, cap_masked,
                   sw, viewwindowy, viewwindowx, scr, cmap, fuzzoffset, atlas, wad, zonewin, centery)
    end
    p += len + 4
  end
  state[rx[R_DC_TEXTUREMID]] = basetexturemid
  0
end

# `Renderer#draw_masked_texture_column`: a masked midtexture's column is its patch's
def dc_rv_draw_masked_texture_column(tex_widthmask, collump, col_base, rv_caps, lump_pos, state, rx, clipbot,
                                     cliptop, openings, viewheight, wad, jobmode, zone_slots, lump_size, next_lump,
                                     zonebuf, zonewin, wall, sc_kind, sc_idx, cap_wall, cap_sched, masked,
                                     cap_masked, sw, viewwindowy, viewwindowx, scr, cmap, fuzzoffset, atlas,
                                     centery, colofs, tex, col, x)
  c = col & tex_widthmask[tex]
  lp = collump[col_base[tex] + c]
  if lp < 0
    core_fail(:capacity)
  end
  if lp >= rv_caps[RV_CAP_LUMPS]
    core_fail(:capacity)
  end
  l = lump_pos[lp]
  dc_rv_draw_masked_column(state, rx, clipbot, cliptop, openings, viewheight, rv_caps, wad, jobmode, zone_slots,
                           lump_pos, lump_size, next_lump, zonebuf, zonewin, wall, sc_kind, sc_idx, cap_wall,
                           cap_sched, masked, cap_masked, sw, viewwindowy, viewwindowx, scr, cmap, fuzzoffset,
                           atlas, centery, lp, l, l + lump_size[lp], l + colofs[col_base[tex] + c] - 3, 1, x)
  0
end

# `Renderer#draw_vissprite`
def dc_rv_draw_vissprite(vs_patch, spr_lumppos, spr_lumpnum, spr_lumpend, state, rx, vs_mobjflags, vs_cmap,
                         vs_xiscale, vs_texturemid, vs_startfrac, vs_scale, centeryfrac, vs_x1, vs_x2, wad, clipbot,
                         cliptop, openings, viewheight, rv_caps, jobmode, zone_slots, lump_pos, lump_size,
                         next_lump, zonebuf, zonewin, wall, sc_kind, sc_idx, cap_wall, cap_sched, masked,
                         cap_masked, sw, viewwindowy, viewwindowx, scr, cmap, fuzzoffset, atlas, centery, vis,
                         use_clip)
  patch = vs_patch[vis]
  l = spr_lumppos[patch]
  lnum = spr_lumpnum[patch]
  lend = spr_lumpend[patch]
  state[rx[R_DC_FUZZ]] = (vs_mobjflags[vis] & RV_MF_SHADOW) != 0 ? 1 : 0
  state[rx[R_DC_COLORMAP]] = vs_cmap[vis]
  iscale = vs_xiscale[vis]
  state[rx[R_DC_ISCALE]] = iscale < 0 ? -iscale : iscale
  state[rx[R_DC_TEXTUREMID]] = vs_texturemid[vis]
  frac = vs_startfrac[vis]
  state[rx[R_SPRYSCALE]] = vs_scale[vis]
  m = core_fixed_mul(state[rx[R_DC_TEXTUREMID]], state[rx[R_SPRYSCALE]])
  state[rx[R_SPRTOPSCREEN]] = core_w32_sub(centeryfrac[0], m)
  x = vs_x1[vis]
  while x <= vs_x2[vis]
    texcol = frac >> 16
    state[rx[R_DC_X]] = x
    # `Bytes.i32` of the patch's column directory, written out
    o = l + 8 + texcol * 4
    # the top byte placed by a word multiply: the i32 is its signed pattern at once
    colofs = wad[o] | (wad[o + 1] << 8) | (wad[o + 2] << 16) | core_w32_mul(wad[o + 3], 16777216)
    dc_rv_draw_masked_column(state, rx, clipbot, cliptop, openings, viewheight, rv_caps, wad, jobmode, zone_slots,
                             lump_pos, lump_size, next_lump, zonebuf, zonewin, wall, sc_kind, sc_idx, cap_wall,
                             cap_sched, masked, cap_masked, sw, viewwindowy, viewwindowx, scr, cmap, fuzzoffset,
                             atlas, centery, lnum, l, lend, l + colofs, use_clip, x)
    frac = core_w32_add(frac, vs_xiscale[vis])
    x += 1
  end
  state[rx[R_DC_FUZZ]] = 0
  0
end

# `Renderer#render_masked_seg_range`: a drawseg's masked midtexture
def dc_rv_render_masked_seg_range(state, rx, ds_topkind, ds_topbase, ds_botkind, ds_botbase, ds_curline,
                                  seg_frontsector, seg_backsector, texturetranslation, side_midtexture, seg_sidedef,
                                  sector_lightlevel, vertex_y, seg_v1, seg_v2, vertex_x, ds_maskedbase,
                                  ds_scalestep, ds_scale1, ds_x1, line_flags, seg_linedef, sector_floorheight,
                                  tex_theight, sector_ceilingheight, side_rowoffset, openings, resscale, scalelight,
                                  centeryfrac, tex_widthmask, collump, col_base, rv_caps, lump_pos, clipbot,
                                  cliptop, viewheight, wad, jobmode, zone_slots, lump_size, next_lump, zonebuf,
                                  zonewin, wall, sc_kind, sc_idx, cap_wall, cap_sched, masked, cap_masked, sw,
                                  viewwindowy, viewwindowx, scr, cmap, fuzzoffset, atlas, centery, colofs, ds, x1,
                                  x2)
  # `mfloorclip = ds->sprbottomclip; mceilingclip = ds->sprtopclip;`
  state[rx[R_MCLIP_MODE]] = RV_MCLIP_DRAWSEG
  state[rx[R_MCLIP_TOPKIND]] = ds_topkind[ds]
  state[rx[R_MCLIP_TOPBASE]] = ds_topbase[ds]
  state[rx[R_MCLIP_BOTKIND]] = ds_botkind[ds]
  state[rx[R_MCLIP_BOTBASE]] = ds_botbase[ds]
  seg = ds_curline[ds]
  front = seg_frontsector[seg]
  back = seg_backsector[seg]
  texnum = texturetranslation[side_midtexture[seg_sidedef[seg]]]
  viewz = state[rx[R_VIEWZ]]

  lightnum = (sector_lightlevel[front] >> RV_LIGHTSEGSHIFT) + state[rx[R_EXTRALIGHT]]
  if vertex_y[seg_v1[seg]] == vertex_y[seg_v2[seg]]
    lightnum -= 1
  elsif vertex_x[seg_v1[seg]] == vertex_x[seg_v2[seg]]
    lightnum += 1
  end
  lightnum = 0 if lightnum < 0
  lightnum = RV_LIGHTLEVELS - 1 if lightnum >= RV_LIGHTLEVELS
  state[rx[R_WALLLIGHTS]] = lightnum * RV_MAXLIGHTSCALE

  base = ds_maskedbase[ds]
  state[rx[R_RW_SCALESTEP]] = ds_scalestep[ds]
  state[rx[R_SPRYSCALE]] = core_w32_add(ds_scale1[ds], core_w32_mul(core_w32_sub(x1, ds_x1[ds]), state[rx[R_RW_SCALESTEP]]))

  if (line_flags[seg_linedef[seg]] & RV_ML_DONTPEGBOTTOM) != 0
    mid = sector_floorheight[front] > sector_floorheight[back] ? sector_floorheight[front] : sector_floorheight[back]
    state[rx[R_DC_TEXTUREMID]] = core_w32_sub(core_w32_add(mid, tex_theight[texnum]), viewz)
  else
    mid = sector_ceilingheight[front] < sector_ceilingheight[back] ? sector_ceilingheight[front] : sector_ceilingheight[back]
    state[rx[R_DC_TEXTUREMID]] = core_w32_sub(mid, viewz)
  end
  state[rx[R_DC_TEXTUREMID]] = core_w32_add(state[rx[R_DC_TEXTUREMID]], side_rowoffset[seg_sidedef[seg]])

  x = x1
  while x <= x2
    col = openings[base + x]
    if col != 0x7fff
      index = dc_rv_light_index(resscale, state[rx[R_SPRYSCALE]])
      state[rx[R_DC_COLORMAP]] = scalelight[state[rx[R_WALLLIGHTS]] + index]
      m = core_fixed_mul(state[rx[R_DC_TEXTUREMID]], state[rx[R_SPRYSCALE]])
      state[rx[R_SPRTOPSCREEN]] = core_w32_sub(centeryfrac[0], m)
      state[rx[R_DC_ISCALE]] = dc_rv_umax_div(state[rx[R_SPRYSCALE]])
      state[rx[R_DC_X]] = x
      # the composited buffer has no post headers: walk the patch's own posts
      dc_rv_draw_masked_texture_column(tex_widthmask, collump, col_base, rv_caps, lump_pos, state, rx, clipbot,
                                       cliptop, openings, viewheight, wad, jobmode, zone_slots, lump_size,
                                       next_lump, zonebuf, zonewin, wall, sc_kind, sc_idx, cap_wall, cap_sched,
                                       masked, cap_masked, sw, viewwindowy, viewwindowx, scr, cmap, fuzzoffset,
                                       atlas, centery, colofs, texnum, col, x)
      openings[base + x] = 0x7fff
    end
    state[rx[R_SPRYSCALE]] = core_w32_add(state[rx[R_SPRYSCALE]], state[rx[R_RW_SCALESTEP]])
    x += 1
  end
  0
end

# `Renderer#draw_sprite`: the sprite's clip arrays from the drawsegs in front
def dc_rv_draw_sprite(vs_x1, vs_x2, clipbot, cliptop, state, rx, ds_x1, ds_x2, ds_silhouette, ds_masked, ds_scale1,
                      ds_scale2, vs_scale, vertex_x, vertex_y, seg_v1, seg_v2, vs_gx, vs_gy, ds_curline, ds_topkind,
                      ds_topbase, ds_botkind, ds_botbase, seg_frontsector, seg_backsector, texturetranslation,
                      side_midtexture, seg_sidedef, sector_lightlevel, ds_maskedbase, ds_scalestep, line_flags,
                      seg_linedef, sector_floorheight, tex_theight, sector_ceilingheight, side_rowoffset, openings,
                      resscale, scalelight, centeryfrac, tex_widthmask, collump, col_base, rv_caps, lump_pos,
                      viewheight, wad, jobmode, zone_slots, lump_size, next_lump, zonebuf, zonewin, wall, sc_kind,
                      sc_idx, cap_wall, cap_sched, masked, cap_masked, sw, viewwindowy, viewwindowx, scr, cmap,
                      fuzzoffset, atlas, centery, colofs, vs_gz, ds_bsilheight, vs_gzt, ds_tsilheight, vs_patch,
                      spr_lumppos, spr_lumpnum, spr_lumpend, vs_mobjflags, vs_cmap, vs_xiscale, vs_texturemid,
                      vs_startfrac, spr)
  x = vs_x1[spr]
  while x <= vs_x2[spr]
    clipbot[x] = -2
    cliptop[x] = -2
    x += 1
  end

  ds = state[rx[R_DS_COUNT]] - 1
  while ds >= 0
    skip = ds_x1[ds] > vs_x2[spr] || ds_x2[ds] < vs_x1[spr] || (ds_silhouette[ds] == 0 && ds_masked[ds] == 0) ? 1 : 0
    if skip == 0
      r1 = ds_x1[ds] < vs_x1[spr] ? vs_x1[spr] : ds_x1[ds]
      r2 = ds_x2[ds] > vs_x2[spr] ? vs_x2[spr] : ds_x2[ds]
      if ds_scale1[ds] > ds_scale2[ds]
        lowscale = ds_scale2[ds]
        scale = ds_scale1[ds]
      else
        lowscale = ds_scale1[ds]
        scale = ds_scale2[ds]
      end
      behind = 0
      if scale < vs_scale[spr]
        behind = 1
      elsif lowscale < vs_scale[spr] && dc_rv_point_on_seg_side(vertex_x, vertex_y, seg_v1, seg_v2, vs_gx[spr],
                                                                vs_gy[spr], ds_curline[ds]) == 0
        behind = 1
      end
      if behind != 0
        if ds_masked[ds] != 0
          dc_rv_render_masked_seg_range(state, rx, ds_topkind, ds_topbase, ds_botkind, ds_botbase, ds_curline,
                                        seg_frontsector, seg_backsector, texturetranslation, side_midtexture,
                                        seg_sidedef, sector_lightlevel, vertex_y, seg_v1, seg_v2, vertex_x,
                                        ds_maskedbase, ds_scalestep, ds_scale1, ds_x1, line_flags, seg_linedef,
                                        sector_floorheight, tex_theight, sector_ceilingheight, side_rowoffset,
                                        openings, resscale, scalelight, centeryfrac, tex_widthmask, collump,
                                        col_base, rv_caps, lump_pos, clipbot, cliptop, viewheight, wad, jobmode,
                                        zone_slots, lump_size, next_lump, zonebuf, zonewin, wall, sc_kind, sc_idx,
                                        cap_wall, cap_sched, masked, cap_masked, sw, viewwindowy, viewwindowx, scr,
                                        cmap, fuzzoffset, atlas, centery, colofs, ds, r1, r2)
        end
      else
        silhouette = ds_silhouette[ds]
        silhouette &= ~RV_SIL_BOTTOM if vs_gz[spr] >= ds_bsilheight[ds]
        silhouette &= ~RV_SIL_TOP if vs_gzt[spr] <= ds_tsilheight[ds]
        if silhouette == 1
          x = r1
          while x <= r2
            clipbot[x] = dc_rv_clip_value(openings, viewheight, ds_botkind[ds], ds_botbase[ds], x) if clipbot[x] == -2
            x += 1
          end
        elsif silhouette == 2
          x = r1
          while x <= r2
            cliptop[x] = dc_rv_clip_value(openings, viewheight, ds_topkind[ds], ds_topbase[ds], x) if cliptop[x] == -2
            x += 1
          end
        elsif silhouette == 3
          x = r1
          while x <= r2
            clipbot[x] = dc_rv_clip_value(openings, viewheight, ds_botkind[ds], ds_botbase[ds], x) if clipbot[x] == -2
            cliptop[x] = dc_rv_clip_value(openings, viewheight, ds_topkind[ds], ds_topbase[ds], x) if cliptop[x] == -2
            x += 1
          end
        end
        0
      end
    end
    ds -= 1
  end

  x = vs_x1[spr]
  while x <= vs_x2[spr]
    clipbot[x] = viewheight[0] if clipbot[x] == -2
    cliptop[x] = -1 if cliptop[x] == -2
    x += 1
  end

  # `mfloorclip = clipbot; mceilingclip = cliptop;` after the drawseg loop,
  # which pointed them at the drawsegs' own clips
  state[rx[R_MCLIP_MODE]] = RV_MCLIP_SPRITE
  dc_rv_draw_vissprite(vs_patch, spr_lumppos, spr_lumpnum, spr_lumpend, state, rx, vs_mobjflags, vs_cmap,
                       vs_xiscale, vs_texturemid, vs_startfrac, vs_scale, centeryfrac, vs_x1, vs_x2, wad, clipbot,
                       cliptop, openings, viewheight, rv_caps, jobmode, zone_slots, lump_pos, lump_size, next_lump,
                       zonebuf, zonewin, wall, sc_kind, sc_idx, cap_wall, cap_sched, masked, cap_masked, sw,
                       viewwindowy, viewwindowx, scr, cmap, fuzzoffset, atlas, centery, spr, 1)
  0
end

# `Renderer#draw_psprite_body`: the weapon, in the last vissprite slot
def dc_rv_draw_psprite_body(state, rx, num_nodes, node_x, node_y, node_dx, node_dy, node_child0, node_child1,
                            sector_lightlevel, ss_sector, state_sprite, state_frame, sprlump, framebase, sprflip,
                            spriteoffset, centerxfrac, pspritescale, viewwidth, spritewidth, vs_mobjflags,
                            spritetopoffset, vs_texturemid, vs_x1, vs_x2, vs_scale, vs_xiscale, pspriteiscale,
                            vs_startfrac, vs_patch, vs_cmap, scalelight, spr_lumppos, spr_lumpnum, spr_lumpend,
                            centeryfrac, wad, clipbot, cliptop, openings, viewheight, rv_caps, jobmode, zone_slots,
                            lump_pos, lump_size, next_lump, zonebuf, zonewin, wall, sc_kind, sc_idx, cap_wall,
                            cap_sched, masked, cap_masked, sw, viewwindowy, viewwindowx, scr, cmap, fuzzoffset,
                            atlas, centery)
  pst = state[rx[R_PSP_STATE]]
  return 0 if pst < 0
  ss = dc_rv_st_point_in_subsector(num_nodes, node_x, node_y, node_dx, node_dy, node_child0, node_child1,
                                   state[rx[R_VIEWX]], state[rx[R_VIEWY]])
  lightnum = (sector_lightlevel[ss_sector[ss]] >> RV_LIGHTSEGSHIFT) + state[rx[R_EXTRALIGHT]]
  lightnum = 0 if lightnum < 0
  lightnum = RV_LIGHTLEVELS - 1 if lightnum >= RV_LIGHTLEVELS
  state[rx[R_SPRITELIGHTS]] = lightnum * RV_MAXLIGHTSCALE

  spr = state_sprite[pst]
  frame = state_frame[pst] & RV_FF_FRAMEMASK
  lump = sprlump[(framebase[spr] + frame) * 8]
  flip = sprflip[(framebase[spr] + frame) * 8]

  tx = core_w32_sub(state[rx[R_PSP_SX]], core_w32_mul(160, RV_FRACUNIT))
  tx = core_w32_sub(tx, spriteoffset[lump])
  x1 = core_w32_add(centerxfrac[0], core_fixed_mul(tx, pspritescale[0]))
  x1 >>= 16
  return 0 if x1 > viewwidth[0]
  tx = core_w32_add(tx, spritewidth[lump])
  x2 = core_w32_add(centerxfrac[0], core_fixed_mul(tx, pspritescale[0]))
  x2 = (x2 >> 16) - 1
  return 0 if x2 < 0

  # the weapon borrows the last vissprite slot (vanilla's stack `avis`)
  v = RV_MAXVISSPRITES - 1
  vs_mobjflags[v] = 0
  m = core_w32_sub(state[rx[R_PSP_SY]], spritetopoffset[lump])
  vs_texturemid[v] = core_w32_sub(core_w32_add(core_w32_mul(RV_BASEYCENTER, 65536), RV_FRACUNIT / 2), m)
  vs_x1[v] = x1 < 0 ? 0 : x1
  vs_x2[v] = x2 >= viewwidth[0] ? viewwidth[0] - 1 : x2
  vs_scale[v] = pspritescale[0]
  if flip != 0
    vs_xiscale[v] = core_w32_neg(pspriteiscale[0])
    vs_startfrac[v] = spritewidth[lump] - 1
  else
    vs_xiscale[v] = pspriteiscale[0]
    vs_startfrac[v] = 0
  end
  if vs_x1[v] > x1
    d = core_w32_mul(vs_xiscale[v], core_w32_sub(vs_x1[v], x1))
    vs_startfrac[v] = core_w32_add(vs_startfrac[v], d)
  end
  vs_patch[v] = lump
  if (state_frame[pst] & RV_FF_FULLBRIGHT) != 0
    vs_cmap[v] = 0
  else
    vs_cmap[v] = scalelight[state[rx[R_SPRITELIGHTS]] + RV_MAXLIGHTSCALE - 1]
  end
  dc_rv_draw_vissprite(vs_patch, spr_lumppos, spr_lumpnum, spr_lumpend, state, rx, vs_mobjflags, vs_cmap,
                       vs_xiscale, vs_texturemid, vs_startfrac, vs_scale, centeryfrac, vs_x1, vs_x2, wad, clipbot,
                       cliptop, openings, viewheight, rv_caps, jobmode, zone_slots, lump_pos, lump_size, next_lump,
                       zonebuf, zonewin, wall, sc_kind, sc_idx, cap_wall, cap_sched, masked, cap_masked, sw,
                       viewwindowy, viewwindowx, scr, cmap, fuzzoffset, atlas, centery, v, 0)
  0
end

