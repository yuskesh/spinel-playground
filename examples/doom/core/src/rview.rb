                     node_child0, node_child1, node_bbox, bspnum)
  cap = rv_caps[RV_CAP_BSP]
  bsp_stack[0] = bspnum
  bsp_stack[1] = 0
  bsp_stack[2] = 0
  sp = 0
  while sp >= 0
    b = sp * 3
    node = bsp_stack[b]
    if bsp_stack[b + 1] == 0
      if (node & 0x8000) != 0
        dc_rv_subsector(state, rx, ss_sector, ss_numlines, ss_firstline, sector_floorheight, pl_height, pl_picnum,
                        pl_lightlevel, pl_minx, pl_maxx, pl_top, skyflatnum, sw, plw, plempty, sector_floorpic,
                        sector_lightlevel, sector_ceilingheight, sector_ceilingpic, sector_validcount, sector_head,
                        thing_next, mobj_x, mobj_y, mobj_z, mobj_angle, mobj_frame, mobj_sprite, mobj_flags,
                        numframes, rotate, framebase, sprlump, sprflip, spriteoffset, spritewidth, spritetopoffset,
                        tantoangle, projection, centerxfrac, viewwidth, scalelight, resscale, vs_mobjflags,
                        vs_scale, vs_gx, vs_gy, vs_gz, vs_gzt, vs_texturemid, vs_x1, vs_x2, vs_startfrac,
                        vs_xiscale, vs_patch, vs_cmap, seg_v1, seg_v2, vertex_x, vertex_y, clipangle, two_clipangle,
                        viewangletox, seg_backsector, side_midtexture, seg_sidedef, ss_last, ss_first, seg_linedef,
                        line_flags, seg_angle, finesine, ds_curline, ds_x1, ds_x2, xtoviewangle, ds_scale1,
                        ds_scale2, ds_scalestep, ds_maskedbase, ds_masked, texturetranslation, tex_theight,
                        side_rowoffset, ds_silhouette, ds_topkind, ds_botkind, ds_bsilheight, ds_tsilheight,
                        side_toptexture, side_bottomtexture, maxopenings, side_textureoffset, seg_offset,
                        centeryfrac, ceilingclip, floorclip, pl_bottom, openings, finetangent, tex_widthmask,
                        tex_atlas_base, viewheight, jobmode, scr, cmap, atlas, wad, zonewin, centery, viewwindowx,
                        viewwindowy, wall, sc_kind, sc_idx, cap_wall, cap_sched, ds_topbase, ds_botbase,
                        node == -1 ? 0 : (node & 0x7fff))
        sp -= 1
      else
        side = dc_rv_st_point_on_side(node_x, node_y, node_dx, node_dy, state[rx[R_VIEWX]], state[rx[R_VIEWY]],
                                      node)
        bsp_stack[b + 1] = 1
        bsp_stack[b + 2] = side
        if b + 6 > cap
          core_fail(:capacity)
        end
        bsp_stack[b + 3] = side == 0 ? node_child0[node] : node_child1[node]
        bsp_stack[b + 4] = 0
        bsp_stack[b + 5] = 0
        sp += 1
      end
    else
      other = bsp_stack[b + 2] ^ 1
      sp -= 1
      if dc_rv_check_bbox(state, node_bbox, tantoangle, clipangle, two_clipangle, viewangletox, ss_first, ss_last,
                          rx[R_VIEWX], rx[R_VIEWY], rx[R_VIEWANGLE], node, other) != 0
        sp += 1
        bsp_stack[b] = other == 0 ? node_child0[node] : node_child1[node]
        bsp_stack[b + 1] = 0
        bsp_stack[b + 2] = 0
      end
      # the if/else is the loop body's last statement: each branch has a value
      0
    end
  end
  0
end

