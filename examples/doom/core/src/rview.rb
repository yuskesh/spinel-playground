          sector_floorheight[back] != sector_floorheight[front]
      solid = 0
    else
      return 0 if sector_ceilingpic[back] == sector_ceilingpic[front] &&
                  sector_floorpic[back] == sector_floorpic[front] &&
                  sector_lightlevel[back] == sector_lightlevel[front] &&
                  side_midtexture[seg_sidedef[seg]] == 0
      solid = 0
    end
  end

  if solid != 0
    dc_rv_clip_solid_wall_segment(ss_last, ss_first, state, rx, seg_sidedef, seg_linedef, line_flags, seg_angle,
                                  tantoangle, finesine, vertex_x, seg_v1, vertex_y, ds_curline, ds_x1, ds_x2,
                                  xtoviewangle, projection, ds_scale1, ds_scale2, ds_scalestep,
                                  sector_ceilingheight, sector_floorheight, ds_maskedbase, ds_masked,
                                  texturetranslation, side_midtexture, tex_theight, side_rowoffset, ds_silhouette,
                                  ds_topkind, ds_botkind, ds_bsilheight, ds_tsilheight, sector_ceilingpic,
                                  skyflatnum, sector_floorpic, sector_lightlevel, side_toptexture,
                                  side_bottomtexture, maxopenings, side_textureoffset, seg_offset, seg_v2,
                                  centeryfrac, pl_height, pl_picnum, pl_lightlevel, pl_minx, pl_maxx, pl_top, plw,
                                  plempty, ceilingclip, floorclip, pl_bottom, openings, finetangent, scalelight,
                                  resscale, tex_widthmask, tex_atlas_base, viewheight, jobmode, scr, cmap, atlas,
                                  wad, zonewin, centery, sw, viewwindowx, viewwindowy, wall, sc_kind, sc_idx,
                                  cap_wall, cap_sched, ds_topbase, ds_botbase, x1, x2 - 1)
  else
    dc_rv_clip_pass_wall_segment(ss_last, ss_first, state, rx, seg_sidedef, seg_linedef, line_flags, seg_angle,
                                 tantoangle, finesine, vertex_x, seg_v1, vertex_y, ds_curline, ds_x1, ds_x2,
                                 xtoviewangle, projection, ds_scale1, ds_scale2, ds_scalestep, sector_ceilingheight,
                                 sector_floorheight, ds_maskedbase, ds_masked, texturetranslation, side_midtexture,
                                 tex_theight, side_rowoffset, ds_silhouette, ds_topkind, ds_botkind, ds_bsilheight,
                                 ds_tsilheight, sector_ceilingpic, skyflatnum, sector_floorpic, sector_lightlevel,
                                 side_toptexture, side_bottomtexture, maxopenings, side_textureoffset, seg_offset,
                                 seg_v2, centeryfrac, pl_height, pl_picnum, pl_lightlevel, pl_minx, pl_maxx, pl_top,
                                 plw, plempty, ceilingclip, floorclip, pl_bottom, openings, finetangent, scalelight,
                                 resscale, tex_widthmask, tex_atlas_base, viewheight, jobmode, scr, cmap, atlas,
