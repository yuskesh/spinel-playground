  state[rx[R_RW_ANGLE1]] = angle1
  angle1 = core_w32_sub(angle1, state[rx[R_VIEWANGLE]])
  angle2 = core_w32_sub(angle2, state[rx[R_VIEWANGLE]])

  ca = clipangle[0]
  tca = two_clipangle[0]
  tspan = core_w32_add(angle1, ca)
  if core_u32_gt(tspan, tca)
    tspan = core_w32_sub(tspan, tca)
