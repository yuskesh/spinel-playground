# examples/doom/core/src/rview.rb — the render entry's spine: the view, the BSP walk, walls and sprites.
#
# GPL-derived, from `examples/doom/lib/doom/render.rb` (`Doom::Renderer`),
# `jobs.rb` (`Doom::Jobs#check`), `executor.rb` (`Doom::JobExecutor#run`) and
# `hires.rb` (`Doom::Hires.blit_scale`), which reproduce doomgeneric's
# `r_main.c`, `r_bsp.c`, `r_segs.c`, `r_things.c` and `r_draw.c`. See
# ../NOTICE.md and ../sources.tsv.
#
# THE RENDER SPINE'S CONVENTION is the step entry's (stepcore.rb): a scalar
# field is a cell of `core_state`, reached as `state[rx[R_NAME]]` through the
# index table `rx` (examples/doom/core/entries/render-slots.tsv names the
# field at each position); a value Full prepares is a one-element buffer; an
# array is a buffer named by its field. The leaves this calls take slot indices
# one parameter each (`i_viewx`), and get `rx[R_VIEWX]`.
#
# EVERY DEFINITION THIS REACHES IS A COPY. The kernel refuses an entry whose
# closure member is called from outside the closure, and every leaf here is
# also reached by its own entry. rvcopies.rb holds `dc_rv_<name>` for each
# original `dc_<name>` (or fixed.rb's `<name>`) the spine reaches, generated by
# tools/doom/core-copies.rb and held identical by tests/doom-core/dup-check.rb.
#
# BOTH JOB MODES ARE WRITTEN OUT, as the original has them: mode 0 draws the
# pixels, modes 1 and 2 push jobs and run the executor at the end of the view
# (mode 1 with the strict checks). The native program renders in mode 0
# (decision 0008, 2026-10-21).
#
# THE SOURCE IS A SELECTOR AND A BASE (source.rb). Where the original points
# `@dc_srcbuf` at the WAD or at the single zone window, this sets the selector
# to RES_WAD or RES_ZONE in every mode, and the direct column reads through it.
#
# WHAT CHANGES FROM THE ORIGINAL: the recursion of `render_bsp_node` is a work
# stack (0008), `bsp_stack`, three cells a frame; `raise` is
# `core_fail(:capacity)`; a boolean is 0 or 1; `trace_column` and `trace_wall`
# are not called (the renderer never traces in a program:
# unreached-in-config:trace). `Jobs#check`'s strict raises -- more than K_MAX
# jobs in a column, or an overlap -- fail after each table is counted rather
# than at the first offending column; the frame fails either way.
#
# `rv_caps` holds the sizes a helper cannot read off its buffers: 0 the WAD's
# bytes, 1 its lump count, 2 the per-frame counter table's length, 3 the BSP
# stack's cells.

