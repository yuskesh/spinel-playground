                     spritetopoffset, tantoangle, projection, centerxfrac, viewwidth, scalelight, resscale,
                     vs_mobjflags, vs_scale, vs_gx, vs_gy, vs_gz, vs_gzt, vs_texturemid, vs_x1, vs_x2, vs_startfrac,
