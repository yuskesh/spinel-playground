                     viewangletox, seg_backsector, side_midtexture, seg_sidedef, ss_last, ss_first, seg_linedef,
                     line_flags, seg_angle, finesine, ds_curline, ds_x1, ds_x2, xtoviewangle, ds_scale1, ds_scale2,
