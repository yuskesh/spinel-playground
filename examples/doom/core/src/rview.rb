# `Renderer#draw_masked`: sprites back to front, the remaining masked segs, the weapon
def dc_rv_draw_masked(state, vs_scale, vs_taken, vs_sorted, rx, vs_x1, vs_x2, clipbot, cliptop, ds_x1, ds_x2,
                      ds_silhouette, ds_masked, ds_scale1, ds_scale2, vertex_x, vertex_y, seg_v1, seg_v2, vs_gx,
                      vs_gy, ds_curline, ds_topkind, ds_topbase, ds_botkind, ds_botbase, seg_frontsector,
                      seg_backsector, texturetranslation, side_midtexture, seg_sidedef, sector_lightlevel,
                      ds_maskedbase, ds_scalestep, line_flags, seg_linedef, sector_floorheight, tex_theight,
                      sector_ceilingheight, side_rowoffset, openings, resscale, scalelight, centeryfrac,
                      tex_widthmask, collump, col_base, rv_caps, lump_pos, viewheight, wad, jobmode, zone_slots,
                      lump_size, next_lump, zonebuf, zonewin, wall, sc_kind, sc_idx, cap_wall, cap_sched, masked,
                      cap_masked, sw, viewwindowy, viewwindowx, scr, cmap, fuzzoffset, atlas, centery, colofs,
                      vs_gz, ds_bsilheight, vs_gzt, ds_tsilheight, vs_patch, spr_lumppos, spr_lumpnum, spr_lumpend,
                      vs_mobjflags, vs_cmap, vs_xiscale, vs_texturemid, vs_startfrac, num_nodes, node_x, node_y,
                      node_dx, node_dy, node_child0, node_child1, ss_sector, state_sprite, state_frame, sprlump,
                      framebase, sprflip, spriteoffset, centerxfrac, pspritescale, viewwidth, spritewidth,
                      spritetopoffset, pspriteiscale)
  dc_rv_sort_vissprites(state, vs_scale, vs_taken, vs_sorted, rx[R_VIS_N])
  k = 0
  while k < state[rx[R_VIS_N]]
    dc_rv_draw_sprite(vs_x1, vs_x2, clipbot, cliptop, state, rx, ds_x1, ds_x2, ds_silhouette, ds_masked, ds_scale1,
                      ds_scale2, vs_scale, vertex_x, vertex_y, seg_v1, seg_v2, vs_gx, vs_gy, ds_curline, ds_topkind,
                      ds_topbase, ds_botkind, ds_botbase, seg_frontsector, seg_backsector, texturetranslation,
                      side_midtexture, seg_sidedef, sector_lightlevel, ds_maskedbase, ds_scalestep, line_flags,
                      seg_linedef, sector_floorheight, tex_theight, sector_ceilingheight, side_rowoffset, openings,
                      resscale, scalelight, centeryfrac, tex_widthmask, collump, col_base, rv_caps, lump_pos,
                      viewheight, wad, jobmode, zone_slots, lump_size, next_lump, zonebuf, zonewin, wall, sc_kind,
                      sc_idx, cap_wall, cap_sched, masked, cap_masked, sw, viewwindowy, viewwindowx, scr, cmap,
                      fuzzoffset, atlas, centery, colofs, vs_gz, ds_bsilheight, vs_gzt, ds_tsilheight, vs_patch,
                      spr_lumppos, spr_lumpnum, spr_lumpend, vs_mobjflags, vs_cmap, vs_xiscale, vs_texturemid,
                      vs_startfrac, vs_sorted[k])
    k += 1
  end
  ds = state[rx[R_DS_COUNT]] - 1
  while ds >= 0
    if ds_masked[ds] != 0
      dc_rv_render_masked_seg_range(state, rx, ds_topkind, ds_topbase, ds_botkind, ds_botbase, ds_curline,
                                    seg_frontsector, seg_backsector, texturetranslation, side_midtexture,
                                    seg_sidedef, sector_lightlevel, vertex_y, seg_v1, seg_v2, vertex_x,
                                    ds_maskedbase, ds_scalestep, ds_scale1, ds_x1, line_flags, seg_linedef,
                                    sector_floorheight, tex_theight, sector_ceilingheight, side_rowoffset, openings,
                                    resscale, scalelight, centeryfrac, tex_widthmask, collump, col_base, rv_caps,
                                    lump_pos, clipbot, cliptop, viewheight, wad, jobmode, zone_slots, lump_size,
                                    next_lump, zonebuf, zonewin, wall, sc_kind, sc_idx, cap_wall, cap_sched, masked,
                                    cap_masked, sw, viewwindowy, viewwindowx, scr, cmap, fuzzoffset, atlas, centery,
                                    colofs, ds, ds_x1[ds], ds_x2[ds])
    end
    ds -= 1
  end
  state[rx[R_PHASE]] = 3
  if jobmode[0] != 0
    dc_rv_mark_phase3(state, rx[R_NMASKED], rx[R_MASKED_PHASE2_N])
  end
  dc_rv_draw_player_sprites(state, rx, num_nodes, node_x, node_y, node_dx, node_dy, node_child0, node_child1,
                            sector_lightlevel, ss_sector, state_sprite, state_frame, sprlump, framebase, sprflip,
                            spriteoffset, centerxfrac, pspritescale, viewwidth, spritewidth, vs_mobjflags,
                            spritetopoffset, vs_texturemid, vs_x1, vs_x2, vs_scale, vs_xiscale, pspriteiscale,
                            vs_startfrac, vs_patch, vs_cmap, scalelight, spr_lumppos, spr_lumpnum, spr_lumpend,
                            centeryfrac, wad, clipbot, cliptop, openings, viewheight, rv_caps, jobmode, zone_slots,
                            lump_pos, lump_size, next_lump, zonebuf, zonewin, wall, sc_kind, sc_idx, cap_wall,
                            cap_sched, masked, cap_masked, sw, viewwindowy, viewwindowx, scr, cmap, fuzzoffset,
                            atlas, centery)
  0
end

# `Renderer#store_wall_range`: a drawseg for the visible part of the current seg
def dc_rv_store_wall_range(state, rx, seg_sidedef, seg_linedef, line_flags, seg_angle, tantoangle, finesine,
                           vertex_x, seg_v1, vertex_y, ds_curline, ds_x1, ds_x2, xtoviewangle, projection,
                           ds_scale1, ds_scale2, ds_scalestep, sector_ceilingheight, sector_floorheight,
                           ds_maskedbase, ds_masked, texturetranslation, side_midtexture, tex_theight,
                           side_rowoffset, ds_silhouette, ds_topkind, ds_botkind, ds_bsilheight, ds_tsilheight,
                           sector_ceilingpic, skyflatnum, sector_floorpic, sector_lightlevel, side_toptexture,
                           side_bottomtexture, maxopenings, side_textureoffset, seg_offset, seg_v2, centeryfrac,
                           pl_height, pl_picnum, pl_lightlevel, pl_minx, pl_maxx, pl_top, plw, plempty, ceilingclip,
                           floorclip, pl_bottom, openings, finetangent, scalelight, resscale, tex_widthmask,
                           tex_atlas_base, viewheight, jobmode, scr, cmap, atlas, wad, zonewin, centery, sw,
                           viewwindowx, viewwindowy, wall, sc_kind, sc_idx, cap_wall, cap_sched, ds_topbase,
                           ds_botbase, start, stop)
  return 0 if state[rx[R_DS_COUNT]] == RV_MAXDRAWSEGS
  seg = state[rx[R_CURLINE]]
  sidedef = seg_sidedef[seg]
  linedef = seg_linedef[seg]
  line_flags[linedef] = line_flags[linedef] | RV_ML_MAPPED

  state[rx[R_RW_NORMALANGLE]] = core_w32_add(seg_angle[seg], RV_ANG90)
  offsetangle = dc_rv_abs_angle(core_w32_sub(state[rx[R_RW_NORMALANGLE]], state[rx[R_RW_ANGLE1]]))
  offsetangle = RV_ANG90 if core_u32_gt(offsetangle, RV_ANG90)
  distangle = RV_ANG90 - offsetangle
  hyp = dc_rv_point_to_dist(state, tantoangle, finesine, rx[R_VIEWX], rx[R_VIEWY], vertex_x[seg_v1[seg]],
                            vertex_y[seg_v1[seg]])
  sineval = finesine[core_u32_shr(distangle, RV_ANGLETOFINESHIFT)]
  state[rx[R_RW_DISTANCE]] = core_fixed_mul(hyp, sineval)

  ds = state[rx[R_DS_COUNT]]
  ds_curline[ds] = seg
  ds_x1[ds] = start
  ds_x2[ds] = stop
  state[rx[R_RW_X]] = start
  state[rx[R_RW_STOPX]] = stop + 1
  visangle = core_w32_add(state[rx[R_VIEWANGLE]], xtoviewangle[start])
  state[rx[R_RW_SCALE]] = dc_rv_scale_from_global_angle(state, finesine, projection, rx[R_VIEWANGLE],
                                                        rx[R_RW_NORMALANGLE], rx[R_RW_DISTANCE], visangle)
  ds_scale1[ds] = state[rx[R_RW_SCALE]]
  if stop > start
    visangle = core_w32_add(state[rx[R_VIEWANGLE]], xtoviewangle[stop])
    scale2 = dc_rv_scale_from_global_angle(state, finesine, projection, rx[R_VIEWANGLE], rx[R_RW_NORMALANGLE],
                                           rx[R_RW_DISTANCE], visangle)
    ds_scale2[ds] = scale2
    num = scale2 - state[rx[R_RW_SCALE]]
    q = (num < 0 ? -num : num) / (stop - start)
    q = -q if num < 0
    state[rx[R_RW_SCALESTEP]] = q
    ds_scalestep[ds] = state[rx[R_RW_SCALESTEP]]
  else
    ds_scale2[ds] = ds_scale1[ds]
    ds_scalestep[ds] = state[rx[R_RW_SCALESTEP]]
  end

  front = state[rx[R_FRONTSECTOR]]
  back = state[rx[R_BACKSECTOR]]
  viewz = state[rx[R_VIEWZ]]
  state[rx[R_WORLDTOP]] = core_w32_sub(sector_ceilingheight[front], viewz)
  state[rx[R_WORLDBOTTOM]] = core_w32_sub(sector_floorheight[front], viewz)

  state[rx[R_MIDTEXTURE]] = 0
  state[rx[R_TOPTEXTURE]] = 0
  state[rx[R_BOTTOMTEXTURE]] = 0
  state[rx[R_MASKEDTEXTURE]] = 0
  ds_maskedbase[ds] = -1
  ds_masked[ds] = 0

  if back < 0
    # the animated wall textures go through texturetranslation; the height does not
    state[rx[R_MIDTEXTURE]] = texturetranslation[side_midtexture[sidedef]]
    state[rx[R_MARKFLOOR]] = 1
    state[rx[R_MARKCEILING]] = 1
    if (line_flags[linedef] & RV_ML_DONTPEGBOTTOM) != 0
      vtop = sector_floorheight[front] + tex_theight[side_midtexture[sidedef]]
      state[rx[R_RW_MIDTEXTUREMID]] = core_w32_sub(vtop, viewz)
    else
      state[rx[R_RW_MIDTEXTUREMID]] = state[rx[R_WORLDTOP]]
    end
    state[rx[R_RW_MIDTEXTUREMID]] = core_w32_add(state[rx[R_RW_MIDTEXTUREMID]], side_rowoffset[sidedef])
    ds_silhouette[ds] = RV_SIL_BOTH
    ds_topkind[ds] = RV_CLIP_SCREENHEIGHT
    ds_botkind[ds] = RV_CLIP_NEGONE
    ds_bsilheight[ds] = 0x7fffffff
    ds_tsilheight[ds] = -0x80000000
  else
    ds_topkind[ds] = RV_CLIP_NONE
    ds_botkind[ds] = RV_CLIP_NONE
    ds_silhouette[ds] = RV_SIL_NONE

    if sector_floorheight[front] > sector_floorheight[back]
      ds_silhouette[ds] = RV_SIL_BOTTOM
      ds_bsilheight[ds] = sector_floorheight[front]
    elsif sector_floorheight[back] > viewz
      ds_silhouette[ds] = RV_SIL_BOTTOM
      ds_bsilheight[ds] = 0x7fffffff
    end

    if sector_ceilingheight[front] < sector_ceilingheight[back]
      ds_silhouette[ds] = ds_silhouette[ds] | RV_SIL_TOP
      ds_tsilheight[ds] = sector_ceilingheight[front]
    elsif sector_ceilingheight[back] < viewz
      ds_silhouette[ds] = ds_silhouette[ds] | RV_SIL_TOP
      ds_tsilheight[ds] = -0x80000000
    end

    if sector_ceilingheight[back] <= sector_floorheight[front]
      ds_botkind[ds] = RV_CLIP_NEGONE
      ds_bsilheight[ds] = 0x7fffffff
      ds_silhouette[ds] = ds_silhouette[ds] | RV_SIL_BOTTOM
    end
    if sector_floorheight[back] >= sector_ceilingheight[front]
      ds_topkind[ds] = RV_CLIP_SCREENHEIGHT
      ds_tsilheight[ds] = -0x80000000
      ds_silhouette[ds] = ds_silhouette[ds] | RV_SIL_TOP
    end

    state[rx[R_WORLDHIGH]] = core_w32_sub(sector_ceilingheight[back], viewz)
    state[rx[R_WORLDLOW]] = core_w32_sub(sector_floorheight[back], viewz)

    if sector_ceilingpic[front] == skyflatnum[0] && sector_ceilingpic[back] == skyflatnum[0]
      state[rx[R_WORLDTOP]] = state[rx[R_WORLDHIGH]]
    end

    state[rx[R_MARKFLOOR]] =
      state[rx[R_WORLDLOW]] != state[rx[R_WORLDBOTTOM]] ||
      sector_floorpic[back] != sector_floorpic[front] ||
      sector_lightlevel[back] != sector_lightlevel[front] ? 1 : 0
    state[rx[R_MARKCEILING]] =
      state[rx[R_WORLDHIGH]] != state[rx[R_WORLDTOP]] ||
      sector_ceilingpic[back] != sector_ceilingpic[front] ||
      sector_lightlevel[back] != sector_lightlevel[front] ? 1 : 0

    if sector_ceilingheight[back] <= sector_floorheight[front] ||
       sector_floorheight[back] >= sector_ceilingheight[front]
      state[rx[R_MARKCEILING]] = 1
      state[rx[R_MARKFLOOR]] = 1
    end

    if state[rx[R_WORLDHIGH]] < state[rx[R_WORLDTOP]]
      state[rx[R_TOPTEXTURE]] = texturetranslation[side_toptexture[sidedef]]
      if (line_flags[linedef] & RV_ML_DONTPEGTOP) != 0
        state[rx[R_RW_TOPTEXTUREMID]] = state[rx[R_WORLDTOP]]
      else
        vtop = sector_ceilingheight[back] + tex_theight[side_toptexture[sidedef]]
        state[rx[R_RW_TOPTEXTUREMID]] = core_w32_sub(vtop, viewz)
      end
    end
    if state[rx[R_WORLDLOW]] > state[rx[R_WORLDBOTTOM]]
      state[rx[R_BOTTOMTEXTURE]] = texturetranslation[side_bottomtexture[sidedef]]
      if (line_flags[linedef] & RV_ML_DONTPEGBOTTOM) != 0
        state[rx[R_RW_BOTTOMTEXTUREMID]] = state[rx[R_WORLDTOP]]
      else
        state[rx[R_RW_BOTTOMTEXTUREMID]] = state[rx[R_WORLDLOW]]
      end
    end
    # these run whether or not there is a texture, as vanilla has them: the
    # row offset accumulates in the file-scope texture mids
    state[rx[R_RW_TOPTEXTUREMID]] = core_w32_add(state[rx[R_RW_TOPTEXTUREMID]], side_rowoffset[sidedef])
    state[rx[R_RW_BOTTOMTEXTUREMID]] = core_w32_add(state[rx[R_RW_BOTTOMTEXTUREMID]], side_rowoffset[sidedef])

    if side_midtexture[sidedef] != 0
      state[rx[R_MASKEDTEXTURE]] = 1
      state[rx[R_MASKEDTEXTURECOL]] = state[rx[R_LASTOPENING]] - state[rx[R_RW_X]]
      ds_maskedbase[ds] = state[rx[R_MASKEDTEXTURECOL]]
      ds_masked[ds] = 1
      state[rx[R_LASTOPENING]] += state[rx[R_RW_STOPX]] - state[rx[R_RW_X]]
      if state[rx[R_LASTOPENING]] > maxopenings[0]
        core_fail(:capacity)
      end
    end
    0
  end

  state[rx[R_SEGTEXTURED]] = state[rx[R_MIDTEXTURE]] | state[rx[R_TOPTEXTURE]] |
                             state[rx[R_BOTTOMTEXTURE]] | state[rx[R_MASKEDTEXTURE]]

  if state[rx[R_SEGTEXTURED]] != 0
    # `rw_offset`: every angle here is an unsigned angle_t
    offsetangle = core_w32_sub(state[rx[R_RW_NORMALANGLE]], state[rx[R_RW_ANGLE1]])
    offsetangle = core_w32_neg(offsetangle) if core_u32_gt(offsetangle, RV_ANG180)
    offsetangle = RV_ANG90 if core_u32_gt(offsetangle, RV_ANG90)
    sineval = finesine[core_u32_shr(offsetangle, RV_ANGLETOFINESHIFT)]
    state[rx[R_RW_OFFSET]] = core_fixed_mul(hyp, sineval)
    if core_u32_lt(core_w32_sub(state[rx[R_RW_NORMALANGLE]], state[rx[R_RW_ANGLE1]]), RV_ANG180)
      state[rx[R_RW_OFFSET]] = core_w32_neg(state[rx[R_RW_OFFSET]])
    end
    state[rx[R_RW_OFFSET]] = core_w32_add(core_w32_add(state[rx[R_RW_OFFSET]], side_textureoffset[sidedef]), seg_offset[seg])
    state[rx[R_RW_CENTERANGLE]] = core_w32_sub(core_w32_add(RV_ANG90, state[rx[R_VIEWANGLE]]), state[rx[R_RW_NORMALANGLE]])

    lightnum = (sector_lightlevel[front] >> RV_LIGHTSEGSHIFT) + state[rx[R_EXTRALIGHT]]
    if vertex_y[seg_v1[seg]] == vertex_y[seg_v2[seg]]
      lightnum -= 1
    elsif vertex_x[seg_v1[seg]] == vertex_x[seg_v2[seg]]
      lightnum += 1
    end
    lightnum = 0 if lightnum < 0
    lightnum = RV_LIGHTLEVELS - 1 if lightnum >= RV_LIGHTLEVELS
    state[rx[R_WALLLIGHTS]] = lightnum * RV_MAXLIGHTSCALE
  end

  state[rx[R_MARKFLOOR]] = 0 if sector_floorheight[front] >= viewz
  if sector_ceilingheight[front] <= viewz && sector_ceilingpic[front] != skyflatnum[0]
    state[rx[R_MARKCEILING]] = 0
  end

  state[rx[R_WORLDTOP]] = state[rx[R_WORLDTOP]] >> 4
  state[rx[R_WORLDBOTTOM]] = state[rx[R_WORLDBOTTOM]] >> 4

  half = centeryfrac[0] >> 4
  scale = state[rx[R_RW_SCALE]]
  sstep = state[rx[R_RW_SCALESTEP]]
  wt = state[rx[R_WORLDTOP]]
  wb = state[rx[R_WORLDBOTTOM]]
  m = core_fixed_mul(sstep, wt)
  state[rx[R_TOPSTEP]] = core_w32_neg(m)
  m = core_fixed_mul(wt, scale)
  state[rx[R_TOPFRAC]] = core_w32_sub(half, m)
  m = core_fixed_mul(sstep, wb)
  state[rx[R_BOTTOMSTEP]] = core_w32_neg(m)
  m = core_fixed_mul(wb, scale)
  state[rx[R_BOTTOMFRAC]] = core_w32_sub(half, m)

  if back >= 0
    state[rx[R_WORLDHIGH]] = state[rx[R_WORLDHIGH]] >> 4
    state[rx[R_WORLDLOW]] = state[rx[R_WORLDLOW]] >> 4
    wh = state[rx[R_WORLDHIGH]]
    wl = state[rx[R_WORLDLOW]]
    if wh < wt
      m = core_fixed_mul(wh, scale)
      state[rx[R_PIXHIGH]] = core_w32_sub(half, m)
      m = core_fixed_mul(sstep, wh)
      state[rx[R_PIXHIGHSTEP]] = core_w32_neg(m)
    end
    if wl > wb
      m = core_fixed_mul(wl, scale)
      state[rx[R_PIXLOW]] = core_w32_sub(half, m)
      m = core_fixed_mul(sstep, wl)
      state[rx[R_PIXLOWSTEP]] = core_w32_neg(m)
    end
  end

  if state[rx[R_MARKCEILING]] != 0
    if state[rx[R_CEILINGPLANE]] < 0
      core_fail(:capacity)
    end
    state[rx[R_CEILINGPLANE]] = dc_rv_check_plane(state, pl_height, pl_picnum, pl_lightlevel, pl_minx, pl_maxx,
                                                  pl_top, plw, plempty, rx[R_LASTVISPLANE],
                                                  state[rx[R_CEILINGPLANE]], state[rx[R_RW_X]],
                                                  state[rx[R_RW_STOPX]] - 1)
  end
  if state[rx[R_MARKFLOOR]] != 0
    if state[rx[R_FLOORPLANE]] < 0
      core_fail(:capacity)
    end
    state[rx[R_FLOORPLANE]] = dc_rv_check_plane(state, pl_height, pl_picnum, pl_lightlevel, pl_minx, pl_maxx,
                                                pl_top, plw, plempty, rx[R_LASTVISPLANE], state[rx[R_FLOORPLANE]],
                                                state[rx[R_RW_X]], state[rx[R_RW_STOPX]] - 1)
  end

  dc_rv_render_seg_loop(state, ceilingclip, floorclip, pl_top, pl_bottom, openings, xtoviewangle, finetangent, finesine,
                        scalelight, resscale, tex_widthmask, tex_atlas_base, plw, viewheight, jobmode, scr, cmap,
                        atlas, wad, zonewin, centery, sw, viewwindowx, viewwindowy, wall, sc_kind, sc_idx, cap_wall,
                        cap_sched, rx[R_RW_X], rx[R_RW_STOPX], rx[R_TOPFRAC], rx[R_BOTTOMFRAC], rx[R_TOPSTEP],
                        rx[R_BOTTOMSTEP], rx[R_PIXHIGH], rx[R_PIXLOW], rx[R_PIXHIGHSTEP], rx[R_PIXLOWSTEP],
                        rx[R_RW_SCALE], rx[R_RW_SCALESTEP], rx[R_MARKCEILING], rx[R_MARKFLOOR], rx[R_CEILINGPLANE],
                        rx[R_FLOORPLANE], rx[R_SEGTEXTURED], rx[R_RW_CENTERANGLE], rx[R_RW_DISTANCE],
                        rx[R_RW_OFFSET], rx[R_WALLLIGHTS], rx[R_MIDTEXTURE], rx[R_TOPTEXTURE], rx[R_BOTTOMTEXTURE],
                        rx[R_MASKEDTEXTURE], rx[R_RW_MIDTEXTUREMID], rx[R_RW_TOPTEXTUREMID],
                        rx[R_RW_BOTTOMTEXTUREMID], rx[R_MASKEDTEXTURECOL], rx[R_DC_X], rx[R_DC_YL], rx[R_DC_YH],
                        rx[R_DC_ISCALE], rx[R_DC_TEXTUREMID], rx[R_DC_COLORMAP], rx[R_DC_SRCOFS], rx[R_DC_SRCRES],
                        rx[R_DC_SRCBASE], rx[R_NWALL], rx[R_NSCHED])

  # the sprites' clip rows go to openings; a pointer with a negative offset
  # becomes a base and an x
  if ((ds_silhouette[ds] & RV_SIL_TOP) != 0 || state[rx[R_MASKEDTEXTURE]] != 0) && ds_topkind[ds] == RV_CLIP_NONE
    i = 0
    n = state[rx[R_RW_STOPX]] - start
    lo = state[rx[R_LASTOPENING]]
    while i < n
      openings[lo + i] = ceilingclip[start + i]
      i += 1
    end
    ds_topkind[ds] = RV_CLIP_OPENINGS
    ds_topbase[ds] = lo - start
    state[rx[R_LASTOPENING]] = lo + n
    if state[rx[R_LASTOPENING]] > maxopenings[0]
      core_fail(:capacity)
    end
  end
  if ((ds_silhouette[ds] & RV_SIL_BOTTOM) != 0 || state[rx[R_MASKEDTEXTURE]] != 0) && ds_botkind[ds] == RV_CLIP_NONE
    i = 0
    n = state[rx[R_RW_STOPX]] - start
    lo = state[rx[R_LASTOPENING]]
    while i < n
      openings[lo + i] = floorclip[start + i]
      i += 1
    end
    ds_botkind[ds] = RV_CLIP_OPENINGS
    ds_botbase[ds] = lo - start
    state[rx[R_LASTOPENING]] = lo + n
    if state[rx[R_LASTOPENING]] > maxopenings[0]
      core_fail(:capacity)
    end
  end
  if state[rx[R_MASKEDTEXTURE]] != 0 && (ds_silhouette[ds] & RV_SIL_TOP) == 0
    ds_silhouette[ds] = ds_silhouette[ds] | RV_SIL_TOP
    ds_tsilheight[ds] = -0x80000000
  end
  if state[rx[R_MASKEDTEXTURE]] != 0 && (ds_silhouette[ds] & RV_SIL_BOTTOM) == 0
    ds_silhouette[ds] = ds_silhouette[ds] | RV_SIL_BOTTOM
    ds_bsilheight[ds] = 0x7fffffff
  end
  state[rx[R_DS_COUNT]] += 1
  0
end

# `Renderer#clip_solid_wall_segment`
def dc_rv_clip_solid_wall_segment(ss_last, ss_first, state, rx, seg_sidedef, seg_linedef, line_flags, seg_angle,
                                  tantoangle, finesine, vertex_x, seg_v1, vertex_y, ds_curline, ds_x1, ds_x2,
                                  xtoviewangle, projection, ds_scale1, ds_scale2, ds_scalestep,
                                  sector_ceilingheight, sector_floorheight, ds_maskedbase, ds_masked,
                                  texturetranslation, side_midtexture, tex_theight, side_rowoffset, ds_silhouette,
                                  ds_topkind, ds_botkind, ds_bsilheight, ds_tsilheight, sector_ceilingpic,
                                  skyflatnum, sector_floorpic, sector_lightlevel, side_toptexture,
                                  side_bottomtexture, maxopenings, side_textureoffset, seg_offset, seg_v2,
                                  centeryfrac, pl_height, pl_picnum, pl_lightlevel, pl_minx, pl_maxx, pl_top, plw,
                                  plempty, ceilingclip, floorclip, pl_bottom, openings, finetangent, scalelight,
                                  resscale, tex_widthmask, tex_atlas_base, viewheight, jobmode, scr, cmap, atlas,
                                  wad, zonewin, centery, sw, viewwindowx, viewwindowy, wall, sc_kind, sc_idx,
                                  cap_wall, cap_sched, ds_topbase, ds_botbase, first, last)
  start = 0
  while ss_last[start] < first - 1
    start += 1
  end

  if first < ss_first[start]
    if last < ss_first[start] - 1
      dc_rv_store_wall_range(state, rx, seg_sidedef, seg_linedef, line_flags, seg_angle, tantoangle, finesine,
                             vertex_x, seg_v1, vertex_y, ds_curline, ds_x1, ds_x2, xtoviewangle, projection,
                             ds_scale1, ds_scale2, ds_scalestep, sector_ceilingheight, sector_floorheight,
                             ds_maskedbase, ds_masked, texturetranslation, side_midtexture, tex_theight,
                             side_rowoffset, ds_silhouette, ds_topkind, ds_botkind, ds_bsilheight, ds_tsilheight,
                             sector_ceilingpic, skyflatnum, sector_floorpic, sector_lightlevel, side_toptexture,
                             side_bottomtexture, maxopenings, side_textureoffset, seg_offset, seg_v2, centeryfrac,
                             pl_height, pl_picnum, pl_lightlevel, pl_minx, pl_maxx, pl_top, plw, plempty,
                             ceilingclip, floorclip, pl_bottom, openings, finetangent, scalelight, resscale,
                             tex_widthmask, tex_atlas_base, viewheight, jobmode, scr, cmap, atlas, wad, zonewin,
                             centery, sw, viewwindowx, viewwindowy, wall, sc_kind, sc_idx, cap_wall, cap_sched,
                             ds_topbase, ds_botbase, first, last)
      if state[rx[R_NEWEND]] >= RV_MAXSEGS
        core_fail(:capacity)
      end
      nx = state[rx[R_NEWEND]]
      state[rx[R_NEWEND]] += 1
      while nx != start
